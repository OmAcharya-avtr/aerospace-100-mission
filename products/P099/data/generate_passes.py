"""Generate the committed per-pass record. Deterministic, one declared seed.

WHAT IS REAL HERE AND WHAT IS NOT
---------------------------------
- **Real and published:** the orbit. The element set is catalogue object
  06251 from the official SGP4 verification file distributed with the `sgp4`
  package and originating in Vallado et al. (2006); the pass windows,
  elevations, azimuths and slant ranges are an SGP4 propagation of it.
- **Declared and synthetic:** the eight ground stations
  (:data:`passyield.dataset.STATIONS`), the spacecraft link budget
  (:data:`passyield.link.DEFAULT_BUDGET`), and the whole event timeline --
  acquisition, loss of lock, idle. No part of the timeline is a measurement of
  any real mission. ``DATASET_CARD.md`` says so in the same words.

WHY THE GENERATING MECHANISM DISAGREES WITH BASELINE 2 ON PURPOSE
-----------------------------------------------------------------
Baseline 2 assumes a homogeneous Poisson outage process, an exponential
outage duration, a Gamma idle total and independence between the three
losses. Three of those four are deliberately **false** in this generator:

- outages are an **inhomogeneous** Poisson process with intensity rising as
  ``(1/sin(elevation))**1.5`` -- harder to hold a link at low elevation --
  generated by thinning (Lewis & Shedler (1979), "Simulation of
  nonhomogeneous Poisson processes by thinning", Naval Research Logistics
  Quarterly 26(3), 403-413);
- acquisition time depends on the antenna **slew angle** from where the dish
  was last pointed and on the pass's peak elevation, so it is not an
  identically distributed draw;
- idle time is driven by the **onboard backlog**: when there is less data
  queued than the window can carry, the link runs dry and the rest of the
  pass is idle. That is a deterministic consequence of a pre-pass state
  variable, which is exactly the kind of structure a per-pass predictor could
  find and a stationary analytic model cannot.

If the generator matched baseline 2's assumptions, baseline 2 would be exact
by construction and the comparison would measure nothing. The disagreement is
the experiment.

REPRODUCIBILITY
---------------
One seed, :data:`SEED`, spawned per pass through
``numpy.random.SeedSequence`` so that the draws for a pass do not depend on
how many passes preceded it. Run from any working directory::

    python3 data/generate_passes.py

Writes ``data/passes.csv``, ``data/manifest.json`` and
``data/generate_passes_output.txt``. This script is **not** under
``validation/``, so the release gate does not run it: a generator that the
gate re-ran would overwrite the evidence the validation scripts pin.
"""

from __future__ import annotations

import sys

sys.dont_write_bytecode = True

import json  # noqa: E402
import math  # noqa: E402
import time  # noqa: E402
from pathlib import Path  # noqa: E402

import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from passyield.baselines import fit_event_model  # noqa: E402
from passyield.dataset import (  # noqa: E402
    DEFAULT_MANIFEST_PATH,
    DEFAULT_RECORD_PATH,
    STATIONS,
    PassRow,
    file_digest,
    format_intervals,
    parse_intervals,
    write_passes,
)
from passyield.decompose import PassEvents, decompose_pass  # noqa: E402
from passyield.geometry import (  # noqa: E402
    SECONDS_PER_DAY,
    TLE_LINE1,
    TLE_LINE2,
    campaign_epoch,
    find_passes,
    satellite,
    topocentric_profile,
)
from passyield.link import DEFAULT_BUDGET  # noqa: E402

#: The one declared seed for the whole campaign.
SEED = 990099

#: Campaign length, days from the element set's own epoch.
CAMPAIGN_DAYS = 60.0

#: Coarse scan step for the pass search, seconds. The scan cannot find a pass
#: shorter than this; every pass shorter than
#: :data:`MIN_BOOKABLE_DURATION_S` is discarded anyway, and that threshold is
#: twelve times the step, so the hazard does not reach the record. The
#: shortest retained pass is reported in the transcript.
COARSE_STEP_S = 5.0

#: A scheduler does not book a grazing contact. Declared threshold, seconds.
MIN_BOOKABLE_DURATION_S = 60.0

#: Onboard data accumulation, Mbit/s, between contacts. A declared design
#: value for the synthetic vehicle.
GENERATION_RATE_MBIT_S = 8.5

#: Onboard storage ceiling, Mbit. The backlog saturates here.
STORAGE_CEILING_MBIT = 240000.0

#: Per-station event parameters, all declared: base acquisition time (s),
#: outage intensity at the zenith (1/s), mean outage duration (s), protocol
#: stall scale (s). Varied across stations so that a held-out station is a
#: genuinely different regime and not a relabelling.
STATION_EVENTS: dict[str, tuple[float, float, float, float]] = {
    "GS-01": (22.0, 0.0016, 11.0, 5.0),
    "GS-02": (31.0, 0.0024, 14.5, 7.5),
    "GS-03": (44.0, 0.0035, 19.0, 11.0),
    "GS-04": (19.0, 0.0012, 9.5, 4.0),
    "GS-05": (27.0, 0.0020, 13.0, 6.5),
    "GS-06": (36.0, 0.0029, 16.5, 9.0),
    "GS-07": (24.0, 0.0018, 12.0, 5.5),
    "GS-08": (17.0, 0.0010, 8.5, 3.5),
}

#: Erlang stage count of the acquisition-time law.
ACQUISITION_STAGES = 4.0

#: Slew contribution to the mean acquisition time, s per degree.
SLEW_SECONDS_PER_DEGREE = 0.10

#: Low-elevation penalty on the mean acquisition time, seconds, scaled by
#: ``1/sin(peak elevation) - 1``.
LOW_ELEVATION_ACQUISITION_S = 14.0

#: Exponent of the elevation dependence of the outage intensity.
OUTAGE_ELEVATION_EXPONENT = 1.5

#: Erlang stage count of the protocol-stall idle law.
STALL_STAGES = 2.0

#: Where the dish is parked before its first contact, degrees azimuth.
PARKED_AZIMUTH_DEG = 180.0


def angular_separation_deg(first: float, second: float) -> float:
    """Shortest angle between two azimuths, degrees, in ``[0, 180]``."""
    difference = abs(first - second) % 360.0
    return difference if difference <= 180.0 else 360.0 - difference


def thinned_outages(
    rng: np.random.Generator,
    offsets_s: np.ndarray,
    elevation_deg: np.ndarray,
    duration_s: float,
    zenith_intensity: float,
    mean_duration_s: float,
) -> tuple[tuple[float, float], ...]:
    """Outages of an inhomogeneous Poisson process, by thinning.

    Intensity ``lambda(t) = zenith_intensity * (1/sin(el(t)))**exponent``.
    Candidates are drawn from a homogeneous process at the supremum intensity
    and kept with probability ``lambda(t)/lambda_max`` (Lewis & Shedler 1979).
    Durations are exponential and clipped to the remainder of the window, so
    an outage can never run past mask set.
    """
    sine = np.sin(np.radians(np.clip(elevation_deg, 1.0e-6, 90.0)))
    intensity = zenith_intensity * np.power(1.0 / sine, OUTAGE_ELEVATION_EXPONENT)
    supremum = float(intensity.max())
    if supremum <= 0.0:
        return ()
    count = int(rng.poisson(supremum * duration_s))
    if count == 0:
        return ()
    candidates = np.sort(rng.uniform(0.0, duration_s, size=count))
    keep = rng.uniform(0.0, 1.0, size=count) < (
        np.interp(candidates, offsets_s, intensity) / supremum
    )
    starts = candidates[keep]
    if starts.size == 0:
        return ()
    lengths = rng.exponential(mean_duration_s, size=starts.size)
    lengths = np.minimum(lengths, np.maximum(duration_s - starts, 0.0))
    return tuple(
        (float(start), float(length))
        for start, length in zip(starts, lengths, strict=True)
        if length > 0.0
    )


def main() -> int:
    """Build the campaign and write the record, the manifest and a transcript."""
    started = time.perf_counter()
    lines: list[str] = []

    def say(text: str = "") -> None:
        for line in str(text).splitlines() or [""]:
            lines.append(line)
            print(line)

    say("P099 PassYield -- per-pass campaign generator")
    say("")
    say(f"seed: {SEED}")
    say(f"campaign days from the element-set epoch: {CAMPAIGN_DAYS!r}")
    say(f"coarse scan step, s: {COARSE_STEP_S!r}")
    say(f"minimum bookable pass duration, s: {MIN_BOOKABLE_DURATION_S!r}")
    say(f"onboard generation rate, Mbit/s: {GENERATION_RATE_MBIT_S!r}")
    say(f"rate ceiling R_max = B * eta_max, Mbit/s: {DEFAULT_BUDGET.max_rate_mbit_s!r}")
    say("")
    say("element set, verbatim from the sgp4 package's SGP4-VER.TLE:")
    say(f"  {TLE_LINE1}")
    say(f"  {TLE_LINE2}")
    say("")
    say("stations: eight SYNTHETIC sites. Declared placements and declared design")
    say("figures, not measurements of any real ground station.")

    satrec = satellite()
    epoch_jd, epoch_fr = campaign_epoch(satrec)

    say("")
    say("--- pass search -------------------------------------------------------")
    windows: list[tuple[float, object]] = []
    for station in STATIONS:
        found = find_passes(
            satrec, station, epoch_jd, epoch_fr, CAMPAIGN_DAYS, coarse_step_s=COARSE_STEP_S
        )
        bookable = [item for item in found if item.duration_s >= MIN_BOOKABLE_DURATION_S]
        say(
            f"{station.name}: {len(found)} windows above the {station.mask_deg!r} degree mask, "
            f"{len(bookable)} at or above the bookable threshold"
        )
        for item in bookable:
            windows.append((item.rise_jd + item.rise_fr, item))
    windows.sort(key=lambda entry: entry[0])
    say("")
    say(f"bookable passes in the campaign: {len(windows)}")
    if not windows:
        say("FAILED: no bookable passes; nothing to write")
        return 1
    say(f"shortest retained pass, s: {min(item.duration_s for _t, item in windows):.3f}")
    say(f"longest retained pass, s : {max(item.duration_s for _t, item in windows):.3f}")

    sequence = np.random.SeedSequence(SEED)
    children = sequence.spawn(len(windows))
    backlog = 60000.0
    previous_time = windows[0][0]
    last_azimuth = {station.name: PARKED_AZIMUTH_DEG for station in STATIONS}
    last_contact = {station.name: None for station in STATIONS}
    previous_outages = {station.name: 0 for station in STATIONS}
    by_name = {station.name: station for station in STATIONS}

    rows: list[PassRow] = []
    say("")
    say("--- event draws and decomposition -------------------------------------")
    for index, ((absolute, window), child) in enumerate(zip(windows, children, strict=True)):
        station = by_name[window.station]
        rng = np.random.default_rng(child)

        backlog = min(
            STORAGE_CEILING_MBIT,
            backlog + GENERATION_RATE_MBIT_S * (absolute - previous_time) * SECONDS_PER_DAY,
        )
        previous_time = absolute
        backlog_before = backlog

        base_acquisition, zenith_intensity, mean_outage, stall_scale = STATION_EVENTS[station.name]
        nodes = 129
        offsets = np.linspace(0.0, window.duration_s, nodes)
        elevation, azimuth, _slant = topocentric_profile(satrec, station, window, offsets)
        rise_azimuth = float(azimuth[0])
        slew = angular_separation_deg(last_azimuth[station.name], rise_azimuth)
        last_azimuth[station.name] = float(azimuth[-1])

        peak = math.radians(max(float(window.max_elevation_deg), 1.0))
        mean_acquisition = (
            base_acquisition
            + SLEW_SECONDS_PER_DEGREE * slew
            + LOW_ELEVATION_ACQUISITION_S * (1.0 / math.sin(peak) - 1.0)
        )
        acquisition = float(
            rng.gamma(ACQUISITION_STAGES, mean_acquisition / ACQUISITION_STAGES)
        )

        outages = thinned_outages(
            rng, offsets, elevation, float(window.duration_s), zenith_intensity, mean_outage
        )

        # Idle: a protocol-stall component plus, when the backlog cannot fill
        # the window, the dry time at the end of the pass.
        stalls = float(rng.gamma(STALL_STAGES, stall_scale))
        idle: list[tuple[float, float]] = []
        if stalls > 0.0:
            start = float(rng.uniform(acquisition, max(acquisition, window.duration_s)))
            idle.append((min(start, window.duration_s), stalls))
        events = PassEvents(
            acquisition_s=acquisition,
            resync_intervals_s=outages,
            idle_intervals_s=tuple(idle),
        )
        first = decompose_pass(satrec, station, window, events)
        # The dry time is a function of the capacity actually available, so it
        # needs the first decomposition. If the backlog cannot fill what the
        # active time could carry, the link runs dry and the tail of the pass
        # is idle; the pass is then decomposed again with that interval added.
        deliverable = first.realised_bits
        if backlog_before < deliverable and deliverable > 0.0:
            unused_fraction = 1.0 - backlog_before / deliverable
            dry = unused_fraction * first.active_duration_s
            dry_start = max(0.0, float(window.duration_s) - dry)
            idle.append((dry_start, dry))
            events = PassEvents(
                acquisition_s=acquisition,
                resync_intervals_s=outages,
                idle_intervals_s=tuple(idle),
            )
            decomposition = decompose_pass(satrec, station, window, events)
        else:
            decomposition = first

        backlog = max(0.0, backlog_before - decomposition.realised_bits)

        hours_since = (
            24.0 * (absolute - last_contact[station.name])
            if last_contact[station.name] is not None
            else 0.0
        )
        last_contact[station.name] = absolute
        prior = previous_outages[station.name]
        previous_outages[station.name] = len(outages)

        campaign_hour = 24.0 * (absolute - (epoch_jd + epoch_fr))
        local_hour = (
            24.0 * ((absolute + 0.5 + station.longitude_deg / 360.0) % 1.0)
        )

        rows.append(
            PassRow(
                pass_id=index,
                station=station.name,
                rise_jd=float(window.rise_jd),
                rise_fr=float(window.rise_fr),
                campaign_hour=float(campaign_hour),
                local_hour=float(local_hour),
                duration_s=float(window.duration_s),
                max_elevation_deg=float(window.max_elevation_deg),
                min_slant_range_km=float(window.min_slant_range_km),
                rise_azimuth_deg=rise_azimuth,
                slew_angle_deg=float(slew),
                backlog_mbit=float(backlog_before),
                hours_since_last_contact=float(hours_since),
                prior_pass_outage_count=int(prior),
                acquisition_s=acquisition,
                outage_count=len(outages),
                resync_intervals=format_intervals(events.resync_intervals_s),
                idle_intervals=format_intervals(events.idle_intervals_s),
                nominal_mbit=decomposition.nominal_bits,
                capacity_mbit=decomposition.capacity_bits,
                realised_mbit=decomposition.realised_bits,
                shortfall_mbit=decomposition.shortfall_bits,
                geometry_mbit=decomposition.geometry_bits,
                acquisition_mbit=decomposition.acquisition_bits,
                resync_mbit=decomposition.resync_bits,
                idle_mbit=decomposition.idle_bits,
                residual_mbit=decomposition.residual_bits,
            )
        )
        if (index + 1) % 250 == 0:
            say(f"  decomposed {index + 1} of {len(windows)} passes")

    write_passes(rows, DEFAULT_RECORD_PATH)
    digest = file_digest(DEFAULT_RECORD_PATH)
    size = DEFAULT_RECORD_PATH.stat().st_size

    realised = np.asarray([row.realised_mbit for row in rows])
    capacity = np.asarray([row.capacity_mbit for row in rows])
    nominal = np.asarray([row.nominal_mbit for row in rows])
    shortfall = np.asarray([row.shortfall_mbit for row in rows])
    residual = np.asarray([row.residual_mbit for row in rows])
    truncated = sum(1 for row in rows if row.acquisition_s > row.duration_s)

    model = fit_event_model(
        acquisition_s=[row.acquisition_s for row in rows],
        outage_counts=[row.outage_count for row in rows],
        window_durations_s=[row.duration_s for row in rows],
        outage_durations_s=[
            duration
            for row in rows
            for _start, duration in parse_intervals(row.resync_intervals)
        ],
        idle_totals_s=[row.idle_total_s for row in rows],
    )

    say("")
    say("--- record ------------------------------------------------------------")
    say(f"passes written            : {len(rows)}")
    say(f"record, bytes             : {size}")
    say(f"record, SHA-256           : {digest}")
    say(f"stations                  : {sorted({row.station for row in rows})}")
    say(f"campaign nominal, Mbit    : {nominal.sum():.6g}")
    say(f"campaign capacity, Mbit   : {capacity.sum():.6g}")
    say(f"campaign realised, Mbit   : {realised.sum():.6g}")
    say(f"campaign shortfall, Mbit  : {shortfall.sum():.6g}")
    say(f"realised / capacity       : {realised.sum() / capacity.sum():.6f}")
    say(f"realised / nominal        : {realised.sum() / nominal.sum():.6f}")
    say(f"max |residual|, Mbit      : {np.max(np.abs(residual)):.6e}")
    say(f"max |residual| / shortfall: {np.max(np.abs(residual / shortfall)):.6e}")
    say(f"passes with acquisition longer than the pass: {truncated}")
    say("")
    say("--- event model fitted from the record (method of moments) ------------")
    say(f"acquisition Gamma shape        : {model.acquisition_shape:.6f}")
    say(f"acquisition Gamma scale, s     : {model.acquisition_scale:.6f}")
    say(f"outage intensity, 1/s          : {model.outage_intensity_per_s:.8f}")
    say(f"mean outage duration, s        : {model.outage_mean_s:.6f}")
    say(f"idle Gamma shape               : {model.idle_shape:.6f}")
    say(f"idle Gamma scale, s            : {model.idle_scale:.6f}")
    say(f"passes the moments came from   : {model.sample_passes}")

    manifest = {
        "product": "P099",
        "package": "passyield",
        "seed": SEED,
        "campaign_days": CAMPAIGN_DAYS,
        "coarse_step_s": COARSE_STEP_S,
        "min_bookable_duration_s": MIN_BOOKABLE_DURATION_S,
        "generation_rate_mbit_s": GENERATION_RATE_MBIT_S,
        "storage_ceiling_mbit": STORAGE_CEILING_MBIT,
        "tle_line1": TLE_LINE1,
        "tle_line2": TLE_LINE2,
        "stations": [station.name for station in STATIONS],
        "passes": len(rows),
        "record_relative_path": "data/passes.csv",
        "record_bytes": size,
        "record_sha256": digest,
        "campaign_nominal_mbit": float(nominal.sum()),
        "campaign_capacity_mbit": float(capacity.sum()),
        "campaign_realised_mbit": float(realised.sum()),
        "campaign_shortfall_mbit": float(shortfall.sum()),
        "max_abs_residual_mbit": float(np.max(np.abs(residual))),
        "fitted_event_model": {
            "acquisition_shape": model.acquisition_shape,
            "acquisition_scale_s": model.acquisition_scale,
            "outage_intensity_per_s": model.outage_intensity_per_s,
            "outage_mean_s": model.outage_mean_s,
            "idle_shape": model.idle_shape,
            "idle_scale_s": model.idle_scale,
            "sample_passes": model.sample_passes,
        },
    }
    DEFAULT_MANIFEST_PATH.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    say("")
    say(f"wrote data/passes.csv and data/manifest.json in {time.perf_counter() - started:.1f} s")
    say("this elapsed time is a build note, not an asserted quantity: no test and no")
    say("validation script in this product compares two wall-clock measurements.")
    transcript = ROOT / "data" / "generate_passes_output.txt"
    if transcript.exists():
        transcript.unlink()
    transcript.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
