"""Deterministic synthetic data and a deterministic trained reference model.

The dataset is a three-class, eight-feature Gaussian-blob problem generated by
``sklearn.datasets.make_classification`` with a fixed seed, standardised to zero
mean and unit variance on the training split. It carries no physical meaning:
it exists so that an inference pipeline exists to damage, and so that the
degradation metric has something to degrade. Nothing in this product's claims
depends on the dataset being realistic; see ``DATASET_CARD.md``.

Splits, fixed by seed:

* ``train``       - fits the classifier.
* ``calibration`` - measures the per-bit ground-truth degradation used as the
  learned predictor's training target, and supplies the activation statistics
  used as predictor features.
* ``evaluation``  - measures the degradation that every method, baselines and
  learned alike, is finally scored on.

The calibration and evaluation splits are disjoint, so the metric reported for
the learned predictor is not measured on the data its targets came from.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from sklearn.datasets import make_classification
from sklearn.neural_network import MLPClassifier

from .network import MlpParameters, from_sklearn

N_FEATURES = 8
N_CLASSES = 3
N_HIDDEN = 12
DEFAULT_SEED = 20261005


@dataclass(frozen=True)
class SplitData:
    """One feature/label split. ``x`` is ``(n, N_FEATURES)``, ``y`` is ``(n,)``."""

    x: np.ndarray
    y: np.ndarray

    @property
    def n_samples(self) -> int:
        return int(self.x.shape[0])


@dataclass(frozen=True)
class Problem:
    """The three splits plus the standardisation fitted on the training split."""

    train: SplitData
    calibration: SplitData
    evaluation: SplitData
    feature_mean: np.ndarray
    feature_scale: np.ndarray
    seed: int


def make_problem(
    n_train: int = 900,
    n_calibration: int = 300,
    n_evaluation: int = 300,
    seed: int = DEFAULT_SEED,
) -> Problem:
    """Generate the synthetic problem deterministically.

    Parameters
    ----------
    n_train, n_calibration, n_evaluation:
        Split sizes. Defaults are sized so that the whole criticality sweep
        fits the compute budget documented in the README.
    seed:
        Passed to ``make_classification`` and to the shuffling; the same seed
        reproduces the same arrays bit for bit on the same numpy version.
    """
    for name, value in (
        ("n_train", n_train),
        ("n_calibration", n_calibration),
        ("n_evaluation", n_evaluation),
    ):
        if value <= 0:
            raise ValueError(f"{name} must be > 0, got {value}")
    total = n_train + n_calibration + n_evaluation
    x, y = make_classification(
        n_samples=total,
        n_features=N_FEATURES,
        n_informative=5,
        n_redundant=1,
        n_repeated=0,
        n_classes=N_CLASSES,
        n_clusters_per_class=2,
        class_sep=1.4,
        flip_y=0.01,
        random_state=seed,
        shuffle=True,
    )
    x = np.asarray(x, dtype=np.float64)
    y = np.asarray(y, dtype=np.int64)

    train_x, train_y = x[:n_train], y[:n_train]
    mean = train_x.mean(axis=0)
    scale = train_x.std(axis=0)
    scale[scale == 0.0] = 1.0

    def standardise(block: np.ndarray) -> np.ndarray:
        return (block - mean) / scale

    cal_slice = slice(n_train, n_train + n_calibration)
    eval_slice = slice(n_train + n_calibration, total)
    return Problem(
        train=SplitData(standardise(train_x), train_y),
        calibration=SplitData(standardise(x[cal_slice]), y[cal_slice]),
        evaluation=SplitData(standardise(x[eval_slice]), y[eval_slice]),
        feature_mean=mean,
        feature_scale=scale,
        seed=seed,
    )


def train_reference_model(
    problem: Problem, seed: int = DEFAULT_SEED, max_iter: int = 3000
) -> MLPClassifier:
    """Fit the one-hidden-layer MLP that the upset campaigns damage.

    Fixed ``random_state``, Adam, ReLU, ``tol=1e-4``. Reaches the stopping
    criterion (no ``ConvergenceWarning``) in 1130 iterations and about 2 s on
    one contended core; the measured figure is in the README compute budget.
    """
    clf = MLPClassifier(
        hidden_layer_sizes=(N_HIDDEN,),
        activation="relu",
        solver="adam",
        alpha=1e-3,
        learning_rate_init=3e-3,
        max_iter=max_iter,
        random_state=seed,
        tol=1e-4,
        n_iter_no_change=15,
    )
    clf.fit(problem.train.x, problem.train.y)
    return clf


def reference_parameters(problem: Problem, seed: int = DEFAULT_SEED) -> MlpParameters:
    """Train and pack into a float32 bit-addressable parameter block."""
    return from_sklearn(train_reference_model(problem, seed=seed), itemsize_bytes=4)
