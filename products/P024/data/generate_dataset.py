"""Regenerate the synthetic training dataset used by the learned gain scheduler.

**No flight telemetry is used anywhere in this package.**  Everything this
script writes is produced by ``detumblesim.scenarios.sample_scenario`` and the
simulator, both of which are deterministic in their seeds, so the dataset is
reproducible bit-for-bit from this file alone.  See ``DATASET_CARD.md``.

    python data/generate_dataset.py [--n 20] [--seed0 1000] [--out data/]

Writes
------
``training_scenarios.csv``  one row per scenario: seed, inertia, initial rate,
                            orbit elements, dipole limit, oracle gain, cost
``training_features.csv``   the feature/label matrix the RandomForest is fitted
                            on, one row per harvested control-step window
``dataset_manifest.txt``    row counts, seeds, and a SHA-256 of each CSV
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from detumblesim.evaluate import oracle_gain, run_policy, training_rows  # noqa: E402
from detumblesim.features import FEATURE_NAMES  # noqa: E402
from detumblesim.policies import FixedGainPolicy  # noqa: E402
from detumblesim.scenarios import sample_scenarios  # noqa: E402

GAIN_GRID = np.geomspace(1.0e4, 1.0e6, 8)
SIM = {"duration_s": 23000.0, "control_dt_s": 2.0, "substeps": 1}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--n", type=int, default=20, help="number of scenarios")
    ap.add_argument("--seed0", type=int, default=1000, help="first scenario seed")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent)
    args = ap.parse_args(argv)
    if args.n < 3:
        raise SystemExit("--n must be at least 3 (the power-law fit needs three points)")
    args.out.mkdir(parents=True, exist_ok=True)

    scenarios = sample_scenarios(args.n, args.seed0)
    grid = np.empty((args.n, GAIN_GRID.size))
    best = np.empty(args.n)
    for i, s in enumerate(scenarios):
        bg, _, costs = oracle_gain(s, GAIN_GRID, **SIM)
        grid[i] = costs
        best[i] = bg
    k_fixed = float(GAIN_GRID[int(np.argmin(grid.mean(axis=0)))])

    scen_path = args.out / "training_scenarios.csv"
    with open(scen_path, "w", encoding="utf-8") as fh:
        fh.write(
            "seed,ixx_kgm2,iyy_kgm2,izz_kgm2,rate0_deg_s,altitude_km,inclination_deg,"
            "raan_deg,arg_lat0_deg,gmst0_rad,max_dipole_am2,oracle_gain,oracle_cost\n"
        )
        for s, bg, row in zip(scenarios, best, grid, strict=True):
            d = np.diag(s.inertia)
            fh.write(
                f"{s.seed},{d[0]:.9e},{d[1]:.9e},{d[2]:.9e},"
                f"{np.degrees(s.rate0_rad_s):.9e},{s.orbit.altitude_km:.6f},"
                f"{s.orbit.inclination_deg:.6f},{s.orbit.raan_deg:.6f},"
                f"{s.orbit.arg_lat0_deg:.6f},{s.orbit.gmst0_rad:.9f},"
                f"{float(s.magnetorquer.max_dipole_am2[0]):.9e},{bg:.9e},"
                f"{row.min():.9e}\n"
            )

    xs, ys, seeds = [], [], []
    for s, bg in zip(scenarios, best, strict=True):
        res, _ = run_policy(s, FixedGainPolicy(k_fixed), **SIM)
        x, y = training_rows(s, float(bg), k_fixed, res)
        if x.size:
            xs.append(x)
            ys.append(y)
            seeds.append(np.full(x.shape[0], s.seed))
    x = np.vstack(xs)
    y = np.concatenate(ys)
    seed_col = np.concatenate(seeds)

    feat_path = args.out / "training_features.csv"
    with open(feat_path, "w", encoding="utf-8") as fh:
        fh.write("seed," + ",".join(FEATURE_NAMES) + ",label_log10_gain_ratio\n")
        for sd, row, lab in zip(seed_col, x, y, strict=True):
            fh.write(f"{sd}," + ",".join(f"{v:.9e}" for v in row) + f",{lab:.9e}\n")

    manifest = args.out / "dataset_manifest.txt"
    with open(manifest, "w", encoding="utf-8") as fh:
        fh.write("DetumbleSim synthetic training dataset\n")
        fh.write("Generated by data/generate_dataset.py; no flight telemetry is used.\n")
        fh.write(f"scenarios          : {args.n} (seeds {args.seed0}"
                 f"-{args.seed0 + args.n - 1})\n")
        fh.write(f"gain grid          : {np.array2string(GAIN_GRID, precision=6)}\n")
        fh.write(f"simulation settings: {SIM}\n")
        fh.write(f"tuned fixed gain   : {k_fixed:.9e} A m^2 s / T\n")
        fh.write(f"feature rows       : {x.shape[0]} x {x.shape[1]}\n")
        fh.write(f"label range        : [{y.min():.9e}, {y.max():.9e}] dex\n")
        fh.write(f"training_scenarios.csv sha256 = {sha256(scen_path)}\n")
        fh.write(f"training_features.csv  sha256 = {sha256(feat_path)}\n")

    print(f"wrote {scen_path} ({args.n} rows)")
    print(f"wrote {feat_path} ({x.shape[0]} rows x {x.shape[1]} features)")
    print(f"wrote {manifest}")
    print(f"tuned fixed gain = {k_fixed:.6e} A m^2 s / T")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
