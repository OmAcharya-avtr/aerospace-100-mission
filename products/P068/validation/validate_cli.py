"""The command line interface, exercised end to end.

Every command quoted in README.md is run here and its output captured, so a
change to the CLI that breaks a documented invocation fails this script rather
than being discovered by a reader.
"""

from __future__ import annotations

import contextlib
import io
import tempfile
from pathlib import Path

from _bootstrap import Tee, add_src_to_path, environment_lines

ROOT = add_src_to_path()

from degradepredict.__main__ import main as cli_main  # noqa: E402

OUT = ROOT / "validation" / "validate_cli_output.txt"


def run(say: Tee, argv: list[str], redact: str | None = None) -> int:
    """Run one CLI invocation and record it.

    ``redact`` replaces a temporary-directory path with ``<tmpdir>`` so the
    committed output does not change between runs for a reason that has nothing
    to do with the code.
    """
    shown = [a.replace(redact, "<tmpdir>") if redact else a for a in argv]
    say("")
    say(f"$ python -m degradepredict {' '.join(shown)}")
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        code = cli_main(argv)
    text = buf.getvalue().rstrip("\n")
    if redact:
        text = text.replace(redact, "<tmpdir>")
    say(text)
    say(f"[exit {code}]")
    return code


def main() -> int:
    say = Tee(OUT)
    say("validate_cli.py -- every documented CLI invocation, executed")
    for line in environment_lines():
        say(line)

    codes = []
    say.rule("1. fit: the three analytic baselines on one trajectory")
    codes.append(run(say, ["fit", "--index", "0", "--seed", "20261017"]))

    say.rule("2. generate: a reproducible population as CSV")
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "population.csv"
        codes.append(run(say, ["generate", "--n", "25", "--seed", "20261016",
                               "--out", str(path)], redact=tmp))
        first = path.read_text()
        codes.append(run(say, ["generate", "--n", "25", "--seed", "20261016",
                               "--out", str(path)], redact=tmp))
        identical = first == path.read_text()
        say("")
        say(f"byte-identical on a second run with the same seed: {identical}")
        header = first.splitlines()[0]
        say(f"header: {header}")
        say(f"rows  : {len(first.splitlines()) - 1}")
        size_kb = len(first.encode()) / 1024.0
        say(f"size  : {size_kb:.1f} kB for 25 trajectories; the committed data set is")
        say("        regenerated by this command rather than stored.")

    say.rule("3. benchmark: the head-to-head table")
    codes.append(run(say, ["benchmark", "--n-train", "600", "--n-test", "200",
                           "--seed", "20261016"]))
    say("")
    say("this invocation uses a smaller train set than validate_headtohead.py, so")
    say("its numbers differ from the headline table; the headline numbers come")
    say("from validate_headtohead_output.txt.")

    say.rule("4. rejected input")
    say("")
    say("$ python -m degradepredict fit --level 1.5")
    try:
        cli_main(["fit", "--level", "1.5"])
    except SystemExit as exc:
        say(f"SystemExit({exc.code}) -- argparse error: --level must be in (0, 1)")

    say.rule("summary")
    say(f"documented invocations run : {len(codes)}")
    say(f"non-zero exit codes        : {sum(1 for c in codes if c != 0)}")
    say(f"generation reproducible    : {identical}")
    path = say.save()
    print(f"\nwrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
