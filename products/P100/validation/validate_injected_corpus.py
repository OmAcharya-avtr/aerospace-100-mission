def statistical(out: _bootstrap.Tee, name: str, passed: bool, detail: str = "") -> None:
    """Record a check whose verdict depends on a finite random sample.

    On the fast path the sample is two orders of magnitude smaller and a 95 per
    cent interval over it means nothing, so these checks are recorded as
    UNAVAILABLE rather than evaluated. The fast path exists only to answer
    whether a script RUNS -- ``probe_working_directories.py`` uses it, and a
    stochastic pass or fail would make that probe report a sampling outcome as
    a working-directory defect. No number from the fast path is reported
    anywhere.
    """
    if _bootstrap.FAST:
        out.unavailable(
            name, "fast path: the sample is too small for this interval to mean anything"
        )
        return
    out.check(name, passed, detail)

