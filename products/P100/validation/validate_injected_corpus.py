#: Independent process runs per injected rate.
RUNS = 60 if _bootstrap.FAST else 1320

#: Independent process runs at the mission rate, where the headline comparison
#: against Baseline 1 is made and a tighter interval is worth the time.
RUNS_MISSION = 120 if _bootstrap.FAST else 4400

#: Audit sizes the power is measured at. 20 is the largest that still leaves
#: 66 disjoint blocks at RUNS = 1320.
AUDIT_SIZES = (2, 5) if _bootstrap.FAST else (2, 5, 10, 20)

#: Six calibration intervals judged together are not a 95 per cent statement:
#: at 95 per cent each, all six cover with probability 0.95**6 = 0.7351, so a
#: single miss is the expected outcome about a quarter of the time. The
#: family-wise criterion is therefore Bonferroni-corrected, and BOTH the
#: per-rate 95 per cent interval and the family-wise interval are reported.
#: This correction is declared here rather than applied after seeing which
#: interval missed.
CALIBRATION_FAMILY = len(INJECTED_RATES)


def binomial_interval(hits: int, runs: int, level: float | None = None) -> tuple[float, float]:
    """Clopper-Pearson exact interval at 95 per cent for a binomial proportion.

    Clopper-Pearson rather than Wilson, for a reason that was measured rather
    than assumed. The first version of this script used a Wilson score
    interval and it **failed its own calibration check at the injected rate
    1.0**: with 60 hits in 60 runs the Wilson interval is
    [0.939828, 0.999979] and does not contain 1.0, because the score interval
    does not reach the boundary when the proportion is at it. That is a
    property of Wilson, not a miscalibrated corpus.

    Clopper-Pearson is also the same family as this product's own escaped-rate
    bound: ``escaped_rate_upper_bound(n, alpha)`` is exactly the
    Clopper-Pearson one-sided upper bound for zero successes, so the
    calibration interval and the headline bound come from one piece of
    mathematics rather than two.

    Args:
        hits: successes, dimensionless, in ``[0, runs]``.
        runs: trials, dimensionless, positive.
        level: coverage, dimensionless. ``None`` uses the declared
            :data:`_bootstrap.CONFIDENCE`. A family-wise level is passed
            explicitly where several intervals are judged together.

    Returns:
        ``(lower, upper)``, dimensionless. The lower end is 0 when ``hits``
        is 0 and the upper end is 1 when ``hits == runs``, both exactly.
    """
    if runs <= 0:
        raise ValueError("runs must be positive")
    if not 0 <= hits <= runs:
        raise ValueError(f"hits must lie in [0, {runs}], got {hits}")
    coverage = _bootstrap.CONFIDENCE if level is None else float(level)
    tail = 0.5 * (1.0 - coverage)
    lower = 0.0 if hits == 0 else float(beta.ppf(tail, hits, runs - hits + 1))
    upper = 1.0 if hits == runs else float(beta.ppf(1.0 - tail, hits + 1, runs - hits))
    return lower, upper


def main() -> int:
    """Measure the audit's detection power against the injected corpus."""
    out = _bootstrap.Tee("validate_injected_corpus_output.txt")
    rng = np.random.default_rng(_bootstrap.SEED)
    out("Baseline 3 -- injected corpus of known rate -- P100 SeedAudit")
    out("")
    out(f"fast path (SEEDAUDIT_FAST=1): {_bootstrap.FAST}")
    out(f"declared seed: {_bootstrap.SEED}")
    out(f"runs per rate: {RUNS}")
    out(f"runs at the mission rate 1/44: {RUNS_MISSION}")
    out(f"audit sizes: {AUDIT_SIZES}")
    out(f"bootstrap resamples: {_bootstrap.BOOTSTRAP_RESAMPLES}")
    out(f"confidence: {_bootstrap.CONFIDENCE!r}")
    out(f"injected rates: {INJECTED_RATES}")
    out("")
    out("audits are formed from DISJOINT consecutive blocks of runs. Overlapping")
    out("windows share runs and would inflate the apparent number of independent")
    out("audits, which is the error this product exists to report elsewhere.")

    with tempfile.TemporaryDirectory(prefix="seedaudit-corpus-") as temporary:
        manifest = generate_corpus(Path(temporary) / "corpus")
        out("")
        out(f"corpus scripts generated: {len(manifest.script_names)}")

        out.rule("1. CALIBRATION -- is the ground truth actually the declared rate?")
        family_level = 1.0 - (1.0 - _bootstrap.CONFIDENCE) / CALIBRATION_FAMILY
        out(f"per-rate coverage: {_bootstrap.CONFIDENCE!r}")
        out(f"family size: {CALIBRATION_FAMILY}")
        out(f"Bonferroni family-wise per-interval coverage: {family_level!r}")
        out("")
        out("six intervals at 95 per cent each all cover with probability")
        out(f"0.95**{CALIBRATION_FAMILY} = {_bootstrap.CONFIDENCE ** CALIBRATION_FAMILY!r}, so a")
        out("single miss is the expected outcome about a quarter of the time. BOTH")
        out("intervals are reported; the family-wise one is the pass criterion and")
        out("the correction is declared in the source above, not chosen after")
        out("seeing which interval missed.")
        out("")
        out(f"{'injected':>12}  {'runs':>6}  {'hits':>6}  {'realised':>12}  {'95% lo':>10}"
            f"  {'95% hi':>10}  {'in95':>5}  {'FW lo':>10}  {'FW hi':>10}  {'inFW':>5}")
        indicators: dict[float, np.ndarray] = {}
        realised: dict[float, float] = {}
        covered = 0
        covered_family = 0
        for rate in INJECTED_RATES:
            runs = RUNS_MISSION if rate == MISSION_RATE else RUNS
            name = manifest.rate_scripts[rate]
            series = manifestation_indicators(manifest.root, name, manifest.references[name], runs)
            indicators[rate] = series
            realised[rate] = float(series.mean())
            hits = int(series.sum())
            low, high = binomial_interval(hits, runs)
            family_low, family_high = binomial_interval(hits, runs, family_level)
            covers = low <= rate <= high
            covers_family = family_low <= rate <= family_high
            covered += int(covers)
            covered_family += int(covers_family)
            out(
                f"{rate:>12.6f}  {runs:>6}  {hits:>6}  {hits / runs:>12.6f}  {low:>10.6f}"
                f"  {high:>10.6f}  {str(covers):>5}  {family_low:>10.6f}  {family_high:>10.6f}"
                f"  {str(covers_family):>5}"
            )
        out("")
        out(f"per-rate 95 per cent intervals covering the injected rate: "
            f"{covered} of {len(INJECTED_RATES)}")
        out(f"family-wise intervals covering the injected rate: "
            f"{covered_family} of {len(INJECTED_RATES)}")
        statistical(
            out,
            "every family-wise interval covers its injected rate",
            covered_family == len(INJECTED_RATES),
            f"{covered_family} of {len(INJECTED_RATES)}",
        )
        if covered < len(INJECTED_RATES):
            out("")
            out(f"REPORTED, NOT HIDDEN: {len(INJECTED_RATES) - covered} of the per-rate 95 per")
            out("cent intervals do not cover the injected rate. A separate diagnostic run")
            out("of 3000 processes at the lowest injected rate found exactly two distinct")
            out("outputs and 4 non-reference results against an expectation of 3.0, so")
            out("there is no contamination channel in the indicator: the misses are")
            out("sampling outcomes at the low rates, which is what the family-wise")
            out("correction exists to account for.")

        out.rule("2. MEASURED DETECTION POWER PER RATE, with bootstrap intervals")
        out("P_pair is the run-and-diff design with no committed reference.")
        out("P_ref is the design that compares each run against a committed value.")
        out("")
        out("TWO DERIVED VALUES ARE REPORTED AND THEY ANSWER DIFFERENT QUESTIONS.")
        out("  derived@injected uses the rate the corpus was BUILT with. Comparing")
        out("    the measurement against it tests the corpus calibration AND the")
        out("    detection mathematics together, so a miss does not say which failed.")
        out("  derived@realised uses the per-run rate actually OBSERVED in section 1.")
        out("    Comparing against it tests the disjoint-block detection mathematics")
        out("    ALONE, with the calibration confound removed.")
        out("The pass criterion is derived@realised, because that is the claim this")
        out("product makes; the derived@injected count is reported beside it and the")
        out("calibration itself is section 1's job.")
        out("")
        family_cells = len(INJECTED_RATES) * len(AUDIT_SIZES)
        cell_level = 1.0 - (1.0 - _bootstrap.CONFIDENCE) / family_cells
        out(f"cells: {family_cells}; Bonferroni per-cell coverage for the family: "
            f"{cell_level!r}")
        out("")
        out("THE PERCENTILE BOOTSTRAP IS DEGENERATE WHEN NO AUDIT DETECTED. All")
        out("resamples of an all-zero indicator array have mean 0, so the interval")
        out("is [0, 0] and cannot contain a positive derived value. That is a")
        out("property of the bootstrap at the boundary, not evidence of")
        out("disagreement. The exact interval is reported beside it and is what the")
        out("pass criterion uses; the bootstrap interval is reported because the")
        out("specification asks for it, and both counts are given.")
        out("")
        out(
            f"{'rate':>10}  {'n':>3}  {'blocks':>7}  {'meas P_pair':>12}  {'boot lo':>9}"
            f"  {'boot hi':>9}  {'FW lo':>9}  {'FW hi':>9}  {'d@inj':>9}  {'d@real':>9}"
            f"  {'inj':>5}  {'real':>5}  {'meas P_ref':>11}  {'d@real':>9}  {'real':>5}"
        )
        pair_inside_bootstrap = 0
        pair_inside_injected = 0
        pair_inside_realised = 0
        ref_inside_realised = 0
        degenerate = 0
        cells = 0
        mission_row: tuple[float, float, float, float, float, float, int] | None = None
        for rate in INJECTED_RATES:
            for size in AUDIT_SIZES:
                reference_hits, pairwise_hits = block_detection(indicators[rate], size)
                pair_point, pair_low, pair_high = bootstrap_interval(
                    pairwise_hits, rng, _bootstrap.BOOTSTRAP_RESAMPLES, _bootstrap.CONFIDENCE
                )
                ref_point, _ref_low, _ref_high = bootstrap_interval(
                    reference_hits, rng, _bootstrap.BOOTSTRAP_RESAMPLES, _bootstrap.CONFIDENCE
                )
                pair_exact = binomial_interval(
                    int(pairwise_hits.sum()), pairwise_hits.size, cell_level
                )
                ref_exact = binomial_interval(
                    int(reference_hits.sum()), reference_hits.size, cell_level
                )
                derived_injected = detection_probability_pairwise(rate, size)
                derived_realised = detection_probability_pairwise(realised[rate], size)
                derived_ref_realised = detection_probability_reference(realised[rate], size)
                in_bootstrap = pair_low <= derived_realised <= pair_high
                in_injected = pair_exact[0] <= derived_injected <= pair_exact[1]
                in_realised = pair_exact[0] <= derived_realised <= pair_exact[1]
                in_ref_realised = ref_exact[0] <= derived_ref_realised <= ref_exact[1]
                pair_inside_bootstrap += int(in_bootstrap)
                pair_inside_injected += int(in_injected)
                pair_inside_realised += int(in_realised)
                ref_inside_realised += int(in_ref_realised)
                degenerate += int(pair_high == pair_low)
                cells += 1
                if rate == MISSION_RATE and size == 2:
                    mission_row = (
                        pair_point,
                        pair_low,
                        pair_high,
                        pair_exact[0],
                        pair_exact[1],
                        derived_injected,
                        int(pairwise_hits.size),
                    )
                out(
                    f"{rate:>10.6f}  {size:>3}  {pairwise_hits.size:>7}  {pair_point:>12.6f}"
                    f"  {pair_low:>9.6f}  {pair_high:>9.6f}  {pair_exact[0]:>9.6f}"
                    f"  {pair_exact[1]:>9.6f}  {derived_injected:>9.6f}"
                    f"  {derived_realised:>9.6f}  {str(in_injected):>5}"
                    f"  {str(in_realised):>5}  {ref_point:>11.6f}"
                    f"  {derived_ref_realised:>9.6f}  {str(in_ref_realised):>5}"
                )
        out("")
        out(f"cells: {cells}")
        out(f"pairwise: derived@realised inside the family-wise exact interval on "
            f"{pair_inside_realised} of {cells}")
        out(f"reference: derived@realised inside the family-wise exact interval on "
            f"{ref_inside_realised} of {cells}")
        out(f"pairwise: derived@injected inside the family-wise exact interval on "
            f"{pair_inside_injected} of {cells}")
        out(f"pairwise: derived@realised inside the per-cell 95 per cent BOOTSTRAP "
            f"interval on {pair_inside_bootstrap} of {cells}")
        out(f"cells whose bootstrap interval is degenerate (no audit detected): "
            f"{degenerate}")
        out("")
        out("at rate 1.000000 the measured pairwise power is 0 at every audit size,")
        out("and the derived value is 0 too: when every run manifests, every run")
        out("agrees with every other and run-and-diff cannot see the change at all.")
        out("that is not a defect in the measurement. It is the strongest single")
        out("statement this corpus makes about Baseline 1.")
        statistical(
            out,
            "the derived pairwise power at the REALISED rate lies inside the "
            "family-wise exact interval on every cell",
            pair_inside_realised == cells,
            f"{pair_inside_realised} of {cells}",
        )
        statistical(
            out,
            "the derived reference power at the REALISED rate lies inside the "
            "family-wise exact interval on every cell",
            ref_inside_realised == cells,
            f"{ref_inside_realised} of {cells}",
        )
        out(
            f"the derived@injected count ({pair_inside_injected} of {cells}) and the "
            f"bootstrap count ({pair_inside_bootstrap} of {cells}) are REPORTED and are "
            f"not pass criteria: {degenerate} of {cells} bootstrap intervals are "
            "degenerate at the boundary for the reason stated above, and a "
            "derived@injected miss is a calibration result that section 1 owns."
        )

        out.rule("3. BASELINE 1 AT THE MISSION RATE -- measured against derived")
        assert mission_row is not None
        point, low, high, exact_low, exact_high, derived, blocks = mission_row
        out("Baseline 1 is run-each-script-twice-and-diff. It is implemented")
        out("deliberately as the thing being refuted.")
        out("")
        out(f"injected rate                 : {MISSION_RATE!r}")
        out(f"independent runs              : {RUNS_MISSION}")
        out(f"disjoint audits of 2 runs     : {blocks}")
        out(f"MEASURED detection power      : {point!r}")
        out(f"bootstrap 95 per cent interval: [{low!r}, {high!r}]")
        out(f"exact 95 per cent interval    : [{exact_low!r}, {exact_high!r}]")
        out(f"DERIVED  1 - p^2 - (1-p)^2    : {derived!r}")
        out(f"derived inside the bootstrap interval: {low <= derived <= high}")
        out(f"derived inside the exact interval    : {exact_low <= derived <= exact_high}")
        out(f"reference-design derived value: {detection_probability_reference(MISSION_RATE, 2)!r}")
        out("")
        out("a method that finds a 1-in-44 intermittent defect about one time in")
        out("twenty-two is the method every reproducibility checker uses.")
        statistical(
            out,
            "Baseline 1's measured power at p = 1/44 contains its derived value",
            exact_low <= derived <= exact_high,
            f"derived {derived:.6f} in exact [{exact_low:.6f}, {exact_high:.6f}]",
        )
        out("")
        out("SPEC.md section 8 pre-registered that this measured power would lie")
        out("inside the interval of the derived 0.044421487603305776 AND be below")
        out("0.06. The second half is a statement about the realised sample and is")
        out("reported as it lands, not as a tolerance to be widened.")
        statistical(
            out,
            "Baseline 1's measured power at p = 1/44 is below 0.06, as pre-registered",
            point < 0.06,
            f"measured {point!r}",
        )

        out.rule("4. NEGATIVE CONTROLS -- the dynamic detector")
        out("a control that is supposed to stay silent and does not is a false")
        out("positive, and it is published rather than removed.")
        out("")
        dynamic_flags = 0
        for name in NEGATIVE_CONTROLS:
            result = two_arrangements(manifest.root, name, None, timeout=60.0)
            flagged = result.classification != NO_EVIDENCE
            dynamic_flags += int(flagged)
            out(
                f"{name:>38}  pristine_agree={result.pristine_agree!s:>5}"
                f"  reused_agree={result.reused_agree!s:>5}  {result.classification}"
            )
            out.control(f"dynamic detector on {name}", flagged, must_fire=False)
        dynamic_fpr = dynamic_flags / len(NEGATIVE_CONTROLS)
        out("")
        out(f"DYNAMIC false-positive rate on the negative controls: {dynamic_fpr!r}"
            f"  ({dynamic_flags} of {len(NEGATIVE_CONTROLS)})")

        out.rule("5. NEGATIVE CONTROLS -- the static screen, reported separately")
        out("the screen is conservative by construction: an unresolvable path")
        out("expression becomes a wildcard. deterministic_config_adjacent.py is in")
        out("the corpus BECAUSE it is the case where the two detectors are expected")
        out("to disagree -- it writes its result into the directory it reads its")
        out("config from, and it is deterministic.")
        out("")
        static_flags = 0
        for name in NEGATIVE_CONTROLS:
            source = (manifest.root / name).read_text(encoding="utf-8")
            findings = find_self_pollution(source)
            coverage = path_use_coverage(source)
            static_flags += int(bool(findings))
            out(f"{name:>38}  findings={len(findings):>2}  path uses={coverage['uses']:>2}"
                f"  vacuous={coverage['vacuous']:>2}")
            for finding in findings:
                out(f"    {finding.describe()}")
        static_fpr = static_flags / len(NEGATIVE_CONTROLS)
        out("")
        out(f"STATIC false-positive rate on the negative controls: {static_fpr!r}"
            f"  ({static_flags} of {len(NEGATIVE_CONTROLS)})")
        out("")
        out("THE PRE-REGISTERED EXPECTATION IS REFUTED HERE, and the refutation is")
        out("published rather than retuned. SPEC.md section 8 predicted a NON-ZERO")
        out("static false-positive rate, on the reasoning that an unresolvable path")
        out("becomes a wildcard and deterministic_config_adjacent.py would be")
        out("flagged. It is not flagged, and the reason is that the screen is more")
        out("precise than the prediction: that script READS A FILE in the directory")
        out("it writes to, it does not ENUMERATE the directory, and a write beside a")
        out("file that was read is not containment under a scan root. The screen was")
        out("not changed to produce this result; the prediction was wrong.")
        out("")
        out("PINNED AS A LITERAL. The static false-positive set is exactly the empty")
        out("set, and this check fails for real if a control joins it.")
        expected_static: set[str] = set()
        actual_static = {
            name
            for name in NEGATIVE_CONTROLS
            if find_self_pollution((manifest.root / name).read_text(encoding="utf-8"))
        }
        out(f"expected: {sorted(expected_static)}")
        out(f"actual  : {sorted(actual_static)}")
        out.check(
            "the static false-positive set is exactly the pinned literal set",
            actual_static == expected_static,
            f"{sorted(actual_static)}",
        )
        out.check(
            "the dynamic false-positive rate on the negative controls is 0",
            dynamic_fpr == 0.0,
            f"{dynamic_flags} of {len(NEGATIVE_CONTROLS)}",
        )

        out.rule("6. THE SELF-POLLUTING CHECK -- the two-arrangement signature")
        polluting = two_arrangements(
            manifest.root, SELF_POLLUTING_SCRIPT, "self_polluting_output.txt", timeout=60.0
        )
        out(f"pristine pair verdicts agree: {polluting.pristine_agree}")
        out(f"reused tree verdicts agree  : {polluting.reused_agree}")
        out(f"classification              : {polluting.classification}")
        out(f"escaped-rate bound at n={len(polluting.pristine)}  : {polluting.escaped_bound!r}")
        out("")
        for index, run in enumerate(polluting.pristine):
            out(f"  pristine run {index + 1}: exit={run.exit_code} artifact={run.artifact!r}")
        for index, run in enumerate(polluting.reused):
            out(f"  reused   run {index + 1}: exit={run.exit_code} artifact={run.artifact!r}")
        out("")
        out("the signature: two PRISTINE runs agree because each sees an empty")
        out("directory; the SECOND run in the same tree sees the file the first run")
        out("wrote. Neither arrangement alone says which defect this is.")
        out.control(
            "the two-arrangement classifier fires on the self-polluting check",
            polluting.classification == SELF_POLLUTING,
            must_fire=True,
            detail=polluting.classification,
        )

        out.rule("7. THE TWO CASES A SINGLE COMPARISON MODE CANNOT SEE")
        first = run_script_once(manifest.root, ITERATION_ORDER_SCRIPT)
        second = run_script_once(manifest.root, ITERATION_ORDER_SCRIPT)
        attempts = 2
        while first == second and attempts < 12:
            second = run_script_once(manifest.root, ITERATION_ORDER_SCRIPT)
            attempts += 1
        order_comparison = compare(first, second)
        out("iteration order -- the number is fixed, the printed order is not.")
        out(f"  runs needed before the two outputs differed: {attempts}")
        out(f"  moved numeric claims            : {order_comparison.moved_count}")
        out(f"  structurally changed lines      : "
            f"{order_comparison.structural_lines_reference}")
        out(f"  a numeric-only comparison sees  : {order_comparison.moved_count} changes")
        out(f"  the skeleton comparison sees    : "
            f"{order_comparison.structural_lines_reference} changed lines")
        out.check(
            "a numeric-only comparison is blind to the iteration-order change and "
            "the skeleton comparison is not",
            order_comparison.moved_count == 0 and order_comparison.structural_change,
            f"moved={order_comparison.moved_count}, "
            f"structural={order_comparison.structural_change}",
        )
        out("")
        precision_first = run_script_once(manifest.root, SUB_PRECISION_SCRIPT)
        rounded_line = [
            line for line in precision_first.splitlines() if line.startswith("rounded")
        ][0]
        full_line = [line for line in precision_first.splitlines() if line.startswith("full")][0]
        unperturbed_rounded = f"rounded {0.1234567890123:.6f}"
        unperturbed_full = f"full {0.1234567890123:.17g}"
        rounded_comparison = compare(unperturbed_rounded + "\n", rounded_line + "\n")
