"""Baseline 3: measured detection power against a corpus of known rate.

Ground truth. Without it, "the audit found nothing" and "the audit cannot find
anything" are the same observation.

The corpus is generated by the committed generator in ``seedaudit.corpus`` into
a temporary directory. Non-determinism is injected at rates from 1.0 down to
0.001 using an operating-system draw inside each generated script, so the
injected rate is a property of the script and is not reachable by any declared
seed; a seeded draw would make the measurement of detection power a measurement
of the seed sweep instead.

Four things are measured and all four are published as they land:

1. **Calibration.** The realised per-run rate against the injected rate, with a
   binomial interval. A corpus whose rates are wrong is not ground truth.
2. **Detection power per rate**, for both designs, with bootstrap intervals
   whose resampling unit is the audit. Audits are formed from DISJOINT blocks
   of runs; overlapping windows would inflate the apparent sample size, which
   is the error this product exists to report in other people's work.
3. **Baseline 1 at the mission rate.** Measured against its derived
   0.044421487603305776.
4. **The false-positive rate on the deterministic negative controls**, for the
   dynamic detector and for the static screen separately. The static screen is
   deliberately conservative and is expected to flag at least one control. That
   number is published; the screen is not weakened to bring it to zero.
"""

