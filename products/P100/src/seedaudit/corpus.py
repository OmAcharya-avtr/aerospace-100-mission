"""Baseline 3: a corpus with deliberately injected non-determinism of known rate.

Ground truth. Without it, "the audit found nothing" and "the audit cannot find
anything" are the same observation. The corpus is generated by this module --
which is committed -- into a temporary directory, so the scripts themselves are
not tracked and cannot drift from the generator that describes them.

What is in it
-------------
**Rate scripts**, one per entry of :data:`INJECTED_RATES`, spanning
``1.0`` down to ``0.001``: three orders of magnitude and a bit. Each prints a
fixed reference line, except that with probability exactly ``p`` it prints a
perturbed one. The Bernoulli draw comes from :func:`os.urandom`, so it is a
genuine per-process draw at a known rate and is not reachable by any declared
seed -- a seeded draw would make the injected rate a function of the seed and
the measured detection power would be measuring the seed sweep instead.

**Negative controls**, which must NOT be flagged:

- ``deterministic_control.py`` -- pure arithmetic, no file access at all;
- ``deterministic_reader.py`` -- reads an input and writes somewhere else;
- ``deterministic_config_adjacent.py`` -- reads a config file and writes its
  result **into the same directory**. This one is deterministic, so the dynamic
  detector must stay silent, and its path structure is exactly what the static
  screen flags. It is in the corpus on purpose: it is the case where the two
  detectors are expected to disagree, and the measured static false-positive
  rate is published rather than removed by deleting the control.

**A self-polluting check**, ``self_polluting.py``: it globs its own directory
for ``*_output.txt`` files, reports how many it found, and then writes its own
``*_output.txt``. Two pristine runs agree, because each sees an empty
directory; a second run in the same tree sees the file the first run wrote. The
verdict changes between run 1 and run 2 of the reused tree and not between the
pristine pair, which is the signature.

**An iteration-order script**, ``iteration_order.py``: its numeric total is
identical on every run and its printed key order is not, because set iteration
order over strings depends on ``PYTHONHASHSEED``. A numeric-only comparison is
blind to it. It is in the corpus to measure that blindness rather than to assert
it.

**A sub-precision script**, ``sub_precision.py``: it prints the same value
twice, once rounded to six decimals and once at full repr precision, and
perturbs it at the twelfth significant digit. A text diff of the rounded line
cannot see the change; the full-precision token moves. It measures the
difference between a text comparison and a numeric one.

Measuring detection power
-------------------------
For each rate script, ``R`` independent processes are run and the per-run
manifestation indicator is recorded. Audits of ``n`` repeats are then formed
from **disjoint consecutive blocks** of those runs, so the audits remain
independent of each other, and the detection power is the fraction of blocks
that detected, with a bootstrap interval whose resampling unit is the block.
Overlapping windows would inflate the apparent sample size.

Units: rates and probabilities are dimensionless; timeouts are seconds.
"""

from __future__ import annotations

import os
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import numpy as np

#: The injected rates, spanning more than three orders of magnitude. ``1/44``
#: is the rate this mission actually shipped and is the reason the product
#: exists.
INJECTED_RATES: tuple[float, ...] = (1.0, 0.5, 0.1, 1.0 / 44.0, 0.01, 0.001)

#: Scripts that must never be flagged by the dynamic detector.
NEGATIVE_CONTROLS: tuple[str, ...] = (
    "deterministic_control.py",
    "deterministic_reader.py",
    "deterministic_config_adjacent.py",
)

#: The deliberately self-polluting check.
SELF_POLLUTING_SCRIPT = "self_polluting.py"

#: The script whose iteration order moves while its numbers do not.
ITERATION_ORDER_SCRIPT = "iteration_order.py"

#: The script whose change is below its own printed precision.
SUB_PRECISION_SCRIPT = "sub_precision.py"

#: The reference value every rate script prints when it does not manifest.
REFERENCE_VALUE = "1.000000"

#: The value a rate script prints when it does manifest.
PERTURBED_VALUE = "2.000000"

_RATE_TEMPLATE = '''"""Injected non-determinism at rate {rate!r}. Generated; not tracked."""

import os

RATE = {rate!r}


def draw() -> float:
    """One uniform draw from the operating system, not from any declared seed."""
    return int.from_bytes(os.urandom(8), "big") / 2.0**64


def main() -> None:
    value = "{perturbed}" if draw() < RATE else "{reference}"
    print("script {name}")
    print("value " + value)


main()
'''

_CONTROL_TEMPLATE = '''"""Deterministic negative control. Generated; not tracked."""


def main() -> None:
    total = 0.0
    for index in range(1, 65):
        total += 1.0 / index
    print("script deterministic_control.py")
    print("value %.6f" % total)


main()
'''

_READER_TEMPLATE = '''"""Deterministic control: reads an input, writes elsewhere. Generated."""

from pathlib import Path

HERE = Path(__file__).resolve().parent


def main() -> None:
    text = (HERE / "inputs" / "data.txt").read_text(encoding="utf-8")
    out = HERE / "outputs"
    out.mkdir(exist_ok=True)
    total = sum(float(line) for line in text.split())
    (out / "reader_result.txt").write_text("%.6f\\n" % total, encoding="utf-8")
    print("script deterministic_reader.py")
    print("value %.6f" % total)


main()
'''

_CONFIG_ADJACENT_TEMPLATE = '''"""Deterministic control: writes beside the config it reads.

Deterministic, so the dynamic detector must stay silent. Its path structure is
what the static screen flags, and that disagreement is the measurement.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent


def main() -> None:
    config = HERE / "shared" / "config.txt"
    scale = float(config.read_text(encoding="utf-8").strip())
    value = scale * 2.0
    (HERE / "shared" / "config_adjacent_output.txt").write_text(
        "%.6f\\n" % value, encoding="utf-8"
    )
    print("script deterministic_config_adjacent.py")
    print("value %.6f" % value)


main()
'''

_SELF_POLLUTING_TEMPLATE = '''"""A check whose execution creates what it tests. Generated."""

from pathlib import Path

HERE = Path(__file__).resolve().parent


def main() -> None:
    strays = sorted(p.name for p in HERE.glob("*_output.txt"))
    print("script self_polluting.py")
    print("strays %d" % len(strays))
    verdict = "CLEAN" if not strays else "DIRTY"
    print("verdict " + verdict)
    (HERE / "self_polluting_output.txt").write_text(verdict + "\\n", encoding="utf-8")


main()
'''

_ITERATION_ORDER_TEMPLATE = '''"""Numbers fixed, container order not. Generated; not tracked."""


def main() -> None:
    keys = {"alpha", "bravo", "charlie", "delta", "echo", "foxtrot", "golf"}
    print("script iteration_order.py")
    print("order " + " ".join(keys))
    print("value %.6f" % sum(len(key) for key in sorted(keys)))


main()
'''

_SUB_PRECISION_TEMPLATE = '''"""A change below the printed precision. Generated; not tracked."""

import os

RATE = 1.0
BASE = 0.1234567890123


def draw() -> float:
    return int.from_bytes(os.urandom(8), "big") / 2.0**64


def main() -> None:
    value = BASE
    if draw() < RATE:
        value = BASE + 1e-13
    print("script sub_precision.py")
    print("rounded %.6f" % value)
    print("full %.17g" % value)


main()
'''


def rate_tag(rate: float) -> str:
    """A filesystem-safe tag for an injected rate, e.g. ``0p022727``.

    Args:
        rate: the injected rate, dimensionless, in ``(0, 1]``.

    Returns:
        The tag.
    """
    value = float(rate)
    if not 0.0 < value <= 1.0:
        raise ValueError(f"rate must lie in (0, 1], got {value!r}")
    return f"{value:.6f}".replace(".", "p")


def rate_script_name(rate: float) -> str:
    """The generated script name for an injected rate."""
    return f"rate_{rate_tag(rate)}.py"


@dataclass(frozen=True)
class CorpusManifest:
    """What :func:`generate_corpus` wrote.

    Attributes:
        root: the corpus directory.
        rate_scripts: mapping from injected rate to script file name.
        references: mapping from script file name to the exact stdout the
            script produces when it does **not** manifest. This is the
            committed reference a reference-comparison design compares against.
        negative_controls: the names of the scripts that must not be flagged.
        self_polluting: the name of the deliberately self-polluting script.
    """

    root: Path
    rate_scripts: dict[float, str]
    references: dict[str, str]
    negative_controls: tuple[str, ...]
    self_polluting: str

    @property
    def script_names(self) -> tuple[str, ...]:
        """Every generated script name, sorted."""
        return tuple(sorted(self.references))


def generate_corpus(destination: Path, rates: tuple[float, ...] = INJECTED_RATES) -> CorpusManifest:
    """Write the injected corpus into ``destination``.

    The generator takes no random seed: every file it writes is a fixed
    function of ``rates``, so the corpus itself is byte-reproducible. The
    randomness lives inside the generated scripts at run time, drawn from the
    operating system, which is what makes the injected rate a property of the
    script rather than of the audit.

    Args:
        destination: an existing or creatable directory.
        rates: the injected rates, dimensionless, each in ``(0, 1]``.

    Returns:
        A :class:`CorpusManifest`.
    """
    if not rates:
        raise ValueError("rates must be a non-empty sequence")
    root = Path(destination)
    root.mkdir(parents=True, exist_ok=True)
    (root / "inputs").mkdir(exist_ok=True)
    (root / "shared").mkdir(exist_ok=True)
    (root / "inputs" / "data.txt").write_text("1.5 2.5 3.5 4.5\n", encoding="utf-8")
    (root / "shared" / "config.txt").write_text("3.25\n", encoding="utf-8")

    rate_scripts: dict[float, str] = {}
    references: dict[str, str] = {}
    for rate in rates:
        name = rate_script_name(rate)
        (root / name).write_text(
            _RATE_TEMPLATE.format(
                rate=float(rate), name=name, reference=REFERENCE_VALUE, perturbed=PERTURBED_VALUE
            ),
            encoding="utf-8",
        )
        rate_scripts[float(rate)] = name
        references[name] = f"script {name}\nvalue {REFERENCE_VALUE}\n"

    (root / "deterministic_control.py").write_text(_CONTROL_TEMPLATE, encoding="utf-8")
    total = sum(1.0 / index for index in range(1, 65))
    references["deterministic_control.py"] = (
        f"script deterministic_control.py\nvalue {total:.6f}\n"
    )

    (root / "deterministic_reader.py").write_text(_READER_TEMPLATE, encoding="utf-8")
    references["deterministic_reader.py"] = (
        f"script deterministic_reader.py\nvalue {12.0:.6f}\n"
    )

    (root / "deterministic_config_adjacent.py").write_text(
        _CONFIG_ADJACENT_TEMPLATE, encoding="utf-8"
    )
    references["deterministic_config_adjacent.py"] = (
        f"script deterministic_config_adjacent.py\nvalue {6.5:.6f}\n"
    )

    (root / SELF_POLLUTING_SCRIPT).write_text(_SELF_POLLUTING_TEMPLATE, encoding="utf-8")
    references[SELF_POLLUTING_SCRIPT] = "script self_polluting.py\nstrays 0\nverdict CLEAN\n"

    (root / ITERATION_ORDER_SCRIPT).write_text(_ITERATION_ORDER_TEMPLATE, encoding="utf-8")
    references[ITERATION_ORDER_SCRIPT] = ""

    (root / SUB_PRECISION_SCRIPT).write_text(_SUB_PRECISION_TEMPLATE, encoding="utf-8")
    references[SUB_PRECISION_SCRIPT] = ""

    return CorpusManifest(
        root=root,
        rate_scripts=rate_scripts,
        references=references,
        negative_controls=NEGATIVE_CONTROLS,
        self_polluting=SELF_POLLUTING_SCRIPT,
    )


def run_script_once(
    corpus: Path, name: str, timeout: float = 60.0, hash_seed: str | None = None
) -> str:
    """Run one corpus script in a fresh subprocess and return its stdout.

    The rate scripts and the controls write at most into their own ``outputs``
    directory, so they are run in place inside the already-temporary corpus
    rather than in a copy. The self-polluting script is the exception and is
    exercised through :func:`seedaudit.dynamic.two_arrangements`, which copies.

    Args:
        corpus: the corpus directory.
        name: the script's file name.
        timeout: wall-clock limit, seconds.
        hash_seed: ``PYTHONHASHSEED``, or ``None`` for ``random``.

    Returns:
        The decoded standard output.
    """
    root = Path(corpus)
    target = root / name
    if not target.is_file():
        raise ValueError(f"no such corpus script: {name!r}")
    env = dict(os.environ)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["PYTHONHASHSEED"] = "random" if hash_seed is None else str(hash_seed)
    env.pop("PYTHONPATH", None)
    completed = subprocess.run(  # noqa: S603 - the corpus script is the subject
        [sys.executable, str(target)],
        cwd=str(root),
        capture_output=True,
        env=env,
        timeout=float(timeout),
        check=False,
    )
    return completed.stdout.decode("utf-8", errors="replace")


def manifestation_indicators(
    corpus: Path, name: str, reference: str, runs: int, timeout: float = 60.0
) -> np.ndarray:
    """Run a corpus script ``runs`` times and record whether each run manifested.

    Args:
        corpus: the corpus directory.
        name: the script's file name.
        reference: the stdout the script produces when it does not manifest.
        runs: how many independent processes, dimensionless, at least 1.
        timeout: wall-clock limit per run, seconds.

    Returns:
        A 1-D array of 0/1, one entry per run.
    """
    if isinstance(runs, bool) or not isinstance(runs, int):
        raise TypeError(f"runs must be an int, got {type(runs).__name__}")
    if runs < 1:
        raise ValueError(f"runs must be at least 1, got {runs}")
    out = np.zeros(runs, dtype=float)
    for index in range(runs):
        out[index] = float(run_script_once(corpus, name, timeout) != reference)
    return out


def block_detection(indicators: np.ndarray, repeats: int) -> tuple[np.ndarray, np.ndarray]:
    """Form disjoint audits of ``repeats`` runs and say whether each detected.

    Disjoint blocks, never sliding windows: overlapping audits share runs and
    would inflate the apparent number of independent audits, which is exactly
    the error the product exists to report in other people's work.

    Args:
        indicators: 1-D array of 0/1 per-run manifestation indicators.
        repeats: audit size, dimensionless, at least 1.

    Returns:
        ``(reference_detected, pairwise_detected)``, each a 1-D 0/1 array with
        one entry per complete block. ``reference_detected`` is the
        reference-comparison design: at least one run manifested.
        ``pairwise_detected`` is the run-twice-and-diff design: at least one
        manifested **and** at least one did not.
    """
    values = np.asarray(indicators, dtype=float).ravel()
    if isinstance(repeats, bool) or not isinstance(repeats, int):
        raise TypeError(f"repeats must be an int, got {type(repeats).__name__}")
    if repeats < 1:
        raise ValueError(f"repeats must be at least 1, got {repeats}")
    blocks = values.size // repeats
    if blocks == 0:
        raise ValueError(
            f"{values.size} runs cannot form even one block of {repeats}; "
            "run more repeats or lower the audit size"
        )
    trimmed = values[: blocks * repeats].reshape(blocks, repeats)
    hits = trimmed.sum(axis=1)
    reference = (hits > 0).astype(float)
    pairwise = ((hits > 0) & (hits < repeats)).astype(float)
    return reference, pairwise
