"""The three backends over the same channels, with their stamps.

Left: the die-temperature channel from the simulated backend and from both
committed traces, over the samples each can serve. Right: how many of the
thirteen board channels each backend can serve on a host without the board,
which for the live backend is none and is the correct answer.

What to notice: the replay of the idle fixture and the simulated generator
trace the same curve, because the fixture WAS generated by that generator at a
declared seed -- and the replay is still stamped simulated, not recorded,
because the document declares simulated content.
"""

from __future__ import annotations

import sys

sys.dont_write_bytecode = True

import matplotlib.pyplot as plt  # noqa: E402

from _common import (  # noqa: E402
    PROVENANCE_COLOURS,
    REFUSED,
    bootstrap,
    save,
    style,
)

ROOT = bootstrap()

from boardprobe import (  # noqa: E402
    ORIN_NANO,
    Access,
    LiveSource,
    RecordedSource,
    SimulatedSource,
    Trace,
    read_available,
)

BOARD_CHANNELS = tuple(
    channel.name
    for channel in ORIN_NANO.channels
    if channel.access is not Access.CLOCK_SYSCALL
)


def main() -> int:
    style()
    idle = Trace.from_file(ROOT / "fixtures/orin_nano_idle_simulated_trace.json")
    replay = Trace.from_file(ROOT / "fixtures/replay_path_recorded_trace.json")

    figure, (left, right) = plt.subplots(1, 2, figsize=(11.4, 4.0))

    series = (
        ("simulated backend, seed 20260101",
         SimulatedSource(ORIN_NANO, seed=20260101), 24),
        ("replay of the idle fixture", RecordedSource(ORIN_NANO, idle), 24),
        ("replay of the replay-path fixture", RecordedSource(ORIN_NANO, replay), 12),
    )
    for name, source, count in series:
        values = [source.read("die_temp_cpu").value for _ in range(count)]
        colour = PROVENANCE_COLOURS[source.provenance.value]
        left.plot(
            range(count), values, marker="o", markersize=3, linewidth=1.4,
            color=colour, label=f"{name}  [{source.provenance.value}]",
        )
    left.set_xlabel("sample index")
    left.set_ylabel("die_temp_cpu [degC]")
    left.set_title("the same channel, three backends, three stamps")
    left.legend(fontsize=7.5, loc="lower right")

    counts = []
    labels = []
    colours = []
    for name, source in (
        ("simulated", SimulatedSource(ORIN_NANO, seed=1)),
        ("recorded\n(idle fixture)", RecordedSource(ORIN_NANO, idle)),
        ("recorded\n(replay fixture)", RecordedSource(ORIN_NANO, replay)),
        ("live", LiveSource(ORIN_NANO)),
    ):
        readings, _refusals = read_available(source, BOARD_CHANNELS)
        counts.append(len(readings))
        labels.append(name)
        colours.append(
            REFUSED if not readings else PROVENANCE_COLOURS[source.provenance.value]
        )
    bars = right.bar(labels, counts, color=colours, width=0.6)
    right.bar_label(bars, fmt="%d", fontsize=9)
    right.axhline(len(BOARD_CHANNELS), color="#1a1a1a", linewidth=1.0,
                  linestyle=":", label=f"{len(BOARD_CHANNELS)} board channels declared")
    right.set_ylabel("board channels served")
    right.set_ylim(0, len(BOARD_CHANNELS) + 1.6)
    right.set_title("what each backend can serve with no board attached")
    right.legend(fontsize=8, loc="upper right")
    right.text(
        3, 0.6, "zero, and that is\nthe correct answer",
        ha="center", fontsize=8, color=REFUSED,
    )

    figure.suptitle(
        "boardprobe: three backends behind one interface "
        "(Level 3, hardware-pending; the board was not reachable)",
        fontsize=10,
    )
    figure.tight_layout(rect=(0, 0, 1, 0.93))
    path = save(figure, "backend_comparison")
    print(f"written: {path}")
    print(f"board channels declared: {len(BOARD_CHANNELS)}")
    print(f"channels served per backend: {dict(zip(labels, counts, strict=True))}")
    print(f"idle fixture content provenance: {idle.content_provenance}")
    print(f"replay fixture content provenance: {replay.content_provenance}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
