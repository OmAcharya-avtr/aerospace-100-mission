"""Synthetic dataset for the learned combiner.

Every dataset is generated by this module from a seed; no data file is
committed. ``make_combiner_dataset`` is deterministic in ``seed`` and in the
sizes passed to it, so the figures in ``validation/`` regenerate exactly.

What one row is
---------------
One row is one symbol interval at one receiver array:

* ``irradiance_true`` ``(L,)`` — the true normalised irradiance per aperture,
  correlated across apertures by a log-domain correlation matrix;
* ``irradiance_estimated`` ``(L,)`` — what the receiver has, degraded by the
  error model of :mod:`aperturediv.estimation`;
* ``sigma_e`` — the log-domain error standard deviation for that row, drawn
  per row so that one model covers the whole error range rather than one
  model per operating point;
* ``features`` ``(L + 3,)`` — exactly the information a receiver has: the
  log of each estimate, their mean and standard deviation, and
  ``sigma_e`` itself (an estimator knows its own accuracy). **The truth is
  not a feature.** This is enforced by construction: the feature builder
  never sees ``irradiance_true``.
* ``weights_optimal`` ``(L,)`` — the unit-norm maximal-ratio weight
  direction for the true state, ``h / ||h||`` with ``h = sqrt(I)``. This is
  the regression target; it is a label, available only in training.

Splits
------
:func:`split_dataset` splits by row index into train / validation / test
with no overlap. Rows are i.i.d. draws, so an index split is a valid
held-out split; there is no temporal structure to leak across it, because
each row is one independent symbol interval. The same held-out test rows are
used for every baseline and for the learned model.

Nothing here is flight-qualified or certified.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .correlation import correlation_matrix, equispaced_positions
from .estimation import DB_PER_NEPER, estimate_from_log_error

__all__ = [
    "CombinerDataset",
    "N_EXTRA_FEATURES",
    "build_features",
    "make_combiner_dataset",
    "split_dataset",
]

N_EXTRA_FEATURES = 3  # mean of log estimates, their std, sigma_e


@dataclass(frozen=True)
class CombinerDataset:
    """A generated combiner dataset. All arrays share the row axis."""

    irradiance_true: np.ndarray
    irradiance_estimated: np.ndarray
    sigma_e: np.ndarray
    features: np.ndarray
    weights_optimal: np.ndarray
    log_correlation: np.ndarray
    si: float
    seed: int

    def __len__(self) -> int:
        return int(self.irradiance_true.shape[0])

    @property
    def n_apertures(self) -> int:
        return int(self.irradiance_true.shape[1])

    @property
    def amplitude_true(self) -> np.ndarray:
        """``h = sqrt(I)``, shape ``(n, L)``."""
        return np.sqrt(self.irradiance_true)

    @property
    def sigma_e_db(self) -> np.ndarray:
        return DB_PER_NEPER * self.sigma_e

    def subset(self, index: np.ndarray) -> CombinerDataset:
        """Row subset, keeping the metadata."""
        return CombinerDataset(
            irradiance_true=self.irradiance_true[index],
            irradiance_estimated=self.irradiance_estimated[index],
            sigma_e=self.sigma_e[index],
            features=self.features[index],
            weights_optimal=self.weights_optimal[index],
            log_correlation=self.log_correlation,
            si=self.si,
            seed=self.seed,
        )


def build_features(irradiance_estimated: np.ndarray, sigma_e: np.ndarray) -> np.ndarray:
    """Feature matrix from the estimate alone.

    Columns: ``ln Ihat_1 .. ln Ihat_L``, then ``mean_k ln Ihat_k``,
    ``std_k ln Ihat_k``, ``sigma_e``. Shape ``(n, L + 3)``.

    The true irradiance is deliberately not an argument, so no caller can
    leak it into the model.
    """
    i_hat = np.asarray(irradiance_estimated, dtype=float)
    if i_hat.ndim != 2:
        raise ValueError("irradiance_estimated must have shape (n, L)")
    if np.any(i_hat <= 0.0):
        raise ValueError("irradiance_estimated must be strictly positive")
    se = np.asarray(sigma_e, dtype=float)
    if se.shape != (i_hat.shape[0],):
        raise ValueError("sigma_e must have shape (n,)")
    log_hat = np.log(i_hat)
    return np.column_stack(
        [log_hat, log_hat.mean(axis=1), log_hat.std(axis=1), se]
    )


def make_combiner_dataset(
    n_samples: int,
    *,
    n_apertures: int = 4,
    si: float = 0.6,
    aperture_spacing_m: float = 0.05,
    correlation_scale_m: float = 0.10,
    sigma_e_range: tuple[float, float] = (0.0, 1.2),
    seed: int = 44044,
) -> CombinerDataset:
    """Generate a combiner dataset.

    Parameters
    ----------
    n_samples
        Number of rows.
    n_apertures
        ``L``, number of receive apertures on a line array.
    si
        Marginal scintillation index per aperture.
    aperture_spacing_m
        Pitch of the line array in metres.
    correlation_scale_m
        Irradiance correlation scale ``rho_c`` in metres. Together with the
        spacing this fixes the inter-aperture correlation.
    sigma_e_range
        ``(low, high)`` for the per-row uniform draw of the log-domain
        estimation error standard deviation.
    seed
        Seed for ``numpy.random.default_rng``.

    Returns
    -------
    CombinerDataset
    """
    from .correlation import sample_correlated_lognormal  # local: keeps the import graph flat

    n = int(n_samples)
    if n < 1:
        raise ValueError(f"n_samples must be >= 1, got {n!r}")
    low, high = float(sigma_e_range[0]), float(sigma_e_range[1])
    if not 0.0 <= low <= high:
        raise ValueError(f"sigma_e_range must satisfy 0 <= low <= high, got {sigma_e_range!r}")
    rng = np.random.default_rng(int(seed))
    pos = equispaced_positions(n_apertures, aperture_spacing_m)
    r_log = correlation_matrix(pos, correlation_scale_m, "gaussian")
    i_true = sample_correlated_lognormal(n, si, r_log, rng)
    sigma_e = rng.uniform(low, high, n)
    est = estimate_from_log_error(i_true, sigma_e, rng)
    h = np.sqrt(i_true)
    w_opt = h / np.linalg.norm(h, axis=1, keepdims=True)
    return CombinerDataset(
        irradiance_true=i_true,
        irradiance_estimated=est.irradiance_estimated,
        sigma_e=sigma_e,
        features=build_features(est.irradiance_estimated, sigma_e),
        weights_optimal=w_opt,
        log_correlation=r_log,
        si=float(si),
        seed=int(seed),
    )


def split_dataset(
    dataset: CombinerDataset, *, n_train: int, n_validation: int
) -> tuple[CombinerDataset, CombinerDataset, CombinerDataset]:
    """Split by row index into train, validation and test, in that order.

    Raises
    ------
    ValueError
        If the requested train and validation sizes leave no test rows.
    """
    total = len(dataset)
    n_tr, n_va = int(n_train), int(n_validation)
    if n_tr < 1 or n_va < 1:
        raise ValueError("n_train and n_validation must be >= 1")
    if n_tr + n_va >= total:
        raise ValueError(
            f"n_train + n_validation = {n_tr + n_va} leaves no test rows out of {total}"
        )
    idx = np.arange(total)
    return (
        dataset.subset(idx[:n_tr]),
        dataset.subset(idx[n_tr : n_tr + n_va]),
        dataset.subset(idx[n_tr + n_va :]),
    )
