"""Optical ground-station site-diversity availability under measured correlation.

The question this package answers: a network of optical ground stations is
unavailable when cloud blocks every station at once, and the usual first
estimate of how often that happens is the product of the stations' individual
cloud probabilities. That estimate assumes the stations' cloud cover is
independent. It is not, and the error is in one direction: the independence
assumption UNDERSTATES joint unavailability and therefore OVERSTATES the
availability a diversity network delivers. This package measures the
overstatement.

What it is measured on. A synthetic concurrent cloud record, generated by
``sitediverse.field`` from declared constants and a fixed seed, with a KNOWN
spatial correlation structure. No real site climatology is used. See
``DATASET_CARD.md``.

Research grade. Not flight-qualified, not certified, not approved for
operational aerospace use.
"""

