"""THE HEADLINE. The independence assumption against the record, with its uncertainty.

This script produces the numbers this product exists for: the joint
unavailability a diversity network is assigned by the independence assumption,
the joint unavailability the record actually shows, the ratio and the difference
between them, and the record's own sampling uncertainty attached to every
figure. The exact decomposition of equation (16) splits the difference into what
the stationarity assumption costs and what the independence assumption costs.

The record is SYNTHETIC. Every number below is a property of a cloud field
generated by ``sitediverse.field`` from declared constants and a fixed seed, and
none of it transfers to a real network. See ``DATASET_CARD.md``.
"""

