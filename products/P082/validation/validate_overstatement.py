def headline(out: Tee, record, climatology) -> dict[str, object]:
    """Part 1: the headline table, for every declared network."""
    out.rule("1. THE HEADLINE: independence against the record")
    out("P_independent is the naive product of marginals of equation (14), which is")
    out("what site-diversity practice does. P_measured is the directly observed joint")
    out("cloud rate of equation (20). The ratio is the factor by which independence")
    out("UNDERSTATES joint unavailability, and therefore the factor by which it")
    out("OVERSTATES the availability a diversity network delivers.")
    out("")
    errors = climatology.rate_standard_error()
    rows = []
    results = {}
    for name, sites in NETWORKS.items():
        result = overstatement(climatology, record.cloud, sites)
        band = bootstrap_joint_rate(
            record.cloud, sites, block=BLOCK, replicates=REPLICATES, seed=909001
        )
        relative = naive_product_relative_sd(
            climatology.long_term_rate[list(sites)], errors[list(sites)]
        )
        results[name] = (result, band, relative)
        rows.append(
            [
                name,
                str(len(sites)),
                f"{result.naive:.6f} +/- {relative * result.naive:.6f}",
                f"{result.measured:.6f} +/- {band.standard_error:.6f}",
                number(result.ratio, 4),
                f"{result.total_difference:+.6f}",
            ]
        )
    out(
        format_table(
            ["network", "n", "P_independent", "P_measured", "ratio", "difference"],
            rows,
        )
    )
    out("")
    out("The same figures as availability. The unavailability is primary everywhere")
    out("and the availability is derived from it, never the other way round: for a")
    out("well-separated network the product is small and `1 - prod q` loses every")
    out("digit of it, which is why `availability_nines` works from the")
    out("unavailability directly.")
    out("")
    rows = []
    for name in NETWORKS:
        result = results[name][0]
        rows.append(
            [
                name,
                number(1.0 - result.naive),
                number(1.0 - result.measured),
                f"{-result.total_difference:+.6f}",
                number(availability_nines(result.naive), 4),
                number(availability_nines(result.measured), 4),
                f"{result.nines_lost:+.4f}",
            ]
        )
    out(
        format_table(
            [
                "network",
                "A_independent",
                "A_measured",
                "deficit",
                "nines claimed",
                "nines measured",
                "nines lost",
            ],
            rows,
        )
    )
    out("")
    worst = max(
        results[name][0].ratio
        for name in NETWORKS
        if np.isfinite(results[name][0].ratio)
    )
    worst_name = max(
        (name for name in NETWORKS if np.isfinite(results[name][0].ratio)),
        key=lambda name: results[name][0].ratio,
    )
    out(f"  largest overstatement factor : {worst:.4f} on the {worst_name} network")
    out(f"  nines lost there             : {results[worst_name][0].nines_lost:.4f}")
    out("")
    out.check(
        "the independence assumption understates joint unavailability for every "
        "network whose baselines are short",
        all(
            results[name][0].measured > results[name][0].naive
            for name in ("near-pair", "mixed-trio", "cluster", "two-groups")
        ),
        "measured above independent on all four short-baseline networks",
    )
    out.check(
        "the largest measured overstatement factor exceeds 10",
        worst > 10.0,
        f"{worst:.4f} on the {worst_name} network",
    )
    return results


def decomposition(out: Tee, record, climatology, results) -> None:
    """Part 2: the exact decomposition of equation (16)."""
    out.rule("2. the exact decomposition of equation (16)")
    out("P_measured - P_naive = (P_conditional - P_naive) + (P_measured - P_conditional)")
    out("")
    out("The identity is exact by construction and has no cross term, so its residual")
    out("is pure rounding. The first bracket is what assuming a STATIONARY climatology")
    out("costs and is signed: two stations whose seasonal cloud maxima fall six months")
    out("apart are jointly clear more often than their annual means suggest. The")
    out("second bracket is what assuming spatial INDEPENDENCE costs and is the")
    out("quantity the correlation models of this package predict.")
    out("")
    rows = []
    worst_residual = 0.0
    for name in NETWORKS:
        result = results[name][0]
        worst_residual = max(worst_residual, abs(result.identity_residual()))
        share = result.correlation_term / result.total_difference if (
            result.total_difference != 0.0
        ) else float("nan")
        rows.append(
            [
                name,
                number(result.naive),
                number(result.conditional),
                number(result.measured),
                f"{result.comodulation_term:+.6f}",
                f"{result.correlation_term:+.6f}",
                number(share, 4),
                scientific(abs(result.identity_residual()), 2),
            ]
        )
    out(
        format_table(
            [
                "network",
                "P_naive",
                "P_conditional",
                "P_measured",
                "co-modulation",
                "correlation",
                "correlation share",
                "identity resid",
            ],
            rows,
        )
    )
    out("")
    out(f"  worst identity residual     : {worst_residual:.6e}")
    out.check(
        "the decomposition of equation (16) closes to rounding on every network",
        worst_residual < 1e-15,
        f"worst residual {worst_residual:.6e} against a tolerance of 1e-15",
    )
    out("")
    negative = [
        name
        for name in NETWORKS
        if results[name][0].comodulation_term < 0.0
    ]
    out(f"  networks with a NEGATIVE co-modulation term : "
        f"{', '.join(negative) if negative else 'none'}")
    out("")
    out("A negative co-modulation term is the mechanism behind an overstatement ratio")
    out("BELOW one, and it is reported rather than hidden: on those networks the naive")
    out("product overstates the joint unavailability rather than understating it, so")
    out("the independence assumption is wrong in both directions and only the")
    out("correlation term has a consistent sign.")
    out.check(
        "the co-modulation term is negative somewhere, so both signs are exercised",
        bool(negative),
        f"{len(negative)} of {len(NETWORKS)} networks",
    )


def uncertainty(out: Tee, record, climatology, results) -> None:
    """Part 3: the climatology sampling uncertainty attached to every figure."""
    out.rule("3. the record's own sampling uncertainty, beside every figure")
    out("The specification requires the climatology-uncertainty share propagated from")
    out("the record's own sampling uncertainty and reported beside every availability")
    out("figure. Equation (28) defines the share as")
    out("")
    out("    share = s_boot^2 / (s_boot^2 + (P_model - P_hat)^2)")
    out("")
    out("A share near 1 says the model and the record disagree by no more than the")
    out("record's own sampling noise, so the disagreement is not evidence of anything.")
    out("The corrected form subtracts s_boot^2 from the squared discrepancy and can")
    out("exceed 1, which is informative and is not clipped.")
    out("")
    rows = []
    for name in NETWORKS:
        result, band, relative = results[name]
        gap = result.naive - result.measured
        rows.append(
            [
                name,
                f"{result.measured:.6f} +/- {band.standard_error:.6f}",
                interval(band.lower, band.upper),
                number(band.relative_half_width, 4),
                f"{gap:+.6f}",
                number(climatology_share(gap, band.standard_error), 6),
                number(climatology_share_corrected(gap, band.standard_error), 6),
            ]
        )
    out(
        format_table(
            [
                "network",
                "P_measured",
                "95% interval",
                "relative half-width",
                "P_naive - P_measured",
                "clim share",
                "corrected",
            ],
            rows,
        )
    )
    out("")
    explained = [
        name
        for name in NETWORKS
        if climatology_share(
            results[name][0].naive - results[name][0].measured,
            results[name][1].standard_error,
        )
        > 0.5
    ]
    out(f"  networks whose whole discrepancy is inside the sampling noise : "
        f"{', '.join(explained) if explained else 'none'}")
    out("")
    out("Those are the networks on which this product has NOTHING to report: the")
    out("independence assumption and the record agree to within the record's own")
    out("sampling uncertainty, so the overstatement is not measurable there. They are")
    out("the far-separated networks, which is the physically expected answer and is")
    out("the reason the headline is quoted per network and never as one number.")
    out.check(
        "at least one network's discrepancy is explained by sampling noise, and it "
        "is a far-separated one",
        bool(explained)
        and all(
            min(
                separation_matrix()[i, j]
                for i in NETWORKS[name]
                for j in NETWORKS[name]
                if i != j
            )
            > 1000.0
            for name in explained
        ),
        f"{len(explained)} network(s): {', '.join(explained)}",
    )
    out("")
    out("Equation (27), the analytic propagation of the marginals' sampling")
    out("uncertainty into the naive product, against a block bootstrap of the same")
    out("product. The propagation treats the stations' estimation errors as")
    out("independent, which they are not; the correlated case has the larger")
    out("variance, so the analytic figure is a LOWER BOUND and the measured ratio")
    out("says by how much.")
    out("")
    draws = block_indices(record.epochs, BLOCK, REPLICATES, seed=272727)
    rows = []
    worst_ratio = 0.0
    for name, sites in NETWORKS.items():
        result, _, relative = results[name]
        analytic = relative * result.naive
        cloud = record.cloud[:, list(sites)]
        replicate = np.array(
            [
                product_of_marginals(cloud[draw].mean(axis=0))
                for draw in draws
            ]
        )
        empirical = float(np.std(replicate, ddof=1))
        ratio = empirical / analytic
        worst_ratio = max(worst_ratio, ratio)
        rows.append(
            [
                name,
                scientific(analytic),
                scientific(empirical),
                number(ratio, 4),
            ]
        )
    out(
        format_table(
            [
                "network",
                "analytic sd, equation (27)",
                "block bootstrap sd",
                "ratio",
            ],
            rows,
        )
    )
    out("")
    out.check(
        "the analytic propagation is a lower bound on the bootstrap, as declared",
        worst_ratio > 1.0,
        f"the bootstrap standard deviation exceeds the analytic one on every "
        f"network, by up to a factor of {worst_ratio:.4f}",
    )


def all_pairs(out: Tee, record, climatology) -> None:
    """Part 4: the overstatement across all 190 pairs, against separation."""
    out.rule("4. the overstatement against separation, over all 190 pairs")
    out("The physical claim: the overstatement is large at short separations and")
    out("vanishes at long ones, because that is what a correlated cloud field does.")
    out("Binned by separation so that the trend is visible without 190 rows.")
    out("")
    separation = separation_matrix()
    pairs = upper_triangle_pairs(len(SITES))
    distances = np.array([separation[i, j] for i, j in pairs])
    naive = np.array(
        [
            product_of_marginals(climatology.long_term_rate[[i, j]])
            for i, j in pairs
        ]
    )
    measured = np.array([joint_rate(record.cloud, (i, j)) for i, j in pairs])
    ratio = measured / naive
    edges = np.array([0.0, 200.0, 400.0, 800.0, 1600.0, 3200.0, 8000.0])
    rows = []
    for low, high in zip(edges[:-1], edges[1:], strict=True):
        mask = (distances >= low) & (distances < high)
        if not np.any(mask):
            continue
        rows.append(
            [
                f"{low:.0f} to {high:.0f}",
                str(int(mask.sum())),
                number(float(np.mean(distances[mask])), 1),
                number(float(np.mean(ratio[mask])), 4),
                number(float(ratio[mask].min()), 4),
                number(float(ratio[mask].max()), 4),
                str(int(np.count_nonzero(ratio[mask] > 1.0))),
            ]
        )
    out(
        format_table(
            [
                "separation km",
                "pairs",
                "mean km",
                "mean ratio",
                "min ratio",
                "max ratio",
                "ratio > 1",
            ],
            rows,
        )
    )
    out("")
    near = distances < 200.0
    far = distances > 3200.0
    out(f"  mean ratio under 200 km  : {float(np.mean(ratio[near])):.4f} "
        f"({int(near.sum())} pairs)")
    out(f"  mean ratio over 3200 km  : {float(np.mean(ratio[far])):.4f} "
        f"({int(far.sum())} pairs)")
    out(f"  pairs with ratio below 1 : {int(np.count_nonzero(ratio < 1.0))} of "
        f"{len(pairs)}")
    out("")
    out.check(
        "the overstatement is far larger at short separations than at long ones",
        float(np.mean(ratio[near])) > 1.5 * float(np.mean(ratio[far])),
        f"mean ratio {float(np.mean(ratio[near])):.4f} under 200 km against "
        f"{float(np.mean(ratio[far])):.4f} over 3200 km",
    )
    out.check(
        "some pairs have a ratio below 1, which the co-modulation term explains",
        int(np.count_nonzero(ratio < 1.0)) > 0,
        f"{int(np.count_nonzero(ratio < 1.0))} of {len(pairs)} pairs",
    )


def main() -> int:
    out = Tee("validate_overstatement_output.txt")
    out.rule("sitediverse -- THE HEADLINE: what the independence assumption costs")
    for line in environment_lines():
        out(line)
    out("")
    out("THE RECORD IS SYNTHETIC. It is generated by sitediverse.field from declared")
    out("constants and a fixed seed, with a KNOWN spatial correlation structure. No")
    out("real site climatology is used, no real optical ground station is a data")
    out("source, and not one number below is a measurement of the atmosphere. What")
    out("that means for the transferability of every figure is in DATASET_CARD.md.")
    with Timer() as timer:
        record = generate_record(RECORD_SPECS["anisotropic"])
        climatology = estimate_climatology(record.cloud)
    out("")
    out(f"record                       : anisotropic, {record.spec.years} declared "
        f"years, {record.epochs} epochs")
    out(f"stations                     : {record.site_count}")
    out(f"seed                         : {record.spec.seed}")
    out(f"generate and estimate        : {timer.elapsed_s:.3f} s")
    out(f"bootstrap replicates         : {REPLICATES}")
    out(f"bootstrap block epochs       : {BLOCK}")
    results = headline(out, record, climatology)
    decomposition(out, record, climatology, results)
    uncertainty(out, record, climatology, results)
    all_pairs(out, record, climatology)
    path = out.save()
    print(f"\nwritten: {path}")
    return 1 if out.failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
