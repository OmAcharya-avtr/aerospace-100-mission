"""Synthetic phase-noise processes whose Allan deviation is known in closed form.

These exist to verify :mod:`timetransfer.allan`. Each process has an Allan
variance that can be written down exactly, so the check is against a closed
form rather than against another implementation.

Definitions and closed forms
----------------------------
Phase data ``x_i`` [s] are time-error samples on a uniform grid of spacing
``tau0`` [s]. With ``tau = m * tau0`` the second difference
``D_i = x_{i+2m} - 2 x_{i+m} + x_i`` gives the Allan variance
``sigma_y^2(tau) = E[D^2] / (2 tau^2)`` (IEEE Std 1139-2008, definition of the
two-sample variance; Allan, "Statistics of atomic frequency standards",
*Proceedings of the IEEE* 54(2):221-230, 1966).

* **White phase modulation.** ``x_i`` independent ``N(0, sigma_x^2)``. Then
  ``E[D^2] = (1 + 4 + 1) sigma_x^2 = 6 sigma_x^2`` for any ``m >= 1``, so

      sigma_y^2(tau) = 3 sigma_x^2 / tau^2,  ADEV = sqrt(3) sigma_x / tau

  slope ``-1`` on a log-log plot.

* **White frequency modulation.** ``x`` is a Wiener process of intensity
  ``q1`` [s^2/s]: ``x(t+h) - x(t) ~ N(0, q1 h)``. The second difference is the
  difference of two independent increments of length ``tau``, so
  ``E[D^2] = 2 q1 tau`` and

      sigma_y^2(tau) = q1 / tau,  ADEV = sqrt(q1 / tau)

  slope ``-1/2``.

* **Random walk frequency modulation.** The fractional frequency ``y`` is a
  Wiener process of intensity ``q2`` [1/s] and ``x`` is its integral. Then

      sigma_y^2(tau) = q2 tau / 3,  ADEV = sqrt(q2 tau / 3)

  slope ``+1/2``. Together with the previous case this is
  ``sigma_y^2(tau) = q1/tau + q2 tau/3``, the two-state clock model of Zucca
  and Tavella, "The clock model and its relationship with the Allan and
  related variances", *IEEE Transactions on Ultrasonics, Ferroelectrics and
  Frequency Control* 52(2):289-296 (2005).

Exact sampling of the integrated Wiener process
-----------------------------------------------
The random-walk-FM phase is generated by sampling the joint increment of
``(x, y)`` from its exact covariance

    Cov = [[q2 h^3 / 3, q2 h^2 / 2],
           [q2 h^2 / 2, q2 h      ]]

rather than by Euler-stepping ``y`` and accumulating it, because the Euler
scheme gets the ``x`` variance wrong by a factor that depends on ``h`` and
would make the Allan-variance comparison a test of the integrator instead of a
test of the estimator. The covariance above is the standard result for the
integrated Wiener process; see Zucca and Tavella 2005, section III.

Validity range
--------------
These are *stationary-increment* processes with no deterministic polynomial.
Flicker noise is not provided: it has no finite-dimensional Markov
representation and any synthesis of it is an approximation, which would
undermine the point of verifying against a closed form.
"""

from __future__ import annotations

import numpy as np

from .errors import ConfigurationError

__all__ = [
    "NOISE_KINDS",
    "random_walk_fm_phase",
    "synthetic_phase",
    "theoretical_adev",
    "theory_slope",
    "white_fm_phase",
    "white_pm_phase",
]

NOISE_KINDS: tuple[str, ...] = ("white_pm", "white_fm", "random_walk_fm")
"""The three processes with closed-form Allan deviations used for verification."""

_SLOPES: dict[str, float] = {"white_pm": -1.0, "white_fm": -0.5, "random_walk_fm": 0.5}


def theory_slope(kind: str) -> float:
    """Log-log slope ``mu`` in ``ADEV ~ tau**mu`` for a named process."""
    if kind not in _SLOPES:
        raise ConfigurationError(f"unknown noise kind {kind!r}; expected one of {NOISE_KINDS}")
    return _SLOPES[kind]


def white_pm_phase(n: int, *, sigma_x_s: float, seed: int) -> np.ndarray:
    """``n`` samples of white phase modulation [s].

    Parameters
    ----------
    n:
        Number of samples, >= 3.
    sigma_x_s:
        Standard deviation of each phase sample [s], > 0.
    seed:
        PCG64 seed.
    """
    if int(n) < 3:
        raise ConfigurationError(f"n must be >= 3, got {n!r}")
    if not (float(sigma_x_s) > 0.0):
        raise ConfigurationError(f"sigma_x_s must be > 0, got {sigma_x_s!r}")
    rng = np.random.Generator(np.random.PCG64(int(seed)))
    return rng.normal(0.0, float(sigma_x_s), size=int(n))


def white_fm_phase(n: int, *, tau0_s: float, q1_s2_per_s: float, seed: int) -> np.ndarray:
    """``n`` samples of white-FM phase [s]: a Wiener process of intensity ``q1``.

    Parameters
    ----------
    n:
        Number of samples, >= 3.
    tau0_s:
        Sample spacing [s], > 0.
    q1_s2_per_s:
        Wiener intensity [s^2/s], > 0.
    seed:
        PCG64 seed.
    """
    if int(n) < 3:
        raise ConfigurationError(f"n must be >= 3, got {n!r}")
    if not (float(tau0_s) > 0.0):
        raise ConfigurationError(f"tau0_s must be > 0, got {tau0_s!r}")
    if not (float(q1_s2_per_s) > 0.0):
        raise ConfigurationError(f"q1_s2_per_s must be > 0, got {q1_s2_per_s!r}")
    rng = np.random.Generator(np.random.PCG64(int(seed)))
    step = np.sqrt(float(q1_s2_per_s) * float(tau0_s))
    increments = rng.normal(0.0, step, size=int(n) - 1)
    return np.concatenate(([0.0], np.cumsum(increments)))


def random_walk_fm_phase(n: int, *, tau0_s: float, q2_per_s: float, seed: int) -> np.ndarray:
    """``n`` samples of random-walk-FM phase [s], sampled exactly.

    The joint ``(phase, frequency)`` increment is drawn from the exact
    covariance of the integrated Wiener process (see the module docstring), so
    the realised Allan variance converges to ``q2 tau / 3`` without an
    integrator bias.

    Parameters
    ----------
    n:
        Number of samples, >= 3.
    tau0_s:
        Sample spacing [s], > 0.
    q2_per_s:
        Frequency Wiener intensity [1/s], > 0.
    seed:
        PCG64 seed.
    """
    if int(n) < 3:
        raise ConfigurationError(f"n must be >= 3, got {n!r}")
    if not (float(tau0_s) > 0.0):
        raise ConfigurationError(f"tau0_s must be > 0, got {tau0_s!r}")
    if not (float(q2_per_s) > 0.0):
        raise ConfigurationError(f"q2_per_s must be > 0, got {q2_per_s!r}")
    rng = np.random.Generator(np.random.PCG64(int(seed)))
    h = float(tau0_s)
    q2 = float(q2_per_s)
    cov = np.array(
        [[q2 * h**3 / 3.0, q2 * h**2 / 2.0], [q2 * h**2 / 2.0, q2 * h]], dtype=np.float64
    )
    chol = np.linalg.cholesky(cov)
    raw = rng.normal(0.0, 1.0, size=(int(n) - 1, 2))
    increments = raw @ chol.T
    x = np.zeros(int(n), dtype=np.float64)
    y = 0.0
    for i in range(int(n) - 1):
        dx, dy = float(increments[i, 0]), float(increments[i, 1])
        x[i + 1] = x[i] + y * h + dx
        y += dy
    return x


def synthetic_phase(
    kind: str, n: int, *, tau0_s: float, level: float, seed: int
) -> np.ndarray:
    """Phase samples [s] for one of :data:`NOISE_KINDS`.

    Parameters
    ----------
    kind:
        ``"white_pm"``, ``"white_fm"`` or ``"random_walk_fm"``.
    n:
        Number of samples.
    tau0_s:
        Sample spacing [s].
    level:
        ``sigma_x`` [s] for white PM, ``q1`` [s^2/s] for white FM, ``q2`` [1/s]
        for random-walk FM.
    seed:
        PCG64 seed.
    """
    if kind == "white_pm":
        return white_pm_phase(n, sigma_x_s=level, seed=seed)
    if kind == "white_fm":
        return white_fm_phase(n, tau0_s=tau0_s, q1_s2_per_s=level, seed=seed)
    if kind == "random_walk_fm":
        return random_walk_fm_phase(n, tau0_s=tau0_s, q2_per_s=level, seed=seed)
    raise ConfigurationError(f"unknown noise kind {kind!r}; expected one of {NOISE_KINDS}")


def theoretical_adev(kind: str, tau_s: np.ndarray, *, level: float) -> np.ndarray:
    """Closed-form Allan deviation [dimensionless] of a named process.

    Parameters
    ----------
    kind:
        One of :data:`NOISE_KINDS`.
    tau_s:
        Averaging times [s], all > 0.
    level:
        The same level parameter :func:`synthetic_phase` takes.
    """
    tau = np.asarray(tau_s, dtype=np.float64)
    if np.any(tau <= 0.0):
        raise ConfigurationError("tau_s must be > 0")
    if kind == "white_pm":
        return np.sqrt(3.0) * float(level) / tau
    if kind == "white_fm":
        return np.sqrt(float(level) / tau)
    if kind == "random_walk_fm":
        return np.sqrt(float(level) * tau / 3.0)
    raise ConfigurationError(f"unknown noise kind {kind!r}; expected one of {NOISE_KINDS}")
