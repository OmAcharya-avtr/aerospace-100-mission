"""Deterministic synthetic dataset for the link-availability predictor.

What this is, and what it is not
--------------------------------
Every row is one contact opportunity.  The geometry is **real**: contacts are
computed by :mod:`constellink.contacts` from an ``sgp4``-propagated Walker
constellation and a ground-station set, so elevation, range and duration are
whatever the orbital dynamics produce.  The **label** -- did this contact
close at the required data rate -- is generated by the capacity models in
:mod:`constellink.capacity` driven by a latent weather and pointing state.

That makes this a self-consistency dataset, not an empirical one.  A model
trained here learns the capacity model this package already contains, plus the
observation noise placed between the latent state and the features.  It
cannot and does not demonstrate agreement with measured link outages.  The
value of the exercise is the *comparison method* -- calibration of three
predictors on identical splits -- not the absolute numbers.  See
``DATASET_CARD.md``.

Generative structure
--------------------
Per contact, with ``rng`` seeded from ``seed``:

1. a latent cloud optical depth ``tau`` is drawn from a Gamma distribution
   whose mean depends on the station's assigned climate regime, and a latent
   visibility is drawn log-normally and correlated with ``tau``;
2. a latent pointing error is drawn half-normally;
3. a latent turbulence fade in dB is drawn log-normally -- this term is
   deliberately NOT exposed as a feature, so it is irreducible aleatoric
   noise and no predictor can reach perfect accuracy.  Log-normal
   (equivalently Gaussian-in-dB) is the conventional weak-fluctuation model
   for intensity scintillation; see Andrews & Phillips 2005, "Laser Beam
   Propagation through Random Media", 2nd ed., SPIE Press, Ch. 9;
4. the achievable rate is evaluated from the appropriate capacity model with
   those realisations and compared with the *planned* rate for that link
   class.  The plan is defined without tuning: it is the clear-sky, zero
   pointing-error achievable rate of the same terminal at the WORST-CASE
   range of that link class -- the maximum supported ISL range, or the slant
   range at the elevation mask for a ground leg (``planned_rates``).  A
   contact closes when the realised geometry and weather beat what the
   worst-case plan assumed, which is the operational question a link plan
   actually asks;
5. the FEATURES are noisy observations of the latent state (a forecast is not
   a measurement), so there is a genuine information gap between what the
   predictor sees and what determines the label.

Feature vector (``FEATURE_NAMES``, index order is part of the contract)::

    0 climatology_prior         long-run success rate of this stratum   [-]
    1 max_elevation_deg         culmination elevation, 90 for an ISL    [deg]
    2 min_range_km              closest approach over the window        [km]
    3 duration_s                window duration                        [s]
    4 cloud_optical_depth_obs   noisy observation of latent tau         [-]
    5 visibility_km_obs         noisy observation of latent visibility  [km]
    6 pointing_jitter_urad_obs  noisy observation of pointing error     [urad]
    7 is_optical                1 for the optical terminal, else 0      [-]
    8 is_ground                 1 for a ground leg, else 0              [-]

Determinism: every array is produced from ``numpy.random.default_rng(seed)``
and the contact geometry is a pure function of the constellation definition
and the horizon, so ``generate_dataset(seed=k)`` is reproducible.  The
regression suite pins the resulting statistics (``tests/test_regression.py``).
"""

