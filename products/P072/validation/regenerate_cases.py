"""Regenerate the committed example case files from the seeded generator.

The three YAML cases under ``examples/cases/`` are generated, not hand-written,
so that they are reproducible from a seed and so that their ground-truth values
and ratios exist for the validation scripts to score against. Running this
script must leave the committed files byte-identical; it exits non-zero if it
does not, which is how a change to the generator that silently changes the
shipped cases is caught.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from _bootstrap import Tee, bootstrap, relative

bootstrap()

from downlinkpick.cases import Case, case_to_mapping  # noqa: E402
from downlinkpick.dataset import generate_instance  # noqa: E402

HEADER = (
    "# Generated by validation/regenerate_cases.py; edit that script, not this file.\n"
)

CASES = (
    (
        20261021,
        "three_pass_declared.yaml",
        dict(n_products=24, n_windows=3),
        "Twenty-four products over three passes; every value declared and every "
        "compressibility measured. The reference case for the greedy-against-exact "
        "comparison.",
    ),
    (
        20261022,
        "missing_declarations.yaml",
        dict(
            n_products=24,
            n_windows=3,
            missing_declared_fraction=0.4,
            stale_declared_fraction=0.5,
            missing_ratio_fraction=0.3,
        ),
        "Twenty-four products over three passes with 40 per cent of declared values "
        "withheld, half the remaining declarations stale, and 30 per cent of "
        "compressibilities unmeasured. The case the learned components exist for.",
    ),
    (
        20261023,
        "single_short_pass.yaml",
        dict(n_products=10, n_windows=1, capacity_fraction=0.3),
        "Ten products and one short pass carrying about thirty per cent of the queue. "
        "Small enough to enumerate exhaustively.",
    ),
)


def render(case: Case) -> str:
    """The YAML text for a case, including the generated-file header."""
    return HEADER + yaml.safe_dump(
        case_to_mapping(case), sort_keys=False, default_flow_style=None, width=96
    )


def main() -> int:
    out = Tee("regenerate_cases_output.txt")
    out.rule("downlinkpick: regenerate the committed example cases")
    out("running this script must leave the committed files byte-identical")
    out("")
    out(f"{'file':>34s} {'seed':>10s} {'bytes':>8s} {'products':>9s} {'windows':>8s} "
        f"{'unchanged':>10s}")
    failures = 0
    for seed, name, kwargs, description in CASES:
        instance = generate_instance(seed, **kwargs)
        case = Case(
            name=name.replace(".yaml", "").replace("_", "-"),
            description=description,
            inventory=instance.inventory,
            plan=instance.plan,
            autocorrelation=instance.autocorrelation,
            source=name,
        )
        text = render(case)
        target = Path("examples/cases") / name
        existing = target.read_text() if target.exists() else None
        unchanged = existing == text
        if not unchanged:
            target.write_text(text)
            failures += 1
        out(
            f"{relative(target):>34s} {seed:>10d} {len(text):8d} "
            f"{len(instance.inventory):9d} {len(instance.plan):8d} {unchanged!s:>10s}"
        )
    out("")
    if failures:
        out(f"  FAIL {failures} committed case file(s) differed and have been rewritten;")
        out("       re-run the validation scripts and the tests, and commit the new files")
    out.rule("summary")
    out(f"failures: {failures}")
    out(f"output  : {out.save()}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
