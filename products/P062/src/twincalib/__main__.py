"""Command-line interface: ``python -m twincalib``.

The only part of the package that writes to a stream. Every subcommand builds
the same objects the library API exposes and prints what the renderers in
:mod:`twincalib.report` return.

One rule shapes the whole interface: **no subcommand prints a parameter value
without the identifiability verdict for the design it came from.** ``fit`` runs
the identifiability analysis first and prints it above the estimate, and
``profile`` prints the open sides before the table. A tool that could print a
tidy six-row parameter table on its own would be a tool for producing
confident-looking numbers from data that does not support them.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence

import numpy as np

from . import __version__
from .benchmark import run_benchmark
from .fitting import CalibrationProblem, fit
from .identifiability import analyse
from .profile import profile_all
from .report import (
    render_correlation,
    render_design,
    render_fit,
    render_identifiability,
    render_profiles,
    render_sensitivity,
)
from .scenarios import DESIGN_NAMES, calibration_model, design, designs, make_dataset, truth_model
from .sensitivity import log_sensitivity

_EPILOGUE = """
Every parameter value this tool prints is accompanied by the identifiability
verdict for the design it was estimated from. A full-rank verdict is not a
statement that the parameters are determined; read the profile intervals.
All data is synthetic and generated by twincalib.scenarios. Research-grade
software: not flight-qualified, not certified, not approved for operational
aerospace use.
"""


def _build_problem(name: str, seed: int, exact: bool):
    d = design(name)
    generator = calibration_model() if exact else truth_model()
    data = make_dataset(d, seed=seed, model=generator)
    problem = CalibrationProblem(
        model=calibration_model(),
        inputs=data.inputs,
        initial_state=d.initial_state,
        channels=d.channels,
        sample_stride=d.sample_stride,
        y=data.y,
        sigma=data.sigma,
    )
    return d, data, problem


def _cmd_designs(args: argparse.Namespace) -> int:
    out = []
    for name in DESIGN_NAMES:
        out.append(render_design(designs()[name]))
        out.append("")
    sys.stdout.write("\n".join(out))
    return 0


def _cmd_identify(args: argparse.Namespace) -> int:
    d, data, _problem = _build_problem(args.design, args.seed, args.exact)
    sens = log_sensitivity(
        calibration_model(),
        d.theta_true,
        data.inputs,
        d.initial_state,
        d.channels,
        data.sigma,
        d.sample_stride,
    )
    report = analyse(sens, rank_tol=args.rank_tol, weak_ratio=args.weak_ratio)
    sys.stdout.write(render_design(d) + "\n\n")
    sys.stdout.write(render_sensitivity(sens) + "\n\n")
    sys.stdout.write(render_identifiability(report) + "\n\n")
    sys.stdout.write(
        render_correlation(report.parameter_names, report.correlation) + "\n"
    )
    return 0 if report.structurally_identifiable else 1


def _cmd_fit(args: argparse.Namespace) -> int:
    d, data, problem = _build_problem(args.design, args.seed, args.exact)
    start = np.asarray(d.theta_true, dtype=float) * float(args.start_factor)
    result = fit(problem, start, max_nfev=args.max_nfev)
    report = analyse(result.sensitivity)
    sys.stdout.write(render_design(d) + "\n\n")
    sys.stdout.write(render_identifiability(report) + "\n\n")
    sys.stdout.write(
        render_fit(
            result,
            units=calibration_model().parameter_units,
            theta_true=d.theta_true if args.show_truth else None,
        )
        + "\n\n"
    )
    sys.stdout.write(
        render_correlation(result.parameter_names, result.correlation) + "\n"
    )
    return 0 if report.structurally_identifiable and result.success else 1


def _cmd_profile(args: argparse.Namespace) -> int:
    d, data, problem = _build_problem(args.design, args.seed, args.exact)
    start = np.asarray(d.theta_true, dtype=float) * float(args.start_factor)
    result = fit(problem, start, max_nfev=args.max_nfev)
    curves = profile_all(
        problem, result, level=args.level, n_points=args.points
    )
    sys.stdout.write(render_design(d) + "\n\n")
    sys.stdout.write(render_profiles(curves) + "\n")
    return 0 if all(c.bounded for c in curves) else 1


def _cmd_residual(args: argparse.Namespace) -> int:
    d = design(args.design)
    result = run_benchmark(
        d,
        n_train=args.n_train,
        n_test=args.n_test,
        base_seed=args.seed,
        max_nfev=args.max_nfev,
    )
    sys.stdout.write(render_design(d) + "\n\n")
    sys.stdout.write(result.summary() + "\n\n")
    for cut in sorted(result.splits):
        sys.stdout.write(result.splits[cut].summary() + "\n\n")
    sys.stdout.write(result.drift.summary() + "\n\n")
    sys.stdout.write(f"fitted residual kernel: {result.residual_kernel}\n")
    sys.stdout.write(
        f"residual training samples: {result.n_training_used} used of "
        f"{result.n_training_samples} offered\n"
    )
    return 0


def build_parser() -> argparse.ArgumentParser:
    """The argument parser, exposed so that tests can inspect it."""
    parser = argparse.ArgumentParser(
        prog="python -m twincalib",
        description=(
            "Fit a digital twin, and say which parameters the data can "
            "actually pin down."
        ),
        epilog=_EPILOGUE,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--version", action="version", version=f"twincalib {__version__}")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("designs", help="list the shipped experiment designs")
    p.set_defaults(func=_cmd_designs)

    common = argparse.ArgumentParser(add_help=False)
    common.add_argument(
        "--design", default="baseline-eclipse", choices=list(DESIGN_NAMES),
        help="which experiment design to use",
    )
    common.add_argument("--seed", type=int, default=1, help="noise seed")
    common.add_argument(
        "--exact", action="store_true",
        help=(
            "generate the data from the calibration model itself, with no "
            "model-form discrepancy; the default generates it from the truth "
            "model, which the calibration model cannot reproduce"
        ),
    )

    p = sub.add_parser(
        "identify", parents=[common],
        help="local identifiability of a design, before any fitting",
    )
    p.add_argument("--rank-tol", type=float, default=1e-8)
    p.add_argument("--weak-ratio", type=float, default=1e-3)
    p.set_defaults(func=_cmd_identify)

    p = sub.add_parser(
        "fit", parents=[common],
        help="weighted least-squares fit, with the identifiability verdict above it",
    )
    p.add_argument("--start-factor", type=float, default=1.2)
    p.add_argument("--max-nfev", type=int, default=2000)
    p.add_argument("--show-truth", action="store_true", help="print the true parameters too")
    p.set_defaults(func=_cmd_fit)

    p = sub.add_parser(
        "profile", parents=[common], help="profile-likelihood intervals"
    )
    p.add_argument("--start-factor", type=float, default=1.2)
    p.add_argument("--max-nfev", type=int, default=2000)
    p.add_argument("--level", type=float, default=0.95)
    p.add_argument("--points", type=int, default=8, help="grid points each side")
    p.set_defaults(func=_cmd_profile)

    p = sub.add_parser(
        "residual",
        help="held-out benchmark of physics-only against physics plus residual",
    )
    p.add_argument(
        "--design", default="baseline-eclipse", choices=list(DESIGN_NAMES)
    )
    p.add_argument("--seed", type=int, default=4200)
    p.add_argument("--n-train", type=int, default=4)
    p.add_argument("--n-test", type=int, default=3)
    p.add_argument("--max-nfev", type=int, default=2000)
    p.set_defaults(func=_cmd_residual)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Run the CLI. Returns the process exit status.

    Exit statuses are informative, not just success or failure:

    * ``0`` -- the command ran and nothing it checked came out negative.
    * ``1`` -- the command ran and something did: a design was found not
      identifiable, a fit did not converge, or a profile interval is open. This
      is a result, not an error.
    * ``2`` -- argparse rejected the arguments.
    """
    parser = build_parser()
    args = parser.parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
