"""twincalib: fit a digital twin, and say which parameters the data can pin down.

The package is deliberately ordered so that identifiability comes first. The
intended sequence is:

1. :func:`twincalib.log_sensitivity` -- the weighted log-parameter sensitivity
   matrix of an experiment design.
2. :func:`twincalib.analyse` -- rank, condition number, the collinearity index
   and the unconstrained parameter *combinations*, written out.
3. :func:`twincalib.fit` -- weighted nonlinear least squares on the physics
   model alone, with parameter covariance and correlation. This is the baseline.
4. :func:`twincalib.profile_likelihood` -- profile intervals, which catch the
   practical non-identifiability a Hessian covariance hides.
5. :func:`twincalib.run_benchmark` -- only now, a learned residual model on top
   of the fitted physics, scored against physics alone on held-out
   trajectories, together with the measurement of how much of its improvement
   is absorbing an identifiability failure rather than finding real structure.

All data is synthetic and generated by :mod:`twincalib.scenarios` from fixed
seeds; see ``DATASET_CARD.md``. This software is research-grade. It is not
flight-qualified, not certified, and not approved for operational aerospace use.
"""

