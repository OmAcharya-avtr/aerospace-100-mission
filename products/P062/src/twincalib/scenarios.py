"""Experiment designs, truth parameters and synthetic data generation.

An *experiment design* is everything about a calibration data set except the
parameters: how long the record is, how often it is sampled, which states are
measured, what the dissipation and illumination profiles look like and how noisy
the thermometers are. Identifiability is a property of the design and the
parameters together, not of the model alone, which is why the designs are
first-class objects here.

Five designs are shipped, three of them deliberately defective:

``baseline-eclipse``
    Both nodes measured over two orbits with eclipses and a duty-cycled unit.
    All six parameters are identifiable from it.
``full-sun``
    The same record with the spacecraft in continuous sunlight. ``q_sun`` and
    ``q_par`` then enter the equations identically and only their sum is
    identifiable. The null direction is known in closed form. This is the
    required deliberately non-identifiable configuration.
``lumped-nodes``
    Only the unit is measured and the interface conductance is 16 times larger,
    so the two nodes equilibrate in 17 s against a 30 s sampling interval. The
    heat capacities are then only identifiable through their sum. This is
    *practical* non-identifiability: the sensitivity matrix has full rank, and a
    covariance from the Hessian understates the uncertainty badly.
``coarse-sampled``
    The baseline design at a 60 s sample interval instead of 30 s. Also sound;
    it exists because the profile-coverage study needs a cheaper record, and
    the identifiability verdict is checked to be unchanged.
``weak-excitation``
    Only the unit is measured and it runs at constant power. The sensitivity
    matrix still has full numerical rank and the Cramer-Rao relative standard
    deviations run to several hundred per cent: a rank test passes and the fit
    is worthless.

All data in this package is synthetic and generated by this module from fixed
seeds. No telemetry from any spacecraft was used, and none of the parameter
values is a measurement of any flight hardware; they are declared constants
chosen to put the shipped designs in a 270-300 K band at a plausible radiator
size. See ``DATASET_CARD.md``.
"""

