THETA_TRUE: tuple[float, ...] = (800.0, 4000.0, 2.5, 1.205e-8, 55.0, 18.0)
"""Declared true parameters of ``ThermalTwinModel``.

``(C1, C2, k12, h_rad, q_sun, q_par)`` in ``(J/K, J/K, W/K, W/K^4, W, W)``.

Where the magnitudes come from, so that a reader can judge them:

* ``C1 = 800 J/K`` is about 0.9 kg of aluminium alloy at
  ``c_p = 900 J/kg/K`` (Incropera and DeWitt, Table A.1, 2024 T6 at 300 K),
  i.e. a small avionics box.
* ``C2 = 4000 J/K`` is about 4.4 kg of the same alloy, i.e. a panel.
* ``k12 = 2.5 W/K`` is a bolted interface with a filler; interface conductances
  of order 1-10 W/K are ordinary for such a joint (Gilmore 2002, Chapter 1).
* ``h_rad = 1.205e-8 W/K^4`` is ``eps sigma A`` with ``eps = 0.85`` (white
  paint) and ``A = 0.25 m^2``.
* ``q_sun = 55 W`` is ``alpha S A`` with ``alpha = 0.2``, ``S = 1361 W/m^2``
  (Kopp and Lean 2011 total solar irradiance) and ``A = 0.2 m^2`` of projected
  area.
* ``q_par = 18 W`` is a declared parasitic load.

None of these is a measurement of flight hardware.
"""

LINEAR_THETA_TRUE: tuple[float, ...] = (800.0, 2.5, 40.0)
"""Declared true parameters of ``LinearNodeModel``: ``(C, k, q)`` in
``(J/K, W/K, W)``."""

TRUTH_CONDUCTANCE_SLOPE: float = 1.5
"""Dimensionless slope of the declared model-form discrepancy.

The truth model uses ``k12_eff = k12 (1 + 1.5 (T1 - 290 K)/100 K)``, i.e. the
interface conductance changes by 15 per cent per 10 K. The calibration model has
no such term and cannot represent it at any parameter value. Interface
conductance really does depend on temperature, through the bulk conductivity of
the two bodies and through the contact pressure as the joint expands
(Madhusudana 2014, Chapter 4). This linear form and this slope are *declared for
the experiment, not measured*, and 15 per cent per 10 K is at the large end of
what is plausible; it was chosen to put the resulting discrepancy clearly above
the thermometer noise (0.51 K root mean square against 0.3 K on
``baseline-eclipse``, measured in ``validation/validate_residual_output.txt``)
so that the residual model has real structure to find rather than noise.
"""

DEFAULT_SIGMA_K: float = 0.3
"""Thermometer noise standard deviation, K, independent and Gaussian.

A declared value in the range typical of a spacecraft housekeeping thermistor
chain end to end. It is not a measurement of any flight sensor, and the fitter
is told this value rather than estimating it.
"""


@dataclass(frozen=True)
class ExperimentDesign:
    """An observation design for the two-node twin.

    Attributes
    ----------
    name:
        Identifier.
    description:
        One sentence saying what is defective about the design, or that nothing
        is.
    duration:
        Record length, seconds.
    dt:
        Integration step, seconds. Also the observation interval when
        ``sample_stride`` is 1.
    sample_stride:
        Keep every n-th integration point as an observation.
    channels:
        Indices into ``ThermalTwinModel.state_names`` that are measured.
    orbit_period:
        Orbital period used for the illumination profile, seconds.
    eclipse_fraction:
        Fraction of each orbit spent in eclipse, dimensionless, in [0, 1).
    sun_constant:
        If not ``None``, the illumination fraction is held at this value for the
        whole record and the orbital profile is ignored. ``1.0`` gives the
        structurally non-identifiable ``full-sun`` design.
    duty_period:
        Period of the unit's dissipation square wave, seconds.
    duty_fraction:
        Fraction of each duty period at the high level, dimensionless.
    dissipation_high, dissipation_low:
        The two dissipation levels, W.
    initial_state:
        ``(T1, T2)`` at ``t = 0``, K. Treated as known by the fitter.
    sigma_k:
        Thermometer noise standard deviation, K.
    theta_override:
        Parameter values that differ from :data:`THETA_TRUE` for this design,
        as ``{name: value}``. ``lumped-nodes`` raises ``k12``.
    """

    name: str
    description: str
    duration: float
    dt: float
    sample_stride: int
    channels: tuple[int, ...]
    orbit_period: float
    eclipse_fraction: float
    sun_constant: float | None
    duty_period: float
    duty_fraction: float
    dissipation_high: float
    dissipation_low: float
    initial_state: tuple[float, float]
    sigma_k: float = DEFAULT_SIGMA_K
    theta_override: dict[str, float] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.dt <= 0.0 or self.duration <= self.dt:
            raise ValueError("require 0 < dt < duration")
        if self.sample_stride < 1:
            raise ValueError("sample_stride must be >= 1")
        if not self.channels:
            raise ValueError("at least one channel must be measured")
        if any(c not in (0, 1) for c in self.channels):
            raise ValueError("channels must be a subset of (0, 1)")
        if len(set(self.channels)) != len(self.channels):
            raise ValueError("channels must not repeat")
        if not 0.0 <= self.eclipse_fraction < 1.0:
            raise ValueError("eclipse_fraction must lie in [0, 1)")
        if self.sun_constant is not None and not 0.0 <= self.sun_constant <= 1.0:
            raise ValueError("sun_constant must lie in [0, 1] when given")
        if not 0.0 < self.duty_fraction < 1.0:
            raise ValueError("duty_fraction must lie in (0, 1)")
        if self.sigma_k <= 0.0:
            raise ValueError("sigma_k must be positive")
        unknown = set(self.theta_override) - set(ThermalTwinModel.parameter_names)
        if unknown:
            raise ValueError(f"theta_override names not in the model: {sorted(unknown)}")

    @property
    def n_integration_points(self) -> int:
        """Number of points on the integration grid, dimensionless."""
        return round(self.duration / self.dt) + 1

    @property
    def n_samples(self) -> int:
        """Number of observation times per channel, dimensionless."""
        return len(range(0, self.n_integration_points, self.sample_stride))

    @property
    def n_observations(self) -> int:
        """Total number of scalar observations, dimensionless."""
        return self.n_samples * len(self.channels)

    @property
    def theta_true(self) -> tuple[float, ...]:
        """Parameters of this design, in ``ThermalTwinModel`` order."""
        values = list(THETA_TRUE)
        for i, name in enumerate(ThermalTwinModel.parameter_names):
            if name in self.theta_override:
                values[i] = float(self.theta_override[name])
        return tuple(values)

    @property
    def channel_labels(self) -> tuple[str, ...]:
        """Names of the measured states."""
        return tuple(ThermalTwinModel.state_names[c] for c in self.channels)


