DESIGN_NAMES: tuple[str, ...] = tuple(_DESIGNS)
"""Shipped design names, in reporting order."""


def designs() -> dict[str, ExperimentDesign]:
    """All shipped designs, keyed by name. The returned dict is a copy."""
    return dict(_DESIGNS)


def design(name: str) -> ExperimentDesign:
    """One shipped design by name.

    Raises
    ------
    KeyError
        With the list of valid names, if ``name`` is not one of them.
    """
    try:
        return _DESIGNS[name]
    except KeyError:
        raise KeyError(f"unknown design {name!r}; valid names are {DESIGN_NAMES}") from None


def calibration_model() -> ThermalTwinModel:
    """The model the fitter assumes: no discrepancy term."""
    return ThermalTwinModel()


def truth_model(slope: float = TRUTH_CONDUCTANCE_SLOPE) -> ThermalTwinModel:
    """The model that generates the data: with the declared discrepancy term."""
    return ThermalTwinModel(conductance_slope=slope)


def linear_design(n_points: int = 121, dt: float = 30.0) -> Inputs:
    """Inputs for :class:`~twincalib.model.LinearNodeModel`.

    The linear model ignores both exogenous channels; the arrays exist only so
    that the same :class:`~twincalib.model.Inputs` container can be used.
    """
    if n_points < 2:
        raise ValueError("n_points must be >= 2")
    times = np.arange(n_points, dtype=float) * float(dt)
    return Inputs(times, np.zeros(n_points), np.zeros(n_points))


def linear_model() -> LinearNodeModel:
    """The single-node reference model with its declared sink temperature."""
    return LinearNodeModel(t_sink=280.0)


def build_inputs(d: ExperimentDesign, phase: float = 0.0) -> Inputs:
    """Exogenous inputs for a design, on its integration grid.

    Parameters
    ----------
    d:
        The design.
    phase:
        Fractional phase offset in [0, 1) applied to both the orbital and the
        duty-cycle profiles, so that different trajectories of the same design
        excite the model differently. ``0`` is the design's nominal profile.

    Returns
    -------
    Inputs
        ``times`` in s, ``dissipation`` in W, ``sun`` dimensionless.
    """
    if not 0.0 <= phase < 1.0:
        raise ValueError("phase must lie in [0, 1)")
    times = np.arange(d.n_integration_points, dtype=float) * d.dt
    duty = ((times / d.duty_period) + phase) % 1.0
    dissipation = np.where(
        duty < d.duty_fraction, d.dissipation_high, d.dissipation_low
    )
    if d.sun_constant is not None:
        sun = np.full(times.shape, float(d.sun_constant))
    else:
        orbit = ((times / d.orbit_period) + phase) % 1.0
        sun = np.where(orbit < (1.0 - d.eclipse_fraction), 1.0, 0.0)
    return Inputs(times, dissipation, sun)


@dataclass(frozen=True)
class Dataset:
    """A synthetic calibration record.

    Attributes
    ----------
    design:
        The design it was generated from.
    inputs:
        Exogenous inputs on the integration grid.
    sample_times:
        Observation times, seconds, shape ``(n_samples,)``.
    y:
        Noisy observations, K, shape ``(n_observations,)``, channel-major in the
        order of ``design.channels``.
    y_clean:
        The same observations without noise, K. Available because the data is
        synthetic; a real record has no such thing.
    sigma:
        Per-observation noise standard deviation, K, shape ``(n_observations,)``.
    theta_true:
        The parameters the data was generated from.
    phase:
        The input phase offset used.
    seed:
        The noise seed used.
    """

    design: ExperimentDesign
    inputs: Inputs
    sample_times: np.ndarray
    y: np.ndarray
    y_clean: np.ndarray
    sigma: np.ndarray
    theta_true: tuple[float, ...]
    phase: float
    seed: int

    @property
    def n_observations(self) -> int:
        """Number of scalar observations, dimensionless."""
        return int(self.y.size)

    def channel_view(self, index: int) -> np.ndarray:
        """Observations of the ``index``-th measured channel, K."""
        n = self.sample_times.size
        if not 0 <= index < len(self.design.channels):
            raise IndexError(f"channel index {index} out of range")
        return self.y[index * n : (index + 1) * n]


def make_dataset(
    d: ExperimentDesign,
    seed: int,
    phase: float = 0.0,
    theta: Sequence[float] | None = None,
    model: TwinModel | None = None,
) -> Dataset:
    """Generate one synthetic record.

    Parameters
    ----------
    d:
        The design.
    seed:
        Seed of the ``numpy.random.default_rng`` used for the thermometer noise.
    phase:
        Input phase offset, see :func:`build_inputs`.
    theta:
        Parameters to generate from. Defaults to ``d.theta_true``.
    model:
        Generating model. Defaults to :func:`truth_model`, i.e. *with* the
        declared discrepancy term, so that the calibration model is wrong in a
        declared way. Pass :func:`calibration_model` to generate data the
        calibration model can represent exactly.

    Returns
    -------
    Dataset
    """
    gen = truth_model() if model is None else model
    values = d.theta_true if theta is None else tuple(float(x) for x in theta)
    inputs = build_inputs(d, phase=phase)
    clean = gen.observe(values, inputs, d.initial_state, d.channels, d.sample_stride)
    rng = np.random.default_rng(int(seed))
    sigma = np.full(clean.shape, float(d.sigma_k))
    y = clean + rng.normal(0.0, float(d.sigma_k), size=clean.shape)
    return Dataset(
        design=d,
        inputs=inputs,
        sample_times=inputs.times[:: d.sample_stride],
        y=y,
        y_clean=clean,
        sigma=sigma,
        theta_true=values,
        phase=float(phase),
        seed=int(seed),
    )
