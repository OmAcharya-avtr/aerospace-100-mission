"""Recovery of known parameters across noise levels, with the Cramer-Rao bound.

Run: ``python examples/parameter_recovery.py``
Writes: ``screenshots/parameter_recovery.png`` and
``validation/example_parameter_recovery_output.txt``.
"""

from __future__ import annotations

import sys
from dataclasses import replace
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "validation"))
from _bootstrap import Tee, add_src_to_path  # noqa: E402

ROOT = add_src_to_path()

from twincalib import (  # noqa: E402
    CalibrationProblem,
    analyse,
    calibration_model,
    design,
    fit,
    log_sensitivity,
    make_dataset,
)

NOISE_LEVELS = (0.05, 0.15, 0.3, 0.6, 1.2)
N_REPEATS = 12
BASE_SEED = 2600


def main() -> None:
    out = Tee(ROOT / "validation" / "example_parameter_recovery_output.txt")
    model = calibration_model()
    base = design("coarse-sampled")
    names = model.parameter_names
    bias = np.zeros((len(NOISE_LEVELS), 6))
    spread = np.zeros((len(NOISE_LEVELS), 6))
    bound = np.zeros((len(NOISE_LEVELS), 6))
    out("recovery of known parameters, data generated by the calibration model")
    out(f"design {base.name}, {N_REPEATS} seeds per noise level, base seed {BASE_SEED}")
    for i, sigma in enumerate(NOISE_LEVELS):
        d = replace(base, sigma_k=sigma)
        errors = []
        for r in range(N_REPEATS):
            data = make_dataset(d, seed=BASE_SEED + 100 * i + r, model=model)
            problem = CalibrationProblem(
                model=model,
                inputs=data.inputs,
                initial_state=d.initial_state,
                channels=d.channels,
                sample_stride=d.sample_stride,
                y=data.y,
                sigma=data.sigma,
            )
            result = fit(problem, np.asarray(d.theta_true, dtype=float))
            errors.append(np.log(result.theta / np.asarray(d.theta_true, dtype=float)))
        err = np.array(errors)
        bias[i] = err.mean(axis=0)
        spread[i] = err.std(axis=0, ddof=1)
        sens = log_sensitivity(
            model,
            d.theta_true,
            data.inputs,
            d.initial_state,
            d.channels,
            sigma,
            d.sample_stride,
        )
        bound[i] = analyse(sens).relative_sd
        out("")
        out(f"sigma = {sigma:.2f} K")
        out(
            f"  {'parameter':<9}{'mean log err':>14}{'sd of log err':>15}"
            f"{'Cramer-Rao':>13}{'ratio':>8}"
        )
        for j, name in enumerate(names):
            out(
                f"  {name:<9}{bias[i, j]:>+14.6f}{spread[i, j]:>15.6f}"
                f"{bound[i, j]:>13.6f}{spread[i, j] / bound[i, j]:>8.3f}"
            )

    fig, axes = plt.subplots(1, 3, figsize=(14.0, 4.6))
    ax = axes[0]
    for j, name in enumerate(names):
        ax.loglog(NOISE_LEVELS, spread[:, j], "o-", label=name, markersize=5)
    ax.loglog(
        NOISE_LEVELS,
        spread[:, 0] * np.asarray(NOISE_LEVELS) / NOISE_LEVELS[0] / 1.0,
        "k--",
        linewidth=1.0,
        label="slope 1",
    )
    ax.set_xlabel("thermometer noise sigma [K]")
    ax.set_ylabel("sd of ln(estimate/truth)")
    ax.set_title("Spread grows linearly in the noise")
    ax.grid(alpha=0.3, which="both")
    ax.legend(fontsize=7, ncols=2)

    ax = axes[1]
    for j, name in enumerate(names):
        ax.plot(NOISE_LEVELS, spread[:, j] / bound[:, j], "o-", label=name)
    ax.axhline(1.0, color="black", linestyle="--", linewidth=1.0)
    ax.set_xscale("log")
    ax.set_xlabel("thermometer noise sigma [K]")
    ax.set_ylabel("observed spread / Cramer-Rao bound")
    ax.set_title("At 1.0 the estimator is efficient")
    ax.set_ylim(0.0, 2.5)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=7, ncols=2)

    ax = axes[2]
    for j, name in enumerate(names):
        ax.plot(NOISE_LEVELS, np.abs(bias[:, j]) / spread[:, j], "o-", label=name)
    ax.axhline(
        2.0 / np.sqrt(N_REPEATS), color="black", linestyle="--", linewidth=1.0
    )
    ax.set_xscale("log")
    ax.set_xlabel("thermometer noise sigma [K]")
    ax.set_ylabel("|mean log error| / sd")
    ax.set_title(
        f"Dashed line: two standard errors of the mean at {N_REPEATS} seeds"
    )
    ax.grid(alpha=0.3)
    ax.legend(fontsize=7, ncols=2)

    fig.tight_layout()
    target = ROOT / "screenshots" / "parameter_recovery.png"
    fig.savefig(target, dpi=130)
    plt.close(fig)
    out("")
    out(f"wrote {target.relative_to(ROOT)}")
    out.save()


if __name__ == "__main__":
    main()
