"""Shared fixtures. Built once per session because every one of them simulates."""

from __future__ import annotations

import numpy as np
import pytest

from twincalib.fitting import CalibrationProblem, fit
from twincalib.scenarios import calibration_model, design, make_dataset


def _problem(name: str, seed: int, exact: bool):
    d = design(name)
    model = calibration_model()
    data = make_dataset(d, seed=seed, model=model if exact else None)
    problem = CalibrationProblem(
        model=model,
        inputs=data.inputs,
        initial_state=d.initial_state,
        channels=d.channels,
        sample_stride=d.sample_stride,
        y=data.y,
        sigma=data.sigma,
    )
    return d, data, problem


@pytest.fixture(scope="session")
def exact_baseline():
    """``baseline-eclipse`` data generated by the calibration model itself."""
    return _problem("baseline-eclipse", seed=101, exact=True)


@pytest.fixture(scope="session")
def truth_baseline():
    """``baseline-eclipse`` data generated by the truth model, so the
    calibration model is wrong in the declared way."""
    return _problem("baseline-eclipse", seed=202, exact=False)


@pytest.fixture(scope="session")
def exact_full_sun():
    """The structurally non-identifiable design, on exact-model data."""
    return _problem("full-sun", seed=303, exact=True)


@pytest.fixture(scope="session")
def exact_baseline_fit(exact_baseline):
    """The weighted least-squares fit of ``exact_baseline``."""
    d, _data, problem = exact_baseline
    return problem, fit(problem, np.asarray(d.theta_true, dtype=float) * 1.15), d
