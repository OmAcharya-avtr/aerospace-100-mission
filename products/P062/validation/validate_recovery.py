"""Validate parameter recovery on synthetic data with known ground truth.

Run from the repository root: ``python validation/validate_recovery.py``
Writes ``validation/validate_recovery_output.txt``.

What is checked:

1. Recovery across five noise levels on a sound design, data generated by the
   calibration model itself so that the only error is sampling error. The
   observed spread of ``ln(estimate/truth)`` is compared with the Cramer-Rao
   bound (Rao 1945; Cramer 1946), which the maximum-likelihood estimator should
   attain asymptotically.
2. The same with the declared model discrepancy present, which biases the
   estimates. That bias is the reason the residual model exists and the reason
   it is dangerous.
3. Recovery on every shipped design at the declared noise level, including the
   two defective ones, so that the failure modes are in the same table as the
   successes.
4. Start-point independence: five starts spanning a factor of four must reach
   the same optimum on a sound design.
"""

from __future__ import annotations

import time
from dataclasses import replace

import numpy as np

from _bootstrap import Tee, add_src_to_path

ROOT = add_src_to_path()

from twincalib import (  # noqa: E402
    DESIGN_NAMES,
    CalibrationProblem,
    analyse,
    calibration_model,
    design,
    fit,
    log_sensitivity,
    make_dataset,
    truth_model,
)

NOISE_LEVELS = (0.05, 0.15, 0.3, 0.6, 1.2)
N_REPEATS = 16
N_DESIGN_REPEATS = 6
BASE_SEED = 7400


def _fit_one(d, seed, generator, start_factor=1.0, max_nfev=2000):
    model = calibration_model()
    data = make_dataset(d, seed=seed, model=generator)
    problem = CalibrationProblem(
        model=model,
        inputs=data.inputs,
        initial_state=d.initial_state,
        channels=d.channels,
        sample_stride=d.sample_stride,
        y=data.y,
        sigma=data.sigma,
    )
    start = np.asarray(d.theta_true, dtype=float) * start_factor
    return problem, fit(problem, start, max_nfev=max_nfev), data


def main() -> None:
    started = time.perf_counter()
    out = Tee(ROOT / "validation" / "validate_recovery_output.txt")
    out("validate_recovery.py -- recovery of known parameters")
    model = calibration_model()
    names = model.parameter_names
    base = design("coarse-sampled")
    out(f"design {base.name}, {base.n_observations} observations")
    out(f"{N_REPEATS} seeds per condition, base seed {BASE_SEED}")

    out.rule("1. Recovery across noise levels, no model discrepancy")
    out("Data generated by the calibration model, so the estimator is unbiased")
    out("up to sampling error and the spread should match the Cramer-Rao bound.")
    worst_ratio_band = (np.inf, -np.inf)
    worst_bias_z = 0.0
    for i, sigma in enumerate(NOISE_LEVELS):
        d = replace(base, sigma_k=sigma)
        errors = []
        chi2r = []
        for r in range(N_REPEATS):
            _problem, result, data = _fit_one(
                d, BASE_SEED + 100 * i + r, calibration_model()
            )
            errors.append(np.log(result.theta / np.asarray(d.theta_true, dtype=float)))
            chi2r.append(result.reduced_chi2)
        err = np.array(errors)
        bias = err.mean(axis=0)
        spread = err.std(axis=0, ddof=1)
        sens = log_sensitivity(
            model,
            d.theta_true,
            data.inputs,
            d.initial_state,
            d.channels,
            sigma,
            d.sample_stride,
        )
        bound = analyse(sens).relative_sd
        out("")
        out(f"sigma = {sigma:.2f} K   mean reduced chi2 = {float(np.mean(chi2r)):.4f}")
        out(
            f"  {'parameter':<9}{'mean log err':>14}{'sd':>12}{'Cramer-Rao':>13}"
            f"{'sd/bound':>10}{'bias z':>9}"
        )
        for j, name in enumerate(names):
            bias_z = abs(bias[j]) / (spread[j] / np.sqrt(N_REPEATS))
            worst_bias_z = max(worst_bias_z, bias_z)
            ratio = spread[j] / bound[j]
            worst_ratio_band = (
                min(worst_ratio_band[0], ratio),
                max(worst_ratio_band[1], ratio),
            )
            out(
                f"  {name:<9}{bias[j]:>+14.6f}{spread[j]:>12.6f}{bound[j]:>13.6f}"
                f"{ratio:>10.3f}{bias_z:>9.2f}"
            )
    out("")
    out(
        f"observed spread / Cramer-Rao bound over all 30 cells: "
        f"{worst_ratio_band[0]:.3f} to {worst_ratio_band[1]:.3f}"
    )
    out(
        "An sd estimated from 16 samples has a relative standard error of "
        f"1/sqrt(2*15) = {1.0 / np.sqrt(30.0):.3f},"
    )
    out("so a band of roughly 0.6 to 1.5 is what efficiency looks like at this")
    out("repeat count. The band above is reported, not asserted.")
    out(f"worst |bias| in standard errors of the mean: {worst_bias_z:.2f}")
    out(
        "verdict: "
        + (
            "PASS"
            if 0.4 < worst_ratio_band[0] and worst_ratio_band[1] < 2.0
            else "REPORTED"
        )
        + "  criterion the whole band inside (0.4, 2.0)"
    )

    out.rule("2. The same, with the declared model discrepancy present")
    out("Data generated by the truth model, which the calibration model cannot")
    out("reproduce at any parameter value. The estimator is then BIASED and the")
    out("bias does not shrink with the noise, which is the whole problem.")
    out("")
    out("Columns are the mean of ln(estimate/truth) over the seeds, per parameter.")
    out(
        f"  {'sigma [K]':>10}{'red. chi2':>12}"
        + "".join(f"{n:>11}" for n in names)
    )
    for i, sigma in enumerate(NOISE_LEVELS):
        d = replace(base, sigma_k=sigma)
        errors = []
        chi2r = []
        for r in range(N_REPEATS):
            _problem, result, _data = _fit_one(
                d, BASE_SEED + 5000 + 100 * i + r, truth_model()
            )
            errors.append(np.log(result.theta / np.asarray(d.theta_true, dtype=float)))
            chi2r.append(result.reduced_chi2)
        bias = np.array(errors).mean(axis=0)
        out(
            f"  {sigma:>10.2f}{float(np.mean(chi2r)):>12.4f}"
            + "".join(f"{b:>+11.5f}" for b in bias)
        )
    out("")
    out("The reduced chi-squared rises as the noise falls, because the model error")
    out("becomes the dominant residual: that is the signal that the model, not the")
    out("data, is the limit. The bias on q_par does not go away.")

    out.rule("3. Every shipped design at its declared noise level")
    out(f"{N_DESIGN_REPEATS} seeds each, data from the calibration model, with the")
    out("default residual-evaluation budget of 400 so that the cost of a bad")
    out("design shows up as non-convergence rather than as a long wait.")
    out("")
    out(
        f"  {'design':<18}{'converged':>10}{'worst |log err|':>17}"
        f"{'worst rel sd':>14}{'parameter':>10}"
    )
    for name in DESIGN_NAMES:
        d = design(name)
        converged = 0
        worst_err = 0.0
        worst_sd = 0.0
        worst_name = ""
        for r in range(N_DESIGN_REPEATS):
            _problem, result, _data = _fit_one(
                d, BASE_SEED + 9000 + r, calibration_model(), max_nfev=400
            )
            converged += int(result.success)
            logerr = np.abs(np.log(result.theta / np.asarray(d.theta_true, dtype=float)))
            if float(np.max(logerr)) > worst_err:
                worst_err = float(np.max(logerr))
            finite = np.where(np.isfinite(result.relative_sd), result.relative_sd, np.inf)
            k = int(np.argmax(finite))
            if float(finite[k]) > worst_sd:
                worst_sd = float(finite[k])
                worst_name = result.parameter_names[k]
        out(
            f"  {name:<18}{converged:>4d}/{N_DESIGN_REPEATS:<5d}{worst_err:>17.5f}"
            f"{worst_sd:>14.4g}{worst_name:>10}"
        )
    out("")
    out("full-sun and weak-excitation are the designs that are supposed to fail,")
    out("and they do: an infinite relative standard deviation on full-sun means")
    out("the parameter loads on the unconstrained direction, and the")
    out("weak-excitation errors run to whole factors.")

    out.rule("4. Start-point independence on a sound design")
    d = design("coarse-sampled")
    out("Five starts over a factor of four, same data (seed 7777).")
    out("")
    out(f"  {'start factor':>13}{'converged':>11}{'chi2':>14}" + "".join(f"{n:>13}" for n in names))
    thetas = []
    for factor in (0.5, 0.75, 1.0, 1.5, 2.0):
        _problem, result, _data = _fit_one(d, 7777, calibration_model(), factor)
        thetas.append(result.theta)
        out(
            f"  {factor:>13.2f}{str(result.success):>11}{result.chi2:>14.6f}"
            + "".join(f"{v:>13.6g}" for v in result.theta)
        )
    stack = np.array(thetas)
    spread = float(np.max(np.abs(np.log(stack / stack[2]))))
    out("")
    out(f"worst |ln(theta/theta at factor 1)| across starts = {spread:.3e}")
    out(f"verdict: {'PASS' if spread < 1e-3 else 'FAIL'}   tolerance 1e-3")

    out("")
    out(f"elapsed {time.perf_counter() - started:.1f} s")
    out.save()


if __name__ == "__main__":
    main()
