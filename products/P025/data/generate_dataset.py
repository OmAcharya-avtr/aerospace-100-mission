"""Regenerate the committed training dataset.

Writes three files into ``data/``:

``training_scenarios.csv``  one row per training scenario: seed, class, onset,
                            magnitude, channel
``training_features.csv``   the feature/label matrix the classifier is fitted
                            to: 16 features plus the class index and the seed
``dataset_manifest.txt``    SHA-256 of both CSVs plus the generating settings

The CSVs are redundant with this script: deleting them and rerunning
reproduces them byte for byte, because every draw is seeded.  They are
committed anyway (they are well under 1 MB) so that a reader can inspect the
training data without running anything.

    python data/generate_dataset.py
"""

from __future__ import annotations

import csv
import hashlib
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

import numpy as np

from fdiscope.evaluate import BenchmarkConfig, harvest_training_rows, run_scenarios
from fdiscope.faults import FAULT_CLASSES
from fdiscope.features import feature_names
from fdiscope.scenarios import sample_scenarios

N_TRAIN = 240
TRAIN_SEED0 = 1000
DATA = Path(__file__).resolve().parent


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    start = time.perf_counter()
    cfg = BenchmarkConfig()
    scenarios = sample_scenarios(N_TRAIN, TRAIN_SEED0)
    runs = run_scenarios(scenarios, cfg)
    features, labels = harvest_training_rows(scenarios, runs, cfg)

    scenario_path = DATA / "training_scenarios.csv"
    with scenario_path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(
            ["index", "seed", "fault_class", "onset_step", "magnitude", "channel", "n_steps"]
        )
        for sc in scenarios:
            writer.writerow(
                [
                    sc.index,
                    sc.seed,
                    sc.label.value,
                    sc.onset_step,
                    f"{sc.fault.magnitude:.12e}",
                    sc.fault.channel,
                    sc.n_steps,
                ]
            )

    feature_path = DATA / "training_features.csv"
    with feature_path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow([*feature_names(), "label_index", "label"])
        for row, label in zip(features, labels, strict=True):
            writer.writerow(
                [*(f"{v:.9e}" for v in row), int(label), FAULT_CLASSES[int(label)].value]
            )

    counts = np.bincount(labels, minlength=len(FAULT_CLASSES))
    manifest = DATA / "dataset_manifest.txt"
    lines = [
        "FDIScope 0.1.0 training dataset manifest",
        "",
        "ALL DATA IS SIMULATED.  Generated by data/generate_dataset.py from the",
        "seeded closed-loop simulator in src/fdiscope/simulate.py.  No flight",
        "telemetry and no measured spacecraft data is used anywhere.",
        "",
        f"scenarios          : {N_TRAIN}, seeds {TRAIN_SEED0}..{TRAIN_SEED0 + N_TRAIN - 1}",
        f"isolation window   : {cfg.iso_window} samples at dt = {cfg.plant.dt_s} s",
        "fault window offsets: 0, 10, 25, 50 samples after onset",
        "null window offsets : -150, -300 samples (pre-onset, genuinely fault-free)",
        f"feature rows       : {features.shape[0]} x {features.shape[1]}",
        "",
        "rows per class:",
    ]
    for fault, count in zip(FAULT_CLASSES, counts, strict=True):
        lines.append(f"  {fault.value:<32} {int(count):>6}")
    lines += [
        "",
        f"sha256 {scenario_path.name} : {sha256(scenario_path)}",
        f"sha256 {feature_path.name}  : {sha256(feature_path)}",
        f"bytes  {scenario_path.name} : {scenario_path.stat().st_size}",
        f"bytes  {feature_path.name}  : {feature_path.stat().st_size}",
        "",
        f"generated in {time.perf_counter() - start:.1f} s",
    ]
    manifest.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"wrote {scenario_path} ({scenario_path.stat().st_size} bytes)")
    print(f"wrote {feature_path} ({feature_path.stat().st_size} bytes)")
    print(f"wrote {manifest}")
    print(f"{features.shape[0]} feature rows x {features.shape[1]} features")
    per_class = dict(zip([f.value for f in FAULT_CLASSES], counts.tolist(), strict=True))
    print(f"rows per class: {per_class}")
    print(f"elapsed {time.perf_counter() - start:.1f} s")


if __name__ == "__main__":
    main()
