"""Smoke tests over the MEASURED campaign that is committed under `data/traces/`.

Every other test in this suite runs on the committed synthetic generator, so
that the suite says something about the code whether or not the measurement is
present. These tests are the exception: they load the real traces and check the
structural facts a reader of the published numbers is entitled to assume.

They are **skipped with a stated reason** when `data/traces/` is absent or
incomplete, because a missing measurement is not a code defect and turning it
into a test failure would hide the refusal that
`validation/validate_measured_*.py` exists to make visible. A skip here and a
non-zero exit there are the same fact reported in the two places it belongs.

No number is asserted to a tolerance here. The measured figures live in
`validation/`, where they are regenerated by a script and can be re-run; a
measured figure pinned in a test would have to be edited every time the
campaign is repeated, and a test that is edited to match its input is not a
test.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from powerenvelope.baselines import (
    between_run_spread,
    duty_cycle_model,
    energy_per_inference,
    floor_occupancy_regression,
    floor_power,
    ground_truth,
    rail_accounting_curve,
    run_order_rows,
)
from powerenvelope.decomposition import decompose
from powerenvelope.energy import cell_energy, interstitial_samples, sleep_energy
from powerenvelope.provenance import Origin
from powerenvelope.schema import REJECT_REASONS
from powerenvelope.trace import (
    FLOOR_CELL,
    PERMISSIVE_CELL,
    PLANNED_CELLS,
    REFERENCE_REPEATS,
    campaign_is_complete,
    load_campaign,
)
from powerenvelope.windows import extract_windows, grouped_splits

ROOT = Path(__file__).resolve().parent.parent
TRACES = ROOT / "data" / "traces"

pytestmark = pytest.mark.skipif(
    not (TRACES.is_dir() and any(TRACES.glob("power_*.csv")) and campaign_is_complete(TRACES)),
    reason=(
        "the measured campaign is not on disk at data/traces/ with its "
        "CAMPAIGN_COMPLETE marker. That is reported as a refusal by "
        "validation/validate_measured_*.py, which exit non-zero; it is not a code "
        "defect and is not turned into a test failure here."
    ),
)


@pytest.fixture(scope="module")
def measured():
    return load_campaign(TRACES, origin=Origin.MEASURED, directory_label="data/traces")


def test_the_campaign_is_complete_and_was_not_aborted(measured):
    assert measured.complete
    assert measured.manifest.get("aborted") is False
    assert not measured.manifest.get("synthetic")
    assert set(measured.cells) == set(PLANNED_CELLS)


def test_every_run_reported_a_zero_return_code(measured):
    for cell in measured.cells.values():
        assert cell.record["sampler_rc"] == 0, cell.label
        assert cell.record["monitor_rc"] == 0, cell.label


def test_the_floor_cell_ran_no_pipeline_and_has_an_empty_decisions_file(measured):
    floor = measured.require(FLOOR_CELL)
    assert not floor.has_pipeline
    assert floor.decisions is None
    assert (TRACES / "decisions_floor.csv").exists()
    assert len((TRACES / "decisions_floor.csv").read_text().splitlines()) == 1


def test_the_headline_decomposes_and_closes(measured):
    for variant in ("measured-active", "nominal-rail"):
        result = decompose(measured.require("w64_d050"), variant)
        product = result.product_of_named_factors() * result.residual_factor
        assert product == pytest.approx(result.factor, rel=1e-10, abs=0.0)
        assert result.factor > 1.0
        assert result.residual_factor == pytest.approx(
            result.accounting_factor, rel=1e-9, abs=0.0
        )


def test_the_active_and_sleep_energies_sum_to_the_whole_run(measured):
    for cell in measured.pipeline_cells():
        whole, active = cell_energy(cell)
        complement = sleep_energy(cell)
        assert active.energy_mj + complement.energy_mj == pytest.approx(
            whole.energy_mj, rel=1e-9, abs=0.0
        )


def test_no_sampler_timestamp_fell_between_two_inferences(measured):
    # The merge tolerance is half a sampler period, 25 ms, and the widest
    # inter-inference gap measured on this campaign is under a millisecond, so
    # the edge case the energy module documents did not arise. It is counted
    # rather than assumed.
    for cell in measured.pipeline_cells():
        gaps = interstitial_samples(cell)
        assert gaps.n_samples == 0, cell.label
        assert gaps.max_gap_s < 0.025, cell.label


def test_two_gate_branches_never_fired_on_this_campaign(measured):
    # A published weakness, asserted so that it cannot change silently: the
    # measured acceptance rate is a property of a gate whose no_candidate and
    # border paths were never reached. If a future campaign does reach them,
    # this test fails and the weakness statement in VALIDATION.md and
    # DATASET_CARD.md has to be revisited.
    census: dict[str, int] = {}
    for cell in measured.pipeline_cells():
        for reason, count in cell.decisions.reason_counts().items():
            census[reason] = census.get(reason, 0) + count
    assert set(census) == {"accept", "area_out", "low_score"}
    assert set(census) < set(REJECT_REASONS)
    assert census["accept"] > 0 and census["area_out"] > 0 and census["low_score"] > 0


def test_the_two_term_and_three_term_cycle_energies_agree(measured):
    # They differ only by the pipeline's loop overshoot past the declared phase
    # boundary, times the ramp's share of the cycle energy. Measured across
    # this campaign the residual is -0.010 times that overshoot and its largest
    # magnitude is 3.02e-5, on w96_d025 -- the cell whose loop overshot most.
    floor = floor_power(measured)
    worst = 0.0
    for cell in measured.pipeline_cells():
        model = duty_cycle_model(measured, cell.label, floor=floor)
        worst = max(worst, abs(model.identity_residual))
        assert abs(model.identity_residual) < 1e-4, cell.label
    assert worst > 0.0, "a residual of exactly zero everywhere would mean the two "
    "forms are the same expression, which would make this check vacuous"


def test_the_floor_regression_is_defined_and_weak(measured):
    regression = floor_occupancy_regression(measured)
    assert regression.n_seconds > 50
    assert regression.busy_max > regression.busy_min
    assert 0.0 < regression.r_squared < 0.6, (
        "the correlation is weak and that is part of the result; a strong one "
        "would mean the floor is dominated by measurable foreign load"
    )
    assert regression.intercept_mw < regression.power_mean_mw


def test_the_between_run_interval_has_positive_width(measured):
    spread = between_run_spread(measured)
    assert spread.n == 4
    assert set(spread.cells) == set(REFERENCE_REPEATS)
    assert spread.sd_mj > 0.0
    assert spread.half_width_mj > 0.0


def test_the_permissive_control_accepts_far_more(measured):
    strict = ground_truth(measured.require("w64_d050"))
    permissive = ground_truth(measured.require(PERMISSIVE_CELL))
    assert permissive.acceptance_rate > 2.0 * strict.acceptance_rate


def test_the_run_order_was_not_randomised(measured):
    # Asserted because it is a published limitation: the plan ran the floor
    # first and then the three frame dimensions in turn, so frame dimension is
    # confounded with elapsed time.
    rows = run_order_rows(measured)
    assert rows[0].cell == FLOOR_CELL
    order = [row.cell for row in rows]
    assert order.index("w48_d100") < order.index("w64_d010")
    assert order.index("w64_d100") < order.index("w96_d010")
    assert rows[-1].elapsed_s > 1500.0


def test_the_rail_accounting_ratio_is_between_zero_and_one(measured):
    rail = rail_accounting_curve(measured)
    assert len(rail.cells) == 20
    assert all(0.0 < value < 1.0 for value in rail.ratio)


def test_the_window_dataset_is_the_expected_shape(measured):
    windows = extract_windows(measured)
    assert len(windows) == 9 * 19
    assert windows.foreign_imputed > 0
    assert np.all(windows.targets > 0.0)
    for grouping, count in (("duty", 5), ("frame_dim", 3)):
        splits = grouped_splits(windows, grouping)
        assert len(splits) == count
        for _label, train, test in splits:
            assert not set(windows.cells[train]) & set(windows.cells[test])


def test_energy_per_useful_decision_exceeds_energy_per_inference_everywhere(measured):
    for cell in measured.pipeline_cells():
        assert (
            ground_truth(cell).energy_per_useful_decision_mj
            > energy_per_inference(cell).energy_mj
        ), cell.label
