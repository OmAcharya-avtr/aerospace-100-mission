"""Term-by-term recovery from synthetic residual sets with known coefficients.

Why this is the only way to verify an attribution
-------------------------------------------------
A pointing-model fit returns nine numbers. Nothing in a residual plot, a
chi-square or a confidence interval says whether those nine numbers are the
nine that generated the data: a wrong sign on one column and a compensating
error on another leave the fit quality untouched and the attribution wrong.
The only check that bears on the attribution is to generate residuals from
coefficients you chose and see whether the fit returns them.

The truth here is generated by :func:`pointmodel.geometry.exact_residuals`,
the exact composition of rotation matrices, so nothing in the generator shares
an expression with the design matrix being fitted.

Four experiments:

1. **Single-term recovery, noiseless.** One term at a time, at three
   amplitudes, over the full-sky geometry. The error left is the first-order
   truncation and nothing else, and it must scale as the square of the
   amplitude.
2. **All-term recovery, noiseless.** All nine at once, so that a sign error
   with a compensating partner would show.
3. **All-term recovery with noise, over a Monte Carlo.** The bias and the
   empirical scatter against the reported standard errors, which is the check
   that the intervals mean what they say.
4. **Recovery against the observation count**, to show the scatter falling as
   one over the square root of the count.
"""

from __future__ import annotations

import numpy as np

from _bootstrap import (
    CONFIDENCE,
    OBSERVATIONS,
    SEED,
    SIGMA_ARCSEC,
    Tee,
    bootstrap,
    environment_lines,
)

ROOT = bootstrap()

from pointmodel import synthetic, terms, wls  # noqa: E402
from pointmodel.report import format_table  # noqa: E402

AMPLITUDES = (10.0, 50.0, 200.0)
MONTE_CARLO = 300


def single_term(out: Tee) -> None:
    """Experiment 1: one term at a time, noiseless."""
    out.rule("1. single-term recovery, noiseless, full_sky geometry")
    out("The truth is generated by the exact rotation composition of equation (12)")
    out("and fitted with the first-order design matrix, so the error left is the")
    out("truncation and nothing else. Its ORDER differs from term to term, and the")
    out("order is derivable rather than measured:")
    out("")
    out("  IA, IE, TF, TS, RF -- EXACT, to rounding. IA alone is a rotation about the")
    out("    untilted vertical by exactly IA, so the beam is the nominal beam at")
    out("    azimuth A + IA and dX = IA cos(E) with no remainder. IE, TF, TS and RF")
    out("    enter only through the effective elevation of equation (13), so the beam")
    out("    is the nominal beam at elevation E + dE_el, giving dE = dE_el and dX = 0")
    out("    with no remainder. These five have NO truncation at all and their error")
    out("    must stay at machine precision and must NOT grow with the amplitude.")
    out("  AN, AW -- QUADRATIC. A finite rotation of a unit vector departs from its")
    out("    first-order approximation at second order, and no other column absorbs")
    out("    the departure, so the coefficient error scales as the square.")
    out("  CA, NPAE -- CUBIC. Both appear only in the cross-elevation block, and")
    out("    there the exact expressions are")
    out("        dX(CA)   = cos(E) arctan(tan(CA) / cos(E)) = CA - (CA^3/3) tan^2(E) + ...")
    out("        dX(NPAE) = cos(E) arctan(sin(NPAE) tan(E)) = NPAE sin(E) + O(NPAE^3)")
    out("    so the second-order part of their effect falls in the elevation block,")
    out("    where the elevation-side columns absorb it, and what is left in the")
    out("    coefficient is third order.")
    out("")
    out("The amplitude ratios below are 5 and 4, so quadratic gives 25 and 16 and")
    out("cubic gives 125 and 64.")
    out("")
    EXACT = {"IA", "IE", "TF", "TS", "RF"}
    QUADRATIC = {"AN", "AW"}
    rows = []
    orders_ok = True
    exact_ok = True
    for name in terms.TERM_NAMES:
        errors = []
        for amplitude in AMPLITUDES:
            residuals = synthetic.generate(
                "full_sky",
                OBSERVATIONS,
                coefficients={name: amplitude},
                sigma_arcsec=0.0,
                seed=SEED,
            )
            result = wls.fit(residuals.design, residuals.observed, 1.0)
            errors.append(
                float(
                    abs(
                        result.coefficients[terms.TERM_INDEX[name]]
                        - residuals.coefficients[terms.TERM_INDEX[name]]
                    )
                )
            )
        ratio_one = errors[1] / errors[0] if errors[0] > 0 else float("inf")
        ratio_two = errors[2] / errors[1] if errors[1] > 0 else float("inf")
        if name in EXACT:
            order = "exact"
            if max(errors) > 1e-9:
                exact_ok = False
        elif name in QUADRATIC:
            order = "quadratic"
            if not (20.0 < ratio_one < 31.0 and 13.0 < ratio_two < 20.0):
                orders_ok = False
        else:
            order = "cubic"
            if not (90.0 < ratio_one < 160.0 and 50.0 < ratio_two < 80.0):
                orders_ok = False
        rows.append(
            [
                name,
                order,
                *[f"{value:.3e}" for value in errors],
                f"{ratio_one:.2f}",
                f"{ratio_two:.2f}",
            ]
        )
    out(
        format_table(
            [
                "term",
                "derived order",
                *[f'|err| at {amplitude:g}"' for amplitude in AMPLITUDES],
                "ratio 50/10",
                "ratio 200/50",
            ],
            rows,
        )
    )
    out("")
    out.check(
        "every single-term recovery error is below 0.05 arcsec at 50 arcsec amplitude",
        all(float(row[3]) < 0.05 for row in rows),
    )
    out.check(
        "the five terms with no truncation stay at machine precision at every amplitude",
        exact_ok,
        "max |error| below 1e-9 arcsec for IA, IE, TF, TS, RF",
    )
    out.check(
        "AN and AW scale quadratically and CA and NPAE cubically, as derived",
        orders_ok,
        "ratios inside [20, 31] and [13, 20] for quadratic, [90, 160] and [50, 80] for cubic",
    )


def all_terms(out: Tee) -> None:
    """Experiment 2: all nine at once, noiseless."""
    out.rule("2. all-term recovery, noiseless, every declared geometry")
    out("A sign error on one column with a compensating error on another leaves the")
    out("fit quality untouched, so all nine terms are fitted together here.")
    out("")
    rows = []
    for name in sorted(synthetic.GEOMETRIES):
        residuals = synthetic.generate(name, OBSERVATIONS, sigma_arcsec=0.0, seed=SEED)
        result = wls.fit(residuals.design, residuals.observed, 1.0)
        error = np.abs(result.coefficients - residuals.coefficients)
        prediction = residuals.design @ (result.coefficients - residuals.coefficients)
        rows.append(
            [
                name,
                str(result.rank),
                f"{float(np.max(error)):.4e}",
                f"{float(np.sqrt(np.mean(prediction**2))):.4e}",
                f"{result.rms_arcsec:.4e}",
            ]
        )
    out(
        format_table(
            [
                "geometry",
                "rank at rcond 1e-12",
                "max |coefficient error| arcsec",
                "predicted sky rms of the error arcsec",
                "post-fit residual rms arcsec",
            ],
            rows,
        )
    )
    out("")
    out("The rank column is the numerical rank of the whitened design matrix at the")
    out("solver's rcond of 1e-12, not the identifiability verdict, whose declared")
    out("threshold is 1e-3 on the singular value ratio. narrow_el has full numerical")
    out("rank and is still refused: its smallest ratio is 1.5e-6, which is above the")
    out("solver's cut and three orders of magnitude below the identifiability one.")
    out("")
    out("The coefficient error is large where the geometry is restricted and the predicted")
    out("sky error is small everywhere: a rank-deficient geometry reproduces the")
    out("residual field it was given and attributes it wrongly. That is the whole")
    out("problem this product addresses, and it is visible in the two columns above.")
    out("")
    full_sky = next(row for row in rows if row[0] == "full_sky")
    out.check(
        "full_sky recovers every term to better than 0.5 arcsec",
        float(full_sky[2]) < 0.5,
        f"max |error| = {full_sky[2]} arcsec",
    )
    out.check(
        "every geometry reproduces the residual field to better than 0.5 arcsec rms",
        all(float(row[3]) < 0.5 for row in rows),
    )
    out.check(
        "a rank-deficient geometry has a large coefficient error",
        all(
            float(row[2]) > 5.0
            for row in rows
            if int(row[1]) < terms.N_TERMS
        ),
        "which is why the per-term split is refused there",
    )


def monte_carlo(out: Tee) -> None:
    """Experiment 3: bias, scatter and interval coverage over noise realisations."""
    out.rule(
        f"3. recovery with noise, {MONTE_CARLO} realisations, full_sky, "
        f"sigma = {SIGMA_ARCSEC:g} arcsec"
    )
    out("The geometry is held fixed and only the noise is redrawn, so what is measured")
    out("is a property of the geometry. The reported standard errors are compared with")
    out("the empirical scatter, which is the check that the intervals mean what they")
    out("say; and the interval coverage is compared with its declared level.")
    out("")
    base = synthetic.generate(
        "full_sky", OBSERVATIONS, sigma_arcsec=SIGMA_ARCSEC, seed=SEED
    )
    estimates = np.empty((MONTE_CARLO, terms.N_TERMS))
    covered = np.zeros(terms.N_TERMS, dtype=int)
    reported = None
    for trial in range(MONTE_CARLO):
        realisation = synthetic.generate(
            "full_sky",
            OBSERVATIONS,
            sigma_arcsec=SIGMA_ARCSEC,
            seed=SEED,
            noise_seed=100_000 + trial,
        )
        result = wls.fit(
            realisation.design,
            realisation.observed,
            SIGMA_ARCSEC,
            confidence_level=CONFIDENCE,
        )
        estimates[trial] = result.coefficients
        inside = np.logical_and(
            result.confidence_intervals[:, 0] <= realisation.coefficients,
            realisation.coefficients <= result.confidence_intervals[:, 1],
        )
        covered += inside.astype(int)
        if reported is None:
            reported = result.standard_errors
    assert reported is not None
    bias = np.mean(estimates, axis=0) - base.coefficients
    scatter = np.std(estimates, axis=0, ddof=1)
    coverage = covered / MONTE_CARLO
    rows = []
    for index, name in enumerate(terms.TERM_NAMES):
        rows.append(
            [
                name,
                f"{base.coefficients[index]:.4f}",
                f"{float(bias[index]):+.4f}",
                f"{float(reported[index]):.4f}",
                f"{float(scatter[index]):.4f}",
                f"{float(scatter[index] / reported[index]):.4f}",
                f"{float(coverage[index]):.4f}",
            ]
        )
    out(
        format_table(
            [
                "term",
                "truth arcsec",
                "bias arcsec",
                "reported se",
                "empirical sd",
                "sd / se",
                f"{100 * CONFIDENCE:g}% coverage",
            ],
            rows,
        )
    )
    out("")
    # The sample standard deviation over 300 trials has a relative standard
    # error of 1 / sqrt(2 * 299) = 0.0409, so a four-sigma band on sd/se is
    # [0.836, 1.164]. The band is derived, not chosen.
    relative_error = 1.0 / np.sqrt(2.0 * (MONTE_CARLO - 1))
    low, high = 1.0 - 4.0 * relative_error, 1.0 + 4.0 * relative_error
    out(
        f"The four-sigma band on sd/se at {MONTE_CARLO} trials is "
        f"[{low:.4f}, {high:.4f}], from the relative standard error "
        f"1/sqrt(2(n-1)) = {relative_error:.4f} of a sample standard deviation."
    )
    out.check(
        "every reported standard error matches the empirical scatter",
        bool(np.all((scatter / reported > low) & (scatter / reported < high))),
        f"worst sd/se = {float(np.max(np.abs(scatter / reported - 1.0)) + 1.0):.4f}",
    )
    out.check(
        "every bias is below a third of the reported standard error",
        bool(np.all(np.abs(bias) < reported / 3.0)),
        f"worst |bias|/se = {float(np.max(np.abs(bias) / reported)):.4f}",
    )
    # Coverage of a 95 per cent interval over 300 trials has a standard error
    # of sqrt(0.95 * 0.05 / 300) = 0.0126, so a four-sigma band is
    # [0.8997, 1.0003].
    coverage_error = float(np.sqrt(CONFIDENCE * (1.0 - CONFIDENCE) / MONTE_CARLO))
    out(
        f"The four-sigma band on the coverage is "
        f"[{CONFIDENCE - 4 * coverage_error:.4f}, "
        f"{min(1.0, CONFIDENCE + 4 * coverage_error):.4f}]."
    )
    out.check(
        f"every interval covers the truth at its declared {100 * CONFIDENCE:g} per cent",
        bool(np.all(coverage > CONFIDENCE - 4.0 * coverage_error)),
        f"worst coverage = {float(np.min(coverage)):.4f}",
    )


def against_count(out: Tee) -> None:
    """Experiment 4: scatter against the observation count."""
    out.rule("4. scatter against the observation count, full_sky")
    out("Doubling the pointings must divide the standard error by sqrt(2). Measured")
    out("on the reported standard errors, which is a statement about the design and")
    out("needs no Monte Carlo.")
    out("")
    counts = (75, 150, 300, 600, 1200)
    rows = []
    previous = None
    ratios_ok = True
    for count in counts:
        residuals = synthetic.generate(
            "full_sky", count, sigma_arcsec=SIGMA_ARCSEC, seed=SEED
        )
        result = wls.fit(residuals.design, residuals.observed, SIGMA_ARCSEC)
        worst = float(np.max(result.standard_errors))
        ratio = previous / worst if previous is not None else float("nan")
        rows.append(
            [
                str(count),
                f"{worst:.4f}",
                f"{result.condition_number:.4f}",
                "-" if previous is None else f"{ratio:.4f}",
            ]
        )
        if previous is not None and not 1.25 < ratio < 1.60:
            ratios_ok = False
        previous = worst
    out(
        format_table(
            ["observations", "largest se arcsec", "condition number", "se ratio to previous"],
            rows,
        )
    )
    out("")
    out.check(
        "the largest standard error falls as the square root of the count",
        ratios_ok,
        "every doubling ratio inside [1.25, 1.60] around sqrt(2) = 1.4142",
    )


def main() -> int:
    out = Tee("validate_term_recovery_output.txt")
    out.rule("pointmodel -- term-by-term recovery from known coefficients")
    for line in environment_lines():
        out(line)
    out("")
    out(f"declared sigma        : {SIGMA_ARCSEC:g} arcsec per residual row")
    out(f"declared observations : {OBSERVATIONS}")
    out(f"declared geometry seed: {SEED}")
    out(f"declared confidence   : {100 * CONFIDENCE:g} per cent")
    truth_text = ", ".join(
        f"{name}={value:g}" for name, value in synthetic.NOMINAL_COEFFICIENTS.items()
    )
    out(f"generating truth      : {truth_text}")
    out("")
    out("The generating coefficients are declared test values in pointmodel.synthetic.")
    out("No number in this repository is a measurement of any real instrument.")
    single_term(out)
    all_terms(out)
    monte_carlo(out)
    against_count(out)
    path = out.save()
    print(f"\nwritten: {path}")
    return 1 if out.failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
