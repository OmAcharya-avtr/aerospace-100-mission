"""Synthetic residual sets from known coefficients, and the declared geometries.

Why the truth is generated by the exact model
---------------------------------------------
A term-by-term recovery test is only evidence if the data were not produced by
the algebra being tested. Every residual set here is generated by
:func:`pointmodel.geometry.exact_residuals`, the exact composition of rotation
matrices, and is then fitted with the first-order design matrix of
:mod:`pointmodel.terms`. The two share no expressions. A sign error or a wrong
trigonometric factor in a design-matrix column shows up as a recovery failure,
and the residual bias left by the first-order truncation is bounded by
equation (16).

``generate(..., linear_truth=True)`` generates from the design matrix instead.
It exists for one purpose: to separate a recovery error caused by the
truncation from a recovery error caused by the geometry, by removing the
truncation. It is never the default.

The declared geometries
-----------------------
Five observation geometries, each a deliberate experiment. Azimuths and
elevations are in **radians** inside the package and are declared in degrees
here.

==================  =========================================================
name                what it is, and what it is for
==================  =========================================================
``full_sky``        Azimuth uniform on [0, 360), elevation uniform on
                    [15, 80] degrees. A well-scheduled pointing run. The
                    reference case: all nine terms separable, with the
                    flexure-refraction direction weakly determined.
``narrow_el``       Azimuth uniform on [0, 360), elevation uniform on
                    [43, 47] degrees. A run confined to one elevation band,
                    which happens when a mission tracks a single orbital
                    regime. Makes ``IA``/``CA``/``NPAE`` and
                    ``IE``/``TF``/``TS``/``RF`` mutually unidentifiable.
``single_az``       Azimuth fixed at 135 degrees, elevation uniform on
                    [15, 80] degrees. A single meridian-like sweep. Exactly
                    rank deficient by two: ``AN``, ``AW`` and ``NPAE`` cannot
                    be separated from each other or from ``IE``.
``two_az``          Azimuth drawn from {90, 270} degrees, elevation uniform on
                    [15, 80]. Two opposed cuts. Included because it looks as
                    restricted as ``single_az`` and is not: two azimuths
                    separate a tilt completely, and the measured condition
                    number is within a factor of two of ``full_sky``. A
                    geometry cannot be judged by how few pointings it has.
``low_el``          Azimuth uniform on [0, 360), elevation uniform on
                    [8, 25] degrees. A horizon-hugging run, where the
                    refraction column is largest and the flexure column is
                    nearly flat.
==================  =========================================================

Outliers
--------
``outlier_fraction`` of observations are given an acquisition-failure offset
instead of Gaussian noise: a displacement of ``outlier_arcsec`` in a uniformly
random direction on the sky, applied to **both** components of that
observation. This is the structure of a real failed acquisition — the beam was
on the wrong place, not on the right place with a noisier readout — and it is
the structure RANSAC's observation-wise sampling in :mod:`pointmodel.robust`
is built for. Which observations are outliers is returned, so every negative
control in ``validation/`` can be anchored on the truth rather than on an
output.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .geometry import exact_residuals
from .refraction import STANDARD_PRESSURE_HPA, STANDARD_TEMPERATURE_C
from .terms import (
    N_TERMS,
    TERM_NAMES,
    coefficients_from_mapping,
    design_matrix,
    stack_residuals,
)

__all__ = [
    "GEOMETRIES",
    "NOMINAL_COEFFICIENTS",
    "ResidualSet",
    "geometry",
    "generate",
]

#: The declared geometries: (azimuth spec, elevation range in degrees).
#: ``azimuth`` is either ``"uniform"``, a single angle in degrees, or a tuple of
#: angles in degrees drawn with equal probability.
GEOMETRIES: dict[str, dict[str, object]] = {
    "full_sky": {"azimuth": "uniform", "elevation_deg": (15.0, 80.0)},
    "narrow_el": {"azimuth": "uniform", "elevation_deg": (43.0, 47.0)},
    "single_az": {"azimuth": 135.0, "elevation_deg": (15.0, 80.0)},
    "two_az": {"azimuth": (90.0, 270.0), "elevation_deg": (15.0, 80.0)},
    "low_el": {"azimuth": "uniform", "elevation_deg": (8.0, 25.0)},
}

#: A plausible but entirely invented set of coefficients, arcseconds. The
#: magnitudes are typical of a large alt-azimuth antenna before correction: tens
#: of arcseconds of encoder index error, a few arcseconds of axis tilt, tens of
#: arcseconds of flexure, and a refraction coefficient near the 59.7 arcsec that
#: equation (1) gives at 45 degrees under standard conditions. **No number here
#: is taken from a published pointing run**; they are declared test values and
#: nothing in this repository treats them as measurements of any real
#: instrument.
NOMINAL_COEFFICIENTS: dict[str, float] = {
    "IA": -45.0,
    "IE": 30.0,
    "CA": 12.0,
    "AN": -8.0,
    "AW": 5.0,
    "NPAE": 20.0,
    "TF": -25.0,
    "TS": 6.0,
    "RF": 58.0,
}


@dataclass(frozen=True)
class ResidualSet:
    """A synthetic pointing run with complete ground truth.

    Attributes
    ----------
    name
        The geometry name.
    azimuth_rad, elevation_rad
        Length-``n`` observation directions, radians.
    design
        ``(2n, 9)`` stacked design matrix, dimensionless.
    observed
        Length-``2n`` stacked residuals, arcseconds: truth plus noise plus
        outliers.
    truth_residuals
        Length-``2n`` noiseless residuals from the exact model, arcseconds.
    coefficients
        Length-9 generating coefficients, arcseconds. The ground truth.
    sigma_arcsec
        The declared per-row noise standard deviation, arcseconds.
    outlier_mask
        Length-``n`` boolean over **observations**: which acquisitions failed.
        True ground truth, not an estimate.
    row_outlier_mask
        Length-``2n`` boolean over rows, the same information stacked.
    outlier_arcsec
        Magnitude of each injected failure, arcseconds.
    linear_truth
        Whether ``truth_residuals`` came from the design matrix (True) or from
        the exact rotation model (False, the default).
    seed
        The seed used.
    """

    name: str
    azimuth_rad: np.ndarray
    elevation_rad: np.ndarray
    design: np.ndarray
    observed: np.ndarray
    truth_residuals: np.ndarray
    coefficients: np.ndarray
    sigma_arcsec: float
    outlier_mask: np.ndarray
    row_outlier_mask: np.ndarray
    outlier_arcsec: float
    linear_truth: bool
    seed: int

    @property
    def n_observations(self) -> int:
        """Number of observations, half the number of residual rows."""
        return int(self.azimuth_rad.size)

    def truth_mapping(self) -> dict[str, float]:
        """Generating coefficients as a name-to-arcsecond dict."""
        return {name: float(self.coefficients[i]) for i, name in enumerate(TERM_NAMES)}


def geometry(
    name: str, n_observations: int, seed: int = 20260101
) -> tuple[np.ndarray, np.ndarray]:
    """Draw one of :data:`GEOMETRIES`. Returns ``(azimuth_rad, elevation_rad)``.

    The draw is deterministic in ``seed`` and independent of the noise draw in
    :func:`generate`, so a geometry can be held fixed while noise is redrawn.
    That separation is what makes the Monte Carlo in
    ``validation/validate_identifiability.py`` a statement about the geometry.
    """
    if name not in GEOMETRIES:
        raise ValueError(
            f"unknown geometry {name!r}; declared geometries are {sorted(GEOMETRIES)}"
        )
    if n_observations < N_TERMS:
        raise ValueError(
            f"{n_observations} observations cannot constrain {N_TERMS} terms; "
            f"at least {N_TERMS} are required"
        )
    spec = GEOMETRIES[name]
    rng = np.random.default_rng(seed)
    low, high = spec["elevation_deg"]  # type: ignore[misc]
    elevation = np.deg2rad(rng.uniform(low, high, n_observations))
    azimuth_spec = spec["azimuth"]
    if azimuth_spec == "uniform":
        azimuth = rng.uniform(0.0, 2.0 * np.pi, n_observations)
    elif isinstance(azimuth_spec, tuple):
        azimuth = np.deg2rad(rng.choice(np.asarray(azimuth_spec, dtype=float), n_observations))
    else:
        azimuth = np.full(n_observations, np.deg2rad(float(azimuth_spec)))  # type: ignore[arg-type]
    return azimuth, elevation


def generate(
    name: str = "full_sky",
    n_observations: int = 300,
    coefficients: dict[str, float] | np.ndarray | None = None,
    sigma_arcsec: float = 2.0,
    outlier_fraction: float = 0.0,
    outlier_arcsec: float = 300.0,
    seed: int = 20260101,
    noise_seed: int | None = None,
    linear_truth: bool = False,
    pressure_hpa: float = STANDARD_PRESSURE_HPA,
    temperature_c: float = STANDARD_TEMPERATURE_C,
) -> ResidualSet:
    """Build a synthetic residual set with known coefficients.

    Parameters
    ----------
    name
        One of :data:`GEOMETRIES`.
    n_observations
        Number of pointings; the residual vector has twice this length.
    coefficients
        Generating coefficients in arcseconds, as a name-to-value dict or a
        length-9 vector. Defaults to :data:`NOMINAL_COEFFICIENTS`.
    sigma_arcsec
        Gaussian noise standard deviation per residual row, arcseconds. Must be
        non-negative; zero gives a noiseless set, which the recovery tests use.
    outlier_fraction
        Fraction of observations given an acquisition-failure offset, in
        ``[0, 1)``. The count is ``floor(fraction * n)``.
    outlier_arcsec
        Magnitude of each failure, arcseconds.
    seed
        Seed for the geometry and for the outlier placement.
    noise_seed
        Separate seed for the Gaussian noise. Defaults to ``seed + 1``. Pass it
        explicitly to redraw noise over a fixed geometry.
    linear_truth
        Generate the truth from the design matrix rather than from the exact
        rotation model. Not the default; see the module docstring.
    pressure_hpa, temperature_c
        Site conditions for the refraction column.

    Returns
    -------
    ResidualSet
    """
    if sigma_arcsec < 0.0:
        raise ValueError(f"sigma_arcsec must be non-negative, got {sigma_arcsec}")
    if not 0.0 <= outlier_fraction < 1.0:
        raise ValueError(f"outlier_fraction must lie in [0, 1), got {outlier_fraction}")
    if outlier_arcsec < 0.0:
        raise ValueError(f"outlier_arcsec must be non-negative, got {outlier_arcsec}")
    if coefficients is None:
        theta = coefficients_from_mapping(NOMINAL_COEFFICIENTS)
    elif isinstance(coefficients, dict):
        theta = coefficients_from_mapping(coefficients)
    else:
        theta = np.asarray(coefficients, dtype=float)
        if theta.shape != (N_TERMS,):
            raise ValueError(
                f"coefficients vector must have shape ({N_TERMS},), got {theta.shape}"
            )
        if not np.all(np.isfinite(theta)):
            raise ValueError("coefficients contain a non-finite value")

    azimuth, elevation = geometry(name, n_observations, seed)
    cross_block, elev_block = design_matrix(azimuth, elevation, pressure_hpa, temperature_c)
    design = stack_residuals(cross_block, elev_block)
    if linear_truth:
        truth = design @ theta
    else:
        cross_truth, elev_truth = exact_residuals(
            azimuth, elevation, theta, pressure_hpa, temperature_c
        )
        truth = np.concatenate([cross_truth, elev_truth])

    noise_rng = np.random.default_rng(seed + 1 if noise_seed is None else noise_seed)
    observed = truth + (
        noise_rng.normal(0.0, sigma_arcsec, truth.size) if sigma_arcsec > 0.0 else 0.0
    )

    outlier_mask = np.zeros(n_observations, dtype=bool)
    count = int(np.floor(outlier_fraction * n_observations))
    if count > 0:
        place_rng = np.random.default_rng(seed + 2)
        chosen = place_rng.choice(n_observations, size=count, replace=False)
        outlier_mask[chosen] = True
        angle = place_rng.uniform(0.0, 2.0 * np.pi, count)
        observed[chosen] += outlier_arcsec * np.cos(angle)
        observed[chosen + n_observations] += outlier_arcsec * np.sin(angle)

    return ResidualSet(
        name=name,
        azimuth_rad=azimuth,
        elevation_rad=elevation,
        design=design,
        observed=observed,
        truth_residuals=truth,
        coefficients=theta,
        sigma_arcsec=float(sigma_arcsec),
        outlier_mask=outlier_mask,
        row_outlier_mask=np.concatenate([outlier_mask, outlier_mask]),
        outlier_arcsec=float(outlier_arcsec),
        linear_truth=bool(linear_truth),
        seed=int(seed),
    )
