"""pointmodel: decompose a pointing error budget and say what cannot be split.

What this package is
--------------------
A pointing model is a linear fit with a known design matrix. Nine standard
alt-azimuth terms — two encoder index offsets, a collimation error, two
azimuth-axis tilt components, an axis non-perpendicularity, two gravitational
flexure terms and an atmospheric refraction term — are fitted to measured
cross-elevation and elevation residuals by weighted least squares, with a full
covariance, a confidence interval on every term, a condition number and a
per-term variance inflation factor.

The part that matters is the refusal. Over a restricted observing geometry —
a narrow elevation band, a single azimuth sweep — standard terms become
mutually unidentifiable, and least squares returns one specific split anyway,
with formal standard errors attached. This package performs a rank analysis on
the singular value decomposition of the weighted design matrix, names the
near-null directions in terms of the physical coefficients, refuses to report a
per-term split along them, and reports the identifiable linear **combinations**
instead.

There is deliberately **no learned component**. The problem is a linear fit
whose entire difficulty is conditioning; the correct answer to a restricted
geometry is a rank analysis, and a model fitted here would predict a confident
split exactly where no split exists.

The public surface
------------------
Start with :func:`pointmodel.budget.decompose`, re-exported here, and with
:func:`pointmodel.report.render_budget` to print its result. Everything else is
a part of that pipeline that is useful on its own:

- :mod:`pointmodel.terms` — the term set, its derivations and the design matrix.
- :mod:`pointmodel.refraction` — Bennett's formula and an independent ray trace.
- :mod:`pointmodel.geometry` — an exact rotation-composition forward model and
  the bound that checks the design matrix against it.
- :mod:`pointmodel.wls` — weighted least squares through the SVD, and the
  normal-equation form kept only to demonstrate its failure.
- :mod:`pointmodel.identifiability` — the rank analysis.
- :mod:`pointmodel.robust` — Huber and RANSAC, and their disagreement with
  least squares as a reported diagnostic.
- :mod:`pointmodel.synthetic` — residual sets with known coefficients.

Status and safety
-----------------
Research grade. Not flight-qualified, not certified, not approved for
operational aerospace use. Every number in this repository is measured against
synthetic residual sets generated by this package's own exact rotation model;
no measurement of any real instrument appears anywhere in it.
"""

