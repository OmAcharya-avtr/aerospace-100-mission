"""Scenario generation, the committed file, and the train/test split."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

from acqsearch import (
    PARAMETER_RANGES,
    build_environment,
    generate_scenarios,
    load_scenarios,
    save_scenarios,
    split_scenarios,
)
from acqsearch.scenarios import THRESHOLD_RANGE

DATA = Path(__file__).resolve().parents[1] / "data" / "scenarios.json"


def test_generation_is_deterministic():
    a = generate_scenarios(25, 20261016)
    b = generate_scenarios(25, 20261016)
    assert a == b


def test_a_different_seed_gives_different_scenarios():
    a = generate_scenarios(25, 20261016)
    b = generate_scenarios(25, 20261017)
    assert a != b


def test_every_parameter_lies_inside_its_declared_range():
    for scenario in generate_scenarios(200, 20261016):
        assert PARAMETER_RANGES["sigma_rad"][0] <= scenario.sigma_rad
        assert scenario.sigma_rad <= PARAMETER_RANGES["sigma_rad"][1]
        low, high = PARAMETER_RANGES["beam_divergence_rad"]
        assert low <= scenario.beam_divergence_rad <= high
        ratio = scenario.detector_fov_rad / scenario.beam_divergence_rad
        assert PARAMETER_RANGES["fov_ratio"][0] <= ratio <= PARAMETER_RANGES["fov_ratio"][1]
        assert THRESHOLD_RANGE[0] <= scenario.threshold_counts <= THRESHOLD_RANGE[1]
        assert PARAMETER_RANGES["dwell_s"][0] <= scenario.dwell_s <= PARAMETER_RANGES["dwell_s"][1]
        assert 0.0 <= scenario.rytov_variance <= PARAMETER_RANGES["rytov_variance"][1]


def test_scenario_ids_are_consecutive_from_zero():
    scenarios = generate_scenarios(40, 1)
    assert [s.scenario_id for s in scenarios] == list(range(40))


def test_round_trip_through_json(tmp_path):
    scenarios = generate_scenarios(17, 5)
    path = tmp_path / "scenarios.json"
    save_scenarios(scenarios, path)
    assert load_scenarios(path) == scenarios


def test_load_rejects_an_unknown_format(tmp_path):
    path = tmp_path / "bad.json"
    path.write_text(json.dumps({"format": "something-else", "scenarios": []}))
    with pytest.raises(ValueError, match="format"):
        load_scenarios(path)


def test_the_committed_file_is_exactly_what_the_generator_produces(tmp_path):
    # data/scenarios.json is regenerated by data/regenerate_data.py with
    # N = 300 and seed 20261016. This asserts the committed bytes match.
    regenerated = tmp_path / "scenarios.json"
    save_scenarios(generate_scenarios(300, 20261016), regenerated)
    assert regenerated.read_text() == DATA.read_text()


def test_the_committed_file_is_small_enough_to_commit():
    assert DATA.stat().st_size < 1_000_000


def test_split_is_disjoint_and_covers_everything():
    scenarios = generate_scenarios(100, 3)
    train, test = split_scenarios(scenarios, 0.65)
    assert len(train) == 65
    assert len(test) == 35
    assert not {s.scenario_id for s in train} & {s.scenario_id for s in test}
    assert {s.scenario_id for s in train} | {s.scenario_id for s in test} == set(range(100))


def test_split_rejects_a_fraction_that_empties_a_side():
    scenarios = generate_scenarios(10, 3)
    with pytest.raises(ValueError, match="train_fraction"):
        split_scenarios(scenarios, 0.0)
    with pytest.raises(ValueError, match="train_fraction"):
        split_scenarios(scenarios, 1.0)
    with pytest.raises(ValueError, match="empty"):
        split_scenarios(scenarios, 0.01)


def test_generate_rejects_a_non_positive_count():
    with pytest.raises(ValueError, match="n must be"):
        generate_scenarios(0, 1)


def test_build_environment_returns_all_four_orders():
    scenario = generate_scenarios(1, 20261016)[0]
    environment, orders = build_environment(scenario)
    assert sorted(orders) == ["lissajous", "random_restart", "raster", "spiral"]
    for order in orders.values():
        assert np.array_equal(np.sort(order), np.arange(environment.grid.n_cells))


def test_build_environment_sets_the_deadline_to_three_nominal_passes():
    scenario = generate_scenarios(1, 20261016)[0]
    environment, _orders = build_environment(scenario)
    assert environment.deadline_s == pytest.approx(3.0 * environment.nominal_period_s, rel=1e-12)
    assert np.all(environment.cell_detection > 0.0)
    assert np.all(environment.cell_detection <= 1.0)


def test_scenario_builders_return_consistent_objects():
    scenario = generate_scenarios(1, 20261016)[0]
    assert scenario.uncertainty().sigma_rad == scenario.sigma_rad
    assert scenario.geometry().beam_divergence_rad == scenario.beam_divergence_rad
    assert scenario.detector().threshold_counts == scenario.threshold_counts
