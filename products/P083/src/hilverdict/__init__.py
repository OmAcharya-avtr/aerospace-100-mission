"""hilverdict: decide whether a hardware-in-the-loop run was timing-faithful.

The question
------------
A hardware-in-the-loop rig produces two things: a trajectory, and a log of how
long every control iteration took. Some of those iterations overran their
deadline. The question a review asks is not how many -- it is whether any of
them changed the answer, and a timing report that quotes an overrun count has
not answered it.

The three ways this package answers it, in the order it answers them
--------------------------------------------------------------------
1. :mod:`hilverdict.certificate` -- **baseline 1, the analytic certificate.**
   A closed-form upper bound on how far a miss of a given duration, holding a
   given input step, could possibly have moved the trajectory of the declared
   linearisation. A miss whose bound falls below the declared tolerance
   **cannot** have mattered, and that is a proof rather than an estimate. It
   costs two matrix exponentials per run and a logarithm per miss, and it
   disposes of the large majority of misses.
2. :mod:`hilverdict.resimulate` -- **baseline 2, direct re-simulation.** Run
   the declared nonlinear plant with the miss and without it, and measure how
   far apart the trajectories get. Slow, exact, and the reference every other
   number here is scored against. It is paid for only on the residual that
   baseline 1 leaves undecided.
3. :mod:`hilverdict.learned` -- **the learned classifier.** Gradient-boosted
   trees over cheap log features, for the case where re-simulation is
   unaffordable. Scored on **recall of consequential misses**, because
   dismissing a miss that mattered is not symmetric with re-simulating one that
   did not.

:mod:`hilverdict.clock` checks the host-to-device clock before any duration is
believed, because a drifting clock changes which iterations appear to have
missed at all and a device-clock reset makes the durations spanning it
meaningless. :mod:`hilverdict.verdict` puts the three together in that order
and returns one word per run.

The measured result
-------------------
The analytic bound wins outright, and the learned component's only defensible
role is the residual undecided set. The numbers are in
``validation/VALIDATION.md`` and in ``README.md``, and they are reported as
measured whichever way they came out.

Status and safety
-----------------
Research grade. Not flight-qualified, not certified, and not approved for
operational aerospace use. Every number in this repository is measured against
synthetic runs generated by :mod:`hilverdict.synthetic` from a declared plant;
no measurement of any real rig, flight computer or test article appears
anywhere in it.
"""

