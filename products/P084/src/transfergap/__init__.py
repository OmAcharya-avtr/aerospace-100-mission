"""transfergap: bound the sim-to-field discrepancy, and say how many more flights.

What this package is
--------------------
A digital twin predicts a quantity; a field test measures it. The difference
is the **sim-to-field gap**, and a programme that has flown fifteen paired
points wants two things from them: an honest upper bound on the gap, and the
number of additional measurements that would bring that bound to a declared
target at a declared confidence.

Both are provided three times over, at three different standings, and the
standing is printed in the same table as the number:

- :mod:`transfergap.bounds` -- **baseline 1**, distribution-free. Hoeffding's
  inequality and the Maurer-Pontil empirical Bernstein bound on the mean gap,
  Wilks' nonparametric one-sided tolerance limit and the exact normal-theory
  tolerance limit on a future gap. The sample-count requirement is inverted in
  closed form from each. Conservative, and explicit about it.
- :mod:`transfergap.resample` -- **baseline 2**, tighter under exchangeability.
  The nonparametric bootstrap and split conformal prediction.
- :mod:`transfergap.learned` -- a learned conditional discrepancy model mapping
  operating condition to the conditional gap distribution, with a conformal
  repair of its coverage.

The assumption that pays for baseline 2 is exchangeability, and
:mod:`transfergap.exchangeability` **tests** it rather than assuming it, by a
permutation test against the drift and step alternatives that a flight-test
card actually produces.

The scoring rule
----------------
Every method in this package is scored on **achieved coverage at the declared
confidence**, never on tightness. Width is reported in its own column and
never enters the verdict. The measured result at field-sample sizes of tens is
in ``validation/VALIDATION.md`` and in ``README.md``, and it is reported as
measured whichever way it came out.

Status and safety
-----------------
Research grade. Not flight-qualified, not certified, not approved for
operational aerospace use. Every number in this repository is measured against
synthetic paired records generated by :mod:`transfergap.synthetic`; no
measurement of any real aircraft, engine or test article appears anywhere in
it.
"""

