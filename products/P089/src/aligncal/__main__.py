def _observability_lines(args: argparse.Namespace) -> list[str]:
    generated = _generated(args)
    verdict = observability.assess(
        generated.record,
        required_sigma_rad=args.required_sigma,
        floor_factor=args.floor_factor,
    )
    lines = report_module.observability_lines(verdict)
    lines.append("")
    lines.append(
        "NO ESTIMATE WAS COMPUTED. The verdict above is what gates one, and it is the "
        "first output of every call in this package."
    )
    return lines


def _align_lines(args: argparse.Namespace) -> list[str]:
    generated = _generated(args)
    verdict = observability.assess(
        generated.record,
        required_sigma_rad=args.required_sigma,
        floor_factor=args.floor_factor,
    )
    lines = report_module.observability_lines(verdict)
    for name in generated.record.names:
        solution = batch.solve(generated.record, verdict, name)
        lines.append("")
        lines.extend(solution.summary()[len(verdict[name].summary()) :])
        truth = generated.truth[name]
        lines.append(
            f"  injected truth = [{', '.join(f'{c * 1e3:+.6f}' for c in truth)}] mrad "
            "(known only because this record is generated)"
        )
        observable, unobservable = benchmark.subspace_split(
            solution.theta_rad - truth, verdict[name]
        )
        lines.append(
            f"  error on the observable subspace   : "
            f"{np.linalg.norm(observable) * report_module.ARCSEC_PER_RAD:.4f} arcsec"
        )
        lines.append(
            f"  error on the unobservable subspace : "
            f"{np.linalg.norm(unobservable) * report_module.ARCSEC_PER_RAD:.4f} arcsec "
            "(carried in full by any estimator, including one that refuses)"
        )
    return lines


def _compare_lines(args: argparse.Namespace) -> list[str]:
    generated = _generated(args)
    verdict = observability.assess(
        generated.record,
        required_sigma_rad=args.required_sigma,
        floor_factor=args.floor_factor,
    )
    lines = report_module.observability_lines(verdict)
    for name in generated.record.names:
        batch_solution = batch.solve(generated.record, verdict, name)
        mekf = recursive_module.run(generated.record, verdict, name, store_history=False)
        lines.append("")
        lines.extend(
            report_module.compare_lines(batch_solution, mekf, truth_rad=generated.truth[name])
        )
    return lines


def _unobservable_lines(args: argparse.Namespace) -> list[str]:
    probe = _generated(args)
    axis = observability.dominant_rotation_axis(probe.record)
    injected = axis * (args.theta_mrad * 1.0e-3)
    generated = dataset.generate(
        profile=args.profile,
        samples=args.samples,
        rate_hz=args.rate_hz,
        amplitude=args.amplitude,
        noise_sigma=args.noise_sigma,
        n_secondaries=1,
        seed=args.seed,
        theta_rad=injected,
    )
    verdict = observability.assess(
        generated.record,
        required_sigma_rad=args.required_sigma,
        floor_factor=args.floor_factor,
    )
    name = generated.record.names[0]
    sensor = verdict[name]
    worst = sensor.degrees_of_freedom[-1]
    best = sensor.degrees_of_freedom[0]

    lines = report_module.observability_lines(verdict)
    lines.append("")
    lines.append(
        f"A misalignment of {args.theta_mrad:g} mrad was injected ENTIRELY along this "
        "record's own dominant rotation axis,"
    )
    lines.append(
        "which is the direction the record cannot support. Each estimator is now asked "
        "for that component."
    )
    lines.append("")

    truth_component = float(np.dot(injected, worst.direction))
    batch_solution = batch.solve(generated.record, verdict, name)
    batch_component = float(np.dot(batch_solution.theta_rad, worst.direction))
    batch_sigma = batch_solution.sigma_rad_in_direction(worst.direction)
    mekf = recursive_module.run(generated.record, verdict, name, store_history=False)
    mekf_component = float(np.dot(mekf.theta_rad, worst.direction))
    mekf_sigma = mekf.sigma_rad_in_direction(worst.direction)

    population = dataset.training_population(count=args.train, samples=args.samples, seed=4242)
    matrix, targets, _ = features.build_population(population)
    model = learned.LearnedEstimator(
        seed=20261029, **learned.CONFIGURATIONS[args.configuration]
    ).fit(matrix, targets)
    prediction = model.predict(features.build(generated.record, name, verdict)[None, :])
    learned_component = float(prediction.component_in_direction(worst.direction[None, :])[0])
    learned_sigma = float(prediction.sigma_in_direction(worst.direction[None, :])[0])
    learned_cross = float(prediction.sigma_in_direction(best.direction[None, :])[0])

    arcsec = report_module.ARCSEC_PER_RAD
    lines.append(
        f"{'estimator':<26s} {'claim arcsec':>14s} {'error arcsec':>14s} "
        f"{'1 sigma arcsec':>16s} {'|error|/sigma':>14s}"
    )
    lines.append(
        f"{'injected truth':<26s} {truth_component * arcsec:>14.4f} {'--':>14s} "
        f"{'--':>16s} {'--':>14s}"
    )
    rows = [
        ("batch, equations (14)-(16)", batch_component, batch_sigma),
        ("recursive MEKF (19)-(22)", mekf_component, mekf_sigma),
        (f"learned, {args.configuration}", learned_component, learned_sigma),
    ]
    for label, value, sigma in rows:
        error = abs(value - truth_component)
        ratio = "0 (refused)" if not np.isfinite(sigma) else f"{error / sigma:.4f}"
        rendered = "inf (refused)" if not np.isfinite(sigma) else f"{sigma * arcsec:.4f}"
        lines.append(
            f"{label:<26s} {value * arcsec:>14.4f} {error * arcsec:>14.4f} "
            f"{rendered:>16s} {ratio:>14s}"
        )
    lines.append("")
    lines.append(
        f"the learned estimator's reported uncertainty is {learned_sigma / learned_cross:.4f} "
        "times larger along the unobservable direction than along the best-observed one."
    )
    lines.append(
        "the analytic ratio is infinite: the batch solution withholds the direction and "
        "reports no number for it at all."
    )
    lines.append(
        "the recursive filter does return a number, and reports a one-sigma "
        f"{mekf_sigma / mekf.sigma_rad_in_direction(best.direction):.4f} times larger there "
        "than along the best-observed direction, which is its own statement of refusal."
    )
    return lines


def _benchmark_lines(args: argparse.Namespace) -> list[str]:
    train = dataset.training_population(count=args.train, samples=args.samples, seed=args.seed)
    test = dataset.training_population(
        count=args.test, samples=args.samples, seed=args.seed + 70000
    )
    train_matrix, train_targets, _ = features.build_population(train)
    test_matrix, test_targets, _ = features.build_population(test)

    sensors = []
    batch_errors = []
    map_errors = []
    for index, generated in enumerate(test):
        name = generated.record.names[0]
        verdict = observability.assess(generated.record)
        sensors.append(verdict[name])
        truth = generated.truth[name]
        batch_errors.append(batch.solve(generated.record, verdict, name).theta_rad - truth)
        map_errors.append(
            batch.solve_map(
                generated.record, verdict, name, prior_sigma_rad=1.0e-3
            ).theta_rad
            - truth
        )
        del index

    tables = [
        benchmark.score("batch (14)-(16)", np.array(batch_errors), sensors),
        benchmark.score("batch MAP (18)", np.array(map_errors), sensors),
    ]
    for configuration in sorted(learned.CONFIGURATIONS):
        model = learned.LearnedEstimator(
            seed=20261029, **learned.CONFIGURATIONS[configuration]
        ).fit(train_matrix, train_targets)
        predicted = model.predict(test_matrix)
        tables.append(
            benchmark.score(
                f"learned {configuration}", predicted.theta_rad - test_targets, sensors
            )
        )
    trivial = learned.TrivialEstimator().fit(train_matrix, train_targets)
    tables.append(
        benchmark.score(
            "trivial (mean)", trivial.predict(test_matrix).theta_rad - test_targets, sensors
        )
    )

    lines = [
        f"SHORT-RECORD BENCHMARK, {args.samples} samples per record",
        f"  training records {len(train)}, test records {len(test)}, "
        f"seeds {args.seed} and {args.seed + 70000}",
        "  all figures in milliradians; RMSE is per component, median is of the vector",
        "",
        benchmark.ScoreTable.header(),
    ]
    lines.extend(table.row() for table in tables)
    lines.append("")
    best = min(tables, key=lambda t: t.rmse_total_mrad)
    lines.append(f"lowest total RMSE: {best.label} at {best.rmse_total_mrad:.6f} mrad")
    lines.append(
        "the unobservable-subspace column is carried in full by every estimator here, "
        "including the batch solution that correctly withholds it."
    )
    return lines


def main(argv: list[str] | None = None) -> int:
    """Entry point. Returns a process exit status."""
    parser = _build_parser()
    args = parser.parse_args(argv)
    handlers = {
        "info": lambda a: _info_lines(),
        "observability": _observability_lines,
        "align": _align_lines,
        "compare": _compare_lines,
        "unobservable": _unobservable_lines,
        "benchmark": _benchmark_lines,
    }
    try:
        lines = handlers[args.command](args)
    except (ValueError, KeyError, RuntimeError) as error:
        print(f"aligncal: {error}", file=sys.stderr)
        return 2
    print("\n".join(lines))
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
