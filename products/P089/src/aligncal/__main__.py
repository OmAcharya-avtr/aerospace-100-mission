        "  (8)       the observability Gramian",
        "  (9)-(10)  the excitation second moment, and lambda_i = (W/s^2)(1 - p_i)",
        "  (11)      the noise floor a rank test on a measured Gramian must clear",
        "  (12)      the Cramer-Rao bound per degree of freedom",
        "  (13)      an independent Gershgorin and Rayleigh bracket on lambda_min",
        "  (14)-(16) the batch least-squares solution on the observable subspace",
        "  (17)      Markley's SVD solution, used as an independent cross-check",
        "  (18)      the regularised (MAP) batch variant, a biased estimator",
        "  (19)-(22) the multiplicative extended Kalman filter",
