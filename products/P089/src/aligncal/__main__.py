"""Command line for aligncal: ``python -m aligncal <command>``.

The only module in this package that prints. Each subcommand writes a report to
stdout and exits 0, or writes an actionable message to stderr and exits 2.

Every subcommand operates on a record generated by
:mod:`aligncal.dataset` with an explicit seed, because this package ships no
flight data and no sample file. The generating call is printed in the
provenance line of every report, so any number a subcommand prints can be
regenerated from what it printed.
"""

from __future__ import annotations

import argparse
import sys

import numpy as np

from . import __version__, batch, benchmark, dataset, features, learned, observability
from . import recursive as recursive_module
from . import report as report_module

_EPILOG = """
research grade: not flight-qualified, not certified, not approved for
operational aerospace use. An observable alignment is not a calibrated one.
"""


def _generated(args: argparse.Namespace) -> dataset.GeneratedRecord:
    return dataset.generate(
        profile=args.profile,
        samples=args.samples,
        rate_hz=args.rate_hz,
        amplitude=args.amplitude,
        noise_sigma=args.noise_sigma,
        n_secondaries=args.secondaries,
        seed=args.seed,
    )


def _add_record_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--profile",
        default="three_axis",
        choices=sorted(dataset.PROFILES),
        help="excitation profile of the generated record (default: three_axis)",
    )
    parser.add_argument("--samples", type=int, default=2000, help="rate samples (default: 2000)")
    parser.add_argument(
        "--rate-hz", type=float, default=100.0, dest="rate_hz", help="sampling rate in Hz"
    )
    parser.add_argument(
        "--amplitude", type=float, default=0.05, help="peak body rate in rad/s"
    )
    parser.add_argument(
        "--noise-sigma",
        type=float,
        default=2.0e-4,
        dest="noise_sigma",
        help="per-axis sensor noise one sigma in rad/s",
    )
    parser.add_argument(
        "--secondaries", type=int, default=1, help="number of secondary sensors"
    )
    parser.add_argument("--seed", type=int, default=20261029, help="generator seed")
    parser.add_argument(
        "--required-sigma",
        type=float,
        default=observability.DEFAULT_REQUIRED_SIGMA_RAD,
        dest="required_sigma",
        help="declared alignment-knowledge requirement, one sigma, rad",
    )
    parser.add_argument(
        "--floor-factor",
        type=float,
        default=observability.DEFAULT_FLOOR_FACTOR,
        dest="floor_factor",
        help="multiple of the equation (11) noise floor an eigenvalue must clear",
    )


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m aligncal",
        description=(
            "Relative sensor alignment from a rate time series, with the observability "
            "of each alignment degree of freedom reported before the estimate."
        ),
        epilog=_EPILOG,
    )
    parser.add_argument("--version", action="version", version=f"aligncal {__version__}")
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("info", help="package, equations and declared defaults")

    for name, helptext in (
        ("observability", "the observability verdict alone, with no estimate"),
        ("align", "the verdict and then the batch estimate"),
        ("compare", "batch against the recursive MEKF, per degree of freedom"),
    ):
        child = sub.add_parser(name, help=helptext, epilog=_EPILOG)
        _add_record_arguments(child)

    unobservable = sub.add_parser(
        "unobservable",
        help=(
            "inject a misalignment along the record's own rotation axis and show "
            "what each estimator says"
        ),
        epilog=_EPILOG,
    )
    _add_record_arguments(unobservable)
    unobservable.add_argument(
        "--theta-mrad",
        type=float,
        default=2.0,
        dest="theta_mrad",
        help="magnitude of the misalignment injected along the rotation axis, mrad",
    )
    unobservable.add_argument(
        "--train",
        type=int,
        default=1200,
        help="training records for the learned estimator",
    )
    unobservable.add_argument(
        "--configuration",
        default="bagged_ridge",
        choices=sorted(learned.CONFIGURATIONS),
        help="declared learned configuration to exhibit",
    )

    bench = sub.add_parser(
        "benchmark",
        help="short-record scores for every estimator, including the trivial baseline",
        epilog=_EPILOG,
    )
    bench.add_argument("--train", type=int, default=1200, help="training records")
    bench.add_argument("--test", type=int, default=300, help="test records")
    bench.add_argument(
        "--samples", type=int, default=150, help="samples per short record (default: 150)"
    )
    bench.add_argument("--seed", type=int, default=20261029, help="training seed")
    return parser


